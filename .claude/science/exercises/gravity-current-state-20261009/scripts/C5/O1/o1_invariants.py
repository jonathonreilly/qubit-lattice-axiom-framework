"""O1 check 1: invariant-tensor counts for candidate substrate symmetry groups.

For each group G acting on the 4D tangent space (index 0 = time), count the
dimension of the G-invariant subspace in:
  V      : vectors                       (dimension-3 CPT-odd terms like b_mu, a_mu, (k_AF)_mu)
  S2     : symmetric rank 2              (dimension-4 speed terms c_mu nu; metric always counts 1 if G preserves it)
  S3     : symmetric rank 3              (dimension-5 Myers-Pospelov-type)
  S4     : symmetric rank 4              (dimension-6 p^4 terms)
  MASS   : Sym^2(Sym^2)                  (h h mass forms of a symmetric 2-tensor)
  KIN    : Sym^2(R4) (x) Sym^2(Sym^2)    (q q h h two-derivative forms)
Group elements are generated by closure (finite) or tested on generators (infinite).
Exact: integer matrices, rank computed with sympy over Q.
"""
import itertools, numpy as np, sympy as sp

def closure(gens, maxn=100000):
    I = np.eye(gens[0].shape[0], dtype=int)
    seen = {I.tobytes(): I}; frontier = [I]
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                b = g @ a
                k = b.tobytes()
                if k not in seen:
                    seen[k] = b; new.append(b)
                    if len(seen) > maxn: raise RuntimeError("group too big")
        frontier = new
    return list(seen.values())

def signed_perms(n, proper_only=False):
    out = []
    for p in itertools.permutations(range(n)):
        for s in itertools.product([1, -1], repeat=n):
            M = np.zeros((n, n), dtype=int)
            for i in range(n): M[p[i], i] = s[i]
            if proper_only and round(np.linalg.det(M)) != 1: continue
            out.append(M)
    return out

def embed_space(M3, t=1):
    M = np.zeros((4, 4), dtype=int); M[0, 0] = t; M[1:, 1:] = M3; return M

# symmetric-tensor bases ------------------------------------------------------
def sym_basis(n, k):
    """basis of Sym^k(R^n) inside (R^n)^{(x)k}, as columns (multisets)."""
    cols = []
    for ms in itertools.combinations_with_replacement(range(n), k):
        v = np.zeros(n ** k)
        for perm in set(itertools.permutations(ms)):
            idx = 0
            for i in perm: idx = idx * n + i
            v[idx] = 1
        cols.append(v)
    return np.array(cols).T

def rep_on(B, M, k):
    """matrix of M^{(x)k} restricted to span(B) (B has orthogonal columns)."""
    Mk = M
    for _ in range(k - 1): Mk = np.kron(Mk, M)
    # coordinates: B^+ Mk B
    Bp = np.linalg.pinv(B)
    return np.rint(Bp @ Mk @ B * 1).astype(float), Bp @ Mk @ B

def inv_dim(mats):
    """dim of common fixed space of a list of square matrices (float, exact-ish via sympy)."""
    n = mats[0].shape[0]
    A = np.vstack([m - np.eye(n) for m in mats])
    A = sp.Matrix(np.round(A * 6).astype(int))  # entries are multiples of 1/2 or 1/6 at worst
    return n - A.rank()

def counts(G, label):
    S1 = np.eye(4); S2 = sym_basis(4, 2); S3 = sym_basis(4, 3); S4 = sym_basis(4, 4)
    res = {}
    for name, B, k in [("V", S1, 1), ("S2", S2, 2), ("S3", S3, 3), ("S4", S4, 4)]:
        mats = [np.linalg.pinv(B) @ (np.kron(*( [g] * 2)) if k == 2 else (g if k == 1 else (np.kron(np.kron(g, g), g) if k == 3 else np.kron(np.kron(g, g), np.kron(g, g))))) @ B for g in G]
        res[name] = inv_dim(mats)
    # MASS and KIN: build rep of g on Sym2(R4) (10-dim), then Sym2 of it (55) and Sym2(R4) (x) Sym2(Sym2)
    B2 = S2 / np.linalg.norm(S2, axis=0)
    B55 = sym_basis(10, 2)
    massm, kinm = [], []
    for g in G:
        R10 = B2.T @ np.kron(g, g) @ B2
        R55 = np.linalg.pinv(B55) @ np.kron(R10, R10) @ B55
        massm.append(R55)
        kinm.append(np.kron(R10, R55))
    res["MASS"] = inv_dim_float(massm)
    res["KIN"] = inv_dim_float(kinm)
    print(f"{label:58s} |G|={len(G):>5}  " + "  ".join(f"{k}={v}" for k, v in res.items()))
    return res

def inv_dim_float(mats, tol=1e-9):
    n = mats[0].shape[0]
    # average projector for finite groups is cheaper: P = mean(g); dim = trace(P)
    P = sum(mats) / len(mats)
    return int(round(np.trace(P)))

