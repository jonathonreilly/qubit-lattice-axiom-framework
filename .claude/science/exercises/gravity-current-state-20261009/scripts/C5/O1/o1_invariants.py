    # continuum O(4) reference for MASS/KIN: Haar average approximated by many random rotations
    rng = np.random.default_rng(1)
    def rand_O4():
        q, r = np.linalg.qr(rng.normal(size=(4, 4))); return q * np.sign(np.diag(r))
    Rs = [rand_O4() for _ in range(4000)]
    B2 = sym_basis(4, 2); B2 = B2 / np.linalg.norm(B2, axis=0); B55 = sym_basis(10, 2); B55p = np.linalg.pinv(B55)
