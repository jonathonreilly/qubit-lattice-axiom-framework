"""R18-2 probe (c): can a Planck-suppressed phi^6 term, or the lattice's own dispersion, make the EW vacuum
the global minimum?  Inputs RECALLED (PREREG.md).  rho_Lambda RECALLED = 2.5e-47 GeV^4."""
import numpy as np
from scipy.optimize import brentq
from smrge import run, lam_eff, MP, MPRED

RHO_L = 2.5e-47
Mt0, Mh0, as0 = 172.57, 125.20, 0.1180
T, Y = run(Mt0, Mh0, as0, mu_max=MP * 1.01, npts=3000)
le, _ = lam_eff(T, Y)
h = np.exp(T)
msk = (h >= 1e3) & (h <= MP)

print("c1. Minimal phi^6 coefficient: V = lam_eff(h) h^4/4 + c h^6/M^2 >= V_EW (~ -1.2e8 GeV^4, negligible) for all h <= M_P")
for M, lab in [(MP, "M = 1/a = M_P"), (MPRED, "M = reduced M_P")]:
    req = -le[msk] * M**2 / (4 * h[msk]**2)
    i = np.argmax(req)
    cmin = req[i]
    print("   %-16s c_min = %.3e at h = %.3e GeV (instability scale h_I = %.2e); equivalent unit-coefficient scale"
          " Lambda_6 = M/sqrt(c_min) = %.3e GeV" % (lab, cmin, h[msk][i], h[msk][np.argmax(le[msk] < 0)], M / np.sqrt(cmin)))

print()
print("c2. With an O(1) Planck-suppressed coefficient the potential is bounded below but a deeper minimum remains:")
for c in [0.1, 1.0, 10.0, 100.0]:
    V = le[msk] * h[msk]**4 / 4 + c * h[msk]**6 / MP**2
    j = np.argmin(V)
    print("   c = %6.1f : V_min = %+.3e GeV^4 at h = %.3e GeV (h a = %.3f) ; Lambda_tilde/rho_Lambda = kappa(V_EW - E0)/rho_L = %.2e"
          % (c, V[j], h[msk][j], h[msk][j] / MP, -V[j] / RHO_L))
print("   (h a ~ O(0.1-1) means this minimum sits where the EFT itself is at the lattice scale: a reading, not a computation)")

print()
print("c3. The lattice's own dispersion: dimension-6 coefficient generated by the one-loop zero-point sum of a field")
print("    with field-dependent mass M = y h/sqrt2, lattice minus continuum, Delta V ~ c_lat h^6 a^2 (a = 1/M_P).")
# third derivative in M^2 of V = -(n/2) int d^3k/(2pi)^3 sqrt(eps^2+M^2)  (fermion sign; boson: +(n/2) per real dof... sign flips)
#   d^3V/d(M^2)^3 = -(n/2)(3/8) int (eps^2+M^2)^(-5/2)
rng = np.random.default_rng(1)


def I_box_minus_cont(Ma):
    """int_cube (k^2+M^2)^(-5/2) - int_R3 (k^2+M^2)^(-5/2), in lattice units, /(2pi)^3: = -int_{R3 minus cube}."""
    # outside-cube integral: radial integral over directions; for direction n, the cube boundary is at r_b = pi/max|n_i|
    N = 400000
    v = rng.normal(size=(N, 3))
    v /= np.linalg.norm(v, axis=1)[:, None]
    rb = np.pi / np.abs(v).max(axis=1)
    # int_{rb}^inf r^2 (r^2+M^2)^(-5/2) dr = [r^3/(3 M^2 (r^2+M^2)^(3/2))]_{rb}^{inf} = 1/(3M^2) - rb^3/(3M^2(rb^2+M^2)^1.5)
    M2 = Ma**2
    if Ma < 1e-3:
        radial = 1 / (2 * rb**2)  # M -> 0 limit: int_rb^inf r^-3 dr
    else:
        radial = 1 / (3 * M2) - rb**3 / (3 * M2 * (rb**2 + M2)**1.5)
    return -4 * np.pi * radial.mean() / (2 * np.pi)**3


def I_sin_minus_cont(Ma, ngrid=160):
    """Nearest-neighbour boson dispersion eps^2 = sum 4 sin^2(k_i/2): int_BZ (eps^2+M^2)^(-5/2) - int_R3 (k^2+M^2)^(-5/2).
    Computed as the cube part with the continuum integrand subtracted pointwise plus the outside-cube piece."""
    k = (np.arange(ngrid) + 0.5) / ngrid * 2 * np.pi - np.pi
    KX, KY, KZ = np.meshgrid(k, k, k, indexing='ij')
    e2 = 4 * (np.sin(KX / 2)**2 + np.sin(KY / 2)**2 + np.sin(KZ / 2)**2)
    k2 = KX**2 + KY**2 + KZ**2
    M2 = Ma**2
    f = (e2 + M2)**-2.5 - (k2 + M2)**-2.5
    inside = f.mean() * (2 * np.pi)**3 / (2 * np.pi)**3
    return inside + I_box_minus_cont(Ma)


for Ma in [1e-1, 3e-2, 1e-2]:
    print("   box law (exact relativistic inside the cube): Ma = %.0e : I = %+.5e" % (Ma, I_box_minus_cont(Ma)))
J0 = -I_box_minus_cont(1e-6)
print("   box law, M -> 0: J = -I = %.5e  (bound: outside inscribed sphere gives 1/(4 pi^4) = %.5e)" % (J0, 1 / (4 * np.pi**4)))
for Ma in [0.3, 0.1, 0.05]:
    print("   nearest-neighbour (sin) boson: Ma = %.2f : I = %+.4e  (IR-log grows like ln(1/Ma) as Ma -> 0: a^2 M^6 ln term)" % (Ma, I_sin_minus_cont(Ma)))
# coefficient: Delta V ~ (1/6) d3V M^6 ; d3V = -(n/2)(3/8) I a^2 for fermions, +(n/2)(3/8) I a^2 for bosons (per real dof n)
yt_hI = np.interp(np.log(1e11), T, Y[3])
n_top = 12
c_box_top = (1 / 6) * (n_top / 2) * (3 / 8) * J0 * (yt_hI**2 / 2)**3   # -(n/2)(3/8)(-J) = +, fermion
print("   top (n = 12, y_t(1e11) = %.3f), box law: c_lat = (1/6)(n/2)(3/8) J (y^2/2)^3 = %+.2e (stabilizing sign)" % (yt_hI, c_box_top))
# sin-law with log: use |I| at the physical Ma ~ y h_I a; extrapolate the log
Ivals = [(Ma, I_sin_minus_cont(Ma)) for Ma in [0.2, 0.1, 0.05]]
sl = (Ivals[-1][1] - Ivals[0][1]) / np.log(Ivals[0][0] / Ivals[-1][0])
Ma_phys = yt_hI * 1.8e11 / np.sqrt(2) / MP
I_phys = Ivals[-1][1] + sl * np.log(0.05 / Ma_phys)
c_sin = (1 / 6) * (n_top / 2) * (3 / 8) * abs(I_phys) * (yt_hI**2 / 2)**3
print("   sin-law, log-extrapolated to the physical Ma = y h_I a/sqrt2 = %.2e: |I| ~ %.2e -> |c_lat| ~ %.2e" % (Ma_phys, abs(I_phys), c_sin))
print("   compare c_min(M = 1/a) from c1: lattice dimension-6 terms fall short by a factor >= %.1e" % (
    (-le[msk] * MP**2 / (4 * h[msk]**2)).max() / max(c_box_top, c_sin)))

print()
print("c4. Field-range reading: if the qubit-composite Higgs amplitude were bounded by h_max, stability needs h_max < h_I:")
hI = h[msk][np.argmax(le[msk] < 0)]
print("   h_I = %.2e GeV -> h_max a < %.1e (a stipulated small number, not a lattice-scale O(1) term)" % (hI, hI / MP))
