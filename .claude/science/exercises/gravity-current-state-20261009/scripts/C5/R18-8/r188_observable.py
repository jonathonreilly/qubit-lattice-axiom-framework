"""C5 R18-8 (D): observable form of the anomaly and its size.

Boost orbit of the asymptotic charges (degree 2, Vlasov form): the flow generated by K_b moves each quantum by
  dk_b/deta = eps(k)   (so dE/deta = P_b, dP_c/deta = delta_bc E + Delta_cb, the anomalous bracket).
Far-field (ADM) mass  M^2 = E^2 - |P|^2,  E = sum eps, P = sum P(k)  (on shell the ADM surface charges equal these).
Prediction (proved from the algebra): at a rest frame (P = 0)  d^2 M^2/deta^2 = -2 (E + Q_bb) Q_bb  and the
centre-of-energy velocity is V = (1 + Q_bb/E) eta + O(eta^2), so  M(V) = M [1 - Q_bb V^2 / (2 (E + Q_bb)) + O(V^4)].
(1) single quanta: box (Q = 0) control and edge quanta;  (2) composite bodies;  (3) the Lie algebra generated by
the charges does not close on a finite set (rank of nested K-brackets);  (4) thermal edge fraction and size.
"""
import os, sys
os.environ.setdefault("OMP_NUM_THREADS", "2")
import numpy as np
from scipy.integrate import solve_ivp
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sublum_copy import SymS, SymG

M0 = 0.3
S14, G14 = SymS(1.4), SymG(1.4)
LAWS = {"S(1.4)": (lambda k: S14.s(k)**2, lambda k: 2*S14.s(k)*S14.ds(k), lambda k: 2*(S14.ds(k)**2 + S14.s(k)*S14.d2s(k))),
        "G(1.4)": (G14.g, G14.dg, G14.d2g)}
lines = []
def pr(s):
    print(s); lines.append(s)

def charges(law, K):            # K: (n,3) array of momenta
    u, up, upp = LAWS[law]
    eps = np.sqrt(M0**2 + u(K).sum(1)); P = 0.5*up(K); Q = eps[:, None]*(0.5*upp(K) - 1.0)
    return eps, P, Q

def orbit(law, K0, b, etas):
    n = K0.shape[0]
    def rhs(t, y):
        K = y.reshape(n, 3); eps, _, _ = charges(law, K); d = np.zeros_like(K); d[:, b] = eps; return d.ravel()
    sol = solve_ivp(rhs, (0, etas[-1]), K0.ravel(), t_eval=etas, rtol=1e-12, atol=1e-13, method="DOP853")
    out = []
    for i in range(len(etas)):
        K = sol.y[:, i].reshape(n, 3); eps, P, Q = charges(law, K)
        E, Pt, Qt = eps.sum(), P.sum(0), Q.sum(0)
        out.append((etas[i], E, Pt, Qt, E**2 - Pt @ Pt))
    return out

pr("(D1) single quanta: far-field M^2 = E^2 - P^2 along the K_b orbit (b = boost axis)")
cases = [("G(1.4)", (0.0, 0.0, 0.0), 0, "box rest"), ("G(1.4)", (np.pi, 0.0, 0.0), 0, "edge corner, boost along edge axis"),
         ("G(1.4)", (np.pi, 0.0, 0.0), 1, "edge corner, boost along box axis"), ("G(1.4)", (2.0, 0.0, 0.0), 0, "edge k1=2.0 (moving)"),
         ("S(1.4)", (0.0, 0.0, 0.0), 0, "box rest"), ("S(1.4)", (1.57, 0.0, 0.0), 0, "strip k1=1.57")]
for law, k0, b, lab in cases:
    etas = np.array([0.0, 0.5, 1.0, 2.0, 2.5, 3.0, 4.0])
    o = orbit(law, np.array([k0]), b, etas)
    pr("  %s %-36s M^2(eta=%s) = %s" % (law, lab, ",".join("%.1f" % t for t in etas), " ".join("%.6f" % t[4] for t in o)))
    _, P, Q = charges(law, np.array([k0]))
    pr("      at eta=0: Q_bb = %+.5f, E = %.5f, |P| = %.3e" % (Q[0, b], o[0][1], np.linalg.norm(P)))

pr("(D2) composite bodies at rest (pairs +-k so P = 0); second derivative of M^2 vs -2(E+Q_bb)Q_bb; V and dM/M")
rng = np.random.default_rng(18)
for law in LAWS:
    for nedge in (0, 1, 4):
        kb = rng.normal(scale=0.25, size=(40, 3)); edges = np.array([[2.6, 0.1, -0.4], [2.0, 0.3, 0.2], [1.6, 1.6, 0.0], [2.9, -0.2, 0.5]])[:nedge]
        if law == "S(1.4)":
            edges = np.array([[1.6, 1.6, 0.0], [1.57, 0.2, 0.1], [1.5, -0.3, 0.4], [1.62, 0.0, 0.0]])[:nedge]
        K0 = np.vstack([kb, -kb, edges, -edges])
        for b in (0, 2):
            h = 1e-3
            o = orbit(law, K0, b, np.array([0.0, h, 2*h]))
            _, P, Q = charges(law, K0); E = o[0][1]; Qbb = Q.sum(0)[b]
            d2 = (o[2][4] - 2*o[1][4] + o[0][4])/h**2
            # larger eta: V and fractional mass shift vs prediction
            pr("  %s edges=%d b=%d  E=%9.4f  Q_bb=%+9.4f  d2M2=%+.6e  pred -2(E+Q)Q=%+.6e" % (law, 2*nedge, b, E, Qbb, d2, -2*(E + Qbb)*Qbb))
            for eta in (0.02, 0.002):
                o2 = orbit(law, K0, b, np.array([0.0, eta]))
                V = o2[1][2][b]/o2[1][1]; dM = np.sqrt(o2[1][4])/np.sqrt(o2[0][4]) - 1
                pred = -Qbb*V**2/(2*(E + Qbb))
                pr("      eta=%.3f  V=%+.6e (1+Q/E)eta=%+.6e   dM/M=%+.5e  pred -Q V^2/(2(E+Q))=%+.5e" % (eta, V, (1 + Qbb/E)*eta, dM, pred))

# (D1b) periodicity of the single-quantum K-orbit: dk_b/deta = eps > 0 on a circle => period T = oint dk/eps
for law in LAWS:
    u = LAWS[law][0]; kk = np.linspace(-np.pi, np.pi, 200001); e = np.sqrt(M0**2 + u(kk))
    T = np.trapezoid(1/e, kk)
    o = orbit(law, np.array([[0.0, 0.0, 0.0]]), 0, np.array([0.0, T]))
    pr("  %s: K-orbit period oint dk/eps = %.6f; after one period (E, P_b) = (%.6f, %+.2e) vs start (%.6f, %+.2e)" % (law, T, o[1][1], o[1][2][0], o[0][1], o[0][2][0]))
pr("(D3) closure test: span of k-functions generated from {1, eps, P_b} by ad_K: g -> eps dg/dk_b (axis b = 0, k2 = k3 = 0.3)")
k = np.linspace(-np.pi, np.pi, 4001)[:-1]
for law in LAWS:
    u, up, upp = LAWS[law]
    eps = np.sqrt(M0**2 + 2*u(np.array([0.3]))[0] + u(k)); P = 0.5*up(k)
    D = lambda g: eps*np.gradient(g, k, edge_order=2)
    gens = [np.ones_like(k), eps, P]; g = P.copy(); ranks = []
    for n in range(6):
        g = D(g); gens.append(g)
        A = np.array(gens); s = np.linalg.svd(A/np.linalg.norm(A, axis=1, keepdims=True), compute_uv=False)
        ranks.append(int(np.sum(s > 1e-8*s[0])))
    Delta = eps*(0.5*upp(k) - 1)
    A = np.array([np.ones_like(k), eps, P]); coef, res, *_ = np.linalg.lstsq(A.T, Delta, rcond=None)
    rel = np.linalg.norm(A.T @ coef - Delta)/np.linalg.norm(Delta)
    pr("  %s: Delta in span{1, eps, P}? relative residual %.3f (0 would mean a redefinable/central term);" % (law, rel))
    pr("      rank of {1, eps, P, (eps d)^1 P, ..., (eps d)^n P}, n = 1..6: %s (Poincare closure would stop at 3)" % ranks)

kz = np.linspace(-np.pi, np.pi, 400001)
pr("(D4a) per-quantum, per-axis defect ratio |Q_bb|/eps = |P_b' - 1| over the whole zone (4e5-point scan): S(1.4) max %.4f, G(1.4) max %.4f" % (
    np.max(np.abs(S14.ds(kz)**2 + S14.s(kz)*S14.d2s(kz) - 1)), np.max(np.abs(0.5*G14.d2g(kz) - 1))))
pr("(D4) size: thermal edge fraction and the far-field mass shift for the Earth's CMB speed V = 1.2335e-3")
GeV_per_inv_a = 1.22089e19          # a = l_P (open, AX:189-190)
for floor, lab in ((1.400, "m=0 floor 1.400/a"), (1.431782, "m=0.3 floor 1.431782/a")):
    for T_GeV, tl in ((2.348e-13, "T_CMB"), (1e3, "1 TeV"), (1e16, "1e16 GeV"), (1e18, "1e18 GeV")):
        x = floor*GeV_per_inv_a/T_GeV
        # Boltzmann weight; prefactor (phase space ~ x^3 relative to the bulk) adds log10(x^3) at most
        l10 = -x/np.log(10) + 3*np.log10(x)
        pr("  %-24s %-9s  log10(edge fraction) <= %.4g ;  log10|dM/M| <= %.4g (|Q/E| per edge quantum <= 40 assumed)" % (
            lab, tl, l10, l10 + np.log10(40*1.2335e-3**2/2)))
open(os.path.splitext(os.path.abspath(__file__))[0] + ".out", "w").write("\n".join(lines) + "\n")
