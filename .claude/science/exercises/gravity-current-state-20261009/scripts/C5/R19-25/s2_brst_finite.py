    T = [np.kron(X, np.eye(d2)) for X in A] + [np.kron(np.eye(d1), X) for X in B]
    nil, dims = ce_cohomology(T, f6)
    print(f"  su(2)+su(2) on V_{S1} x V_{S2}: |Q^2| = {nil:.1e}; dim H^n, n=0..6: {dims}")

