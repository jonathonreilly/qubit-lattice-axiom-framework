"""C5 R3-2: count invariant quadratic forms for a symmetric tensor h under
(a) W(B4) on Z^4 (K1 control), (b) the axioms' proper cubic group on Z^3 x R,
(c) Gamma_{L7} = integral Lorentz group of Q7 = -7 n0^2 + n1^2 + n2^2 + n3^2
    (subgroup generated by spatial signed permutations, time flip, and the
    boost gamma with (n0,n1) block [[8,3],[21,8]]),
(d) its proper orthochronous part only, (e) the Lorentz Lie algebra so(1,3).

Spaces (all contravariant coefficient tensors, pairing with covariant h, q):
  mass  : Sym^2(Sym^2 V)                  dim 55
  one-d : V (x) Lambda^2(Sym^2 V)          dim 180  (i q_a A^a(h,h'), A antisym)
  kin   : Sym^2 V (x) Sym^2(Sym^2 V)       dim 550
Exact ranks: Gaussian elimination mod two primes on integer generator matrices
(lattice coordinates).  Float cross-check: SVD in orthonormal coordinates.
Then: gauge-invariant subspace, TT-restriction ranks, E_g/T_2g split.
"""
import itertools
import numpy as np

np.set_printoptions(linewidth=140)
PRIMES = [2147483647, 1000000007]


def sym_basis(n):
    return [(a, b) for a in range(n) for b in range(a, n)]


def asym_basis(n):
    return [(a, b) for a in range(n) for b in range(a + 1, n)]


def rep_sym2(M):
    """Action S -> M S M^T on symmetric matrices, coords = upper triangle."""
    n = M.shape[0]
    B = sym_basis(n)
    R = np.zeros((len(B), len(B)), dtype=object)
    for j, (a, b) in enumerate(B):
        S = np.zeros((n, n), dtype=object)
        S[a, b] = 1
        S[b, a] = 1
        T = M.dot(S).dot(M.T)
        for i, (c, d) in enumerate(B):
            R[i, j] = T[c, d]
    return R


def rep_asym2(M):
    n = M.shape[0]
    B = asym_basis(n)
    R = np.zeros((len(B), len(B)), dtype=object)
    for j, (a, b) in enumerate(B):
        S = np.zeros((n, n), dtype=object)
        S[a, b] = 1
        S[b, a] = -1
        T = M.dot(S).dot(M.T)
        for i, (c, d) in enumerate(B):
            R[i, j] = T[c, d]
    return R


def kron(A, B):
    return np.kron(A, B)


def reps(M):
    """Return the three representation matrices for group element M."""
    R2 = rep_sym2(M)            # Sym^2 V, 10x10
    mass = rep_sym2(R2)         # Sym^2(Sym^2 V), 55x55
    oned = kron(M, rep_asym2(R2))   # V (x) Lambda^2(Sym^2V), 180
    kin = kron(R2, mass)        # Sym^2V (x) Sym^2(Sym^2V), 550
    return {"mass": mass, "oned": oned, "kin": kin}


def rank_mod_p(A, p):
    A = np.array(A % p, dtype=np.int64)
    rows, cols = A.shape
    r = 0
    for c in range(cols):
        if r == rows:
            break
        piv = None
        nz = np.nonzero(A[r:, c])[0]
        if len(nz) == 0:
            continue
        piv = r + nz[0]
        if piv != r:
            A[[r, piv]] = A[[piv, r]]
        inv = pow(int(A[r, c]), p - 2, p)
        A[r] = (A[r] * inv) % p
        col = A[:, c].copy()
        col[r] = 0
        nzr = np.nonzero(col)[0]
        if len(nzr):
            A[nzr] = (A[nzr] - (col[nzr, None] * A[r][None, :]) % p) % p
        r += 1
    return r


def invariant_dim_exact(gens, key):
    blocks = []
    for M in gens:
        R = reps(M)[key]
        blocks.append(R - np.eye(R.shape[0], dtype=object))
    A = np.vstack(blocks)
    n = A.shape[1]
    ranks = []
    for p in PRIMES:
        Ap = np.array([[int(x) % p for x in row] for row in A], dtype=np.int64)
        ranks.append(rank_mod_p(Ap, p))
    return n - ranks[0], n - ranks[1]


# ---------------------------------------------------------------- groups
def perm_matrix(perm, signs=None):
    n = len(perm)
    M = np.zeros((n, n), dtype=object)
    for i, j in enumerate(perm):
        M[j, i] = 1 if signs is None else signs[i]
    return M


I4 = np.eye(4, dtype=object)

# (a) W(B4): adjacent transpositions of 4 coords and one sign flip
WB4 = [perm_matrix([1, 0, 2, 3]), perm_matrix([0, 2, 1, 3]),
       perm_matrix([0, 1, 3, 2]), perm_matrix([0, 1, 2, 3], [-1, 1, 1, 1])]


def spatial(M3):
    M = np.eye(4, dtype=object)
    M[1:, 1:] = M3
    return M


Rz = np.array([[0, -1, 0], [1, 0, 0], [0, 0, 1]], dtype=object)
Rx = np.array([[1, 0, 0], [0, 0, -1], [0, 1, 0]], dtype=object)
P3 = np.array([[-1, 0, 0], [0, -1, 0], [0, 0, -1]], dtype=object)
Tflip = perm_matrix([0, 1, 2, 3], [-1, 1, 1, 1])

