def rep_sym2_f(M):
    n = M.shape[0]
    B = sym_basis(n)
    R = np.zeros((len(B), len(B)))
    for j, (a, b) in enumerate(B):
        S = np.zeros((n, n))
        S[a, b] = 1
        S[b, a] = 1
        T = M.dot(S).dot(M.T)
        for i, (c, d) in enumerate(B):
            R[i, j] = T[c, d]
    return R


def reps_f(M):
    R2 = rep_sym2_f(M)
    mass = rep_sym2_f(R2)
    kin = np.kron(R2, mass)
    return R2, mass, kin


def lie_rep(X, which):
    """Infinitesimal rep: d/dt rep(exp(tX)) at t=0, by finite symmetric diff."""
    from scipy.linalg import expm
    t = 1e-6
    Rp = reps_f(expm(t * X))
    Rm = reps_f(expm(-t * X))
    idx = {"R2": 0, "mass": 1, "kin": 2}[which]
    return (Rp[idx] - Rm[idx]) / (2 * t)


def nullspace(A, tol=1e-8):
    u, s, vt = np.linalg.svd(A)
    smax = s[0] if len(s) else 1.0
    rank = int((s > tol * smax).sum())
    return vt[rank:].T, s


def invariant_space_f(gens, key, lie=None):
    blocks = []
    idx = {"mass": 1, "kin": 2}[key]
    for M in gens:
        R = reps_f(M)[idx]
        blocks.append(R - np.eye(R.shape[0]))
    if lie is not None:
        for X in lie:
            blocks.append(lie_rep(X, key))
    A = np.vstack(blocks)
    N, s = nullspace(A, tol=1e-9)
    return N, s


# Lorentz Lie algebra generators (orthonormal frame): boosts K_i, rotations J_i
def lorentz_gens():
    gens = []
    for i in range(1, 4):
        K = np.zeros((4, 4))
        K[0, i] = K[i, 0] = 1.0
        gens.append(K)
    for i, j in [(1, 2), (2, 3), (1, 3)]:
        J = np.zeros((4, 4))
        J[i, j] = -1.0
        J[j, i] = 1.0
        gens.append(J)
    return gens


