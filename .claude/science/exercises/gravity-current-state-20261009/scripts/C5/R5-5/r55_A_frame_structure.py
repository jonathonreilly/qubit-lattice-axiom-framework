"""R5-5 (A): how fast does R4-1's per-realization deviation change with the frame?
Reuses R4-1's saved shell sums (npz, allow_pickle=False). Frames are regenerated by replaying R4-1's RNG
(r41_B_shell_sums.py:65-76) and checked against the saved etas. For each frame we get the observer 4-velocity in lattice
Minkowski coordinates u = G^{-1} e0, and pairwise hyperbolic distances cosh d = -<u,u'> (an upper bound on the quotient distance).
Structure function: SF(d) = < (eps(u)-eps(u'))^2 > / (2 Var eps), eps = (B_g phi - Bbar phi)/|box phi|  (R4-1's relative deviation).
SF -> 1 means decorrelated frames; SF ~ (d/xi_F)^2 at small d defines a frame-correlation length xi_F.
"""
import numpy as np, sys
from scipy.special import k1
R41 = sys.argv[1]
def frames(NF, eta_max, seed, etas_saved):
    rng = np.random.default_rng(seed); us = []
    def boost(eta, nhat):
        nhat = nhat/np.linalg.norm(nhat); Bm = np.eye(4)
        Bm[0, 0] = np.cosh(eta); Bm[0, 1:] = Bm[1:, 0] = np.sinh(eta)*nhat
        Bm[1:, 1:] += (np.cosh(eta)-1)*np.outer(nhat, nhat); return Bm
    def randrot(rng):
        q, r = np.linalg.qr(rng.normal(size=(3, 3))); q *= np.sign(np.diag(r))
        if np.linalg.det(q) < 0: q[:, 0] *= -1
        R4 = np.eye(4); R4[1:, 1:] = q; return R4
    for f in range(NF):
        while True:
            e = rng.uniform(0, eta_max)
            if rng.uniform() < (np.sinh(e)/np.sinh(eta_max))**2: break
        if f == 0: e = 0.0
        assert abs(e - etas_saved[f]) < 1e-12, (f, e, etas_saved[f])
        G = boost(e, np.array([0, 0, 1.0])) @ randrot(rng)
        us.append(np.linalg.inv(G) @ np.array([1.0, 0, 0, 0]))
    return np.array(us)

def divided_diff(shells, M, Cm, mv):
    g = np.zeros(M)
    for i, mi in enumerate(shells):
        g[mi-1] = 1.0/np.prod([mi - mj for j, mj in enumerate(shells) if j != i])
    nrm = (np.pi/16)*np.sum(g*mv**2*np.log(mv)); g = -g/nrm
    return g/np.where(Cm > 0, Cm, np.inf), g
def smooth_f(L, M, Cm, mv):
    x = mv/L**2; base = np.exp(-x); cols = np.stack([base*x**j for j in range(4)], 1); G = cols*Cm[:, None]
    A = np.stack([G.T @ mv**k for k in range(3)] + [G.T @ (mv**2*np.log(mv))]); b = np.array([0, 0, 0, -16/np.pi])
    coef = np.linalg.lstsq(A, b, rcond=None)[0]; g = G @ coef
    nrm = (np.pi/16)*np.sum(g*mv**2*np.log(mv)); g = -g/nrm
    return g/np.where(Cm > 0, Cm, np.inf), g

for fn, seed, eta_max in ((f"{R41}/r41_B_M96_seed7_eta1.0.npz", 7, 1.0), (f"{R41}/r41_B_M96_seed23_eta0.6.npz", 23, 0.6)):
    d = np.load(fn, allow_pickle=False); S = d['S']; I = d['I']; ells = d['ells']; C = d['C']; etas = d['etas']
    NF, nl, M = S.shape; mv = np.arange(1, M+1).astype(float); Cm = C[1:M+1]
    us = frames(NF, eta_max, seed, etas)
    mink = lambda a, b: -a[..., 0]*b[..., 0] + (a[..., 1:]*b[..., 1:]).sum(-1)
    ch = -mink(us[:, None, :], us[None, :, :]); ch = np.maximum(ch, 1.0); D = np.arccosh(ch)
    iu = np.triu_indices(NF, 1); dd = D[iu]
    print(f"\n#### {fn.split('/')[-1]}: {NF} frames, eta_max={eta_max}; pair distances d in [{dd.min():.3f}, {dd.max():.3f}], median {np.median(dd):.3f}")
    kernels = {"4-shell {1,2,3,4}": divided_diff([1, 2, 3, 4], M, Cm, mv), "4-shell {1,2,4,7}": divided_diff([1, 2, 4, 7], M, Cm, mv),
               "smooth-f L=2": smooth_f(2.0, M, Cm, mv), "smooth-f L=3": smooth_f(3.0, M, Cm, mv)}
    bins = [0, 0.25, 0.5, 0.75, 1.0, 1.5, 2.5]
    for name, (f, g) in kernels.items():
        print(f"  kernel {name}")
        print("     l   rms eps    sd eps   | SF(d) in bins " + " ".join(f"[{bins[i]},{bins[i+1]})" for i in range(len(bins)-1)) + " | xi_F (fit SF=(d/xi)^2, d<0.5)")
        for j, l in enumerate(ells):
            if l < 4: continue
            box = 2.0/l**2
            eps = (S[:, j, :] @ f - np.sum(g*I[j]))/box
            v = eps.var()
            sf = (eps[:, None] - eps[None, :])[iu]**2/(2*v)
            row = []
            for i in range(len(bins)-1):
                k = (dd >= bins[i]) & (dd < bins[i+1])
                row.append(f"{sf[k].mean():6.3f}({k.sum():3d})" if k.sum() else "   -     ")
            k = dd < 0.5
            xi = np.sqrt(np.sum(dd[k]**4)/np.sum(dd[k]**2*sf[k])) if k.sum() > 3 else np.nan
            print(f"  {l:5.1f}  {np.sqrt(np.mean(eps**2)):9.3e} {eps.std():9.3e} | " + " ".join(row) + f" | {xi:.3f}")
