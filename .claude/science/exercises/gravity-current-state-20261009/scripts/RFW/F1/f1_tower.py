"""F1 part 3: gauging the cos k defect -> infinite tower.

The Lie algebra generated by the Killing-sector matter generators {F_rho, L_J} (mod trivial)
contains the multiplication operators by the functions in
     Fspace = span{ W_J^n f_rho : n >= 0 },   W_J = (J f).grad  (first-moment rotation flow).
Any finite-field-content extension has a finite-dimensional Killing algebra K, and P~ = 0 makes
X: K -> Sym/Triv a Lie homomorphism whose image contains F, L, hence Fspace.  So dim Fspace = inf
excludes finite field content.

(a) exact rank growth of Fspace (functions of k0,k1 only for J in the (0,1) plane; such
    functions restrict injectively to the Z^4 shell, so the count is also the count mod A):
    K2 scalar f = sin k, K2 fermion f = sin(2k)/2, Hamiltonian Z^3 scalar (C3: f = grad u, same).
(b) the flow of W on the real (k0,k1) torus is the Hamiltonian flow of u2 = cos k0 + cos k1;
    its orbit period T(E) varies with E, so no finite-dimensional W-invariant space can
    contain f (a T(E)-periodic exponential polynomial with fixed exponents has constant period).
"""
import sympy as sp
from fractions import Fraction
import numpy as np
from scipy.integrate import solve_ivp

# trig polynomials in k0,k1 as dict {(n0,n1): complex Fraction pair}
def mul(a, b):
    out = {}
    for (n, ca) in a.items():
        for (m, cb) in b.items():
            key = (n[0]+m[0], n[1]+m[1])
            re = ca[0]*cb[0] - ca[1]*cb[1]; im = ca[0]*cb[1] + ca[1]*cb[0]
            o = out.get(key, (Fraction(0), Fraction(0)))
            out[key] = (o[0]+re, o[1]+im)
    return {k: v for k, v in out.items() if v != (0, 0)}
def add(a, b, s=1):
    out = dict(a)
    for k, v in b.items():
        o = out.get(k, (Fraction(0), Fraction(0)))
        out[k] = (o[0]+s*v[0], o[1]+s*v[1])
    return {k: v for k, v in out.items() if v != (0, 0)}
def deriv(a, i):  # d/dk_i e^{i n.k} = i n_i e^{...}
    return {k: (-k[i]*v[1], k[i]*v[0]) for k, v in a.items() if k[i] != 0}
def sin_(i, mult=1):  # sin(mult*k_i) = (e^{i m k} - e^{-i m k})/(2i)
    n = [0, 0]; n[i] = mult; p = tuple(n); n[i] = -mult; q = tuple(n)
    return {p: (Fraction(0), Fraction(-1, 2)), q: (Fraction(0), Fraction(1, 2))}
def scale(a, c): return {k: (v[0]*c, v[1]*c) for k, v in a.items()}

def tower_dims(f0, f1, nmax):
    # W = (J f) . grad with J in (0,1) plane: W_0 = -f1, W_1 = f0  (sign irrelevant for span)
    def W(g):
        return add(mul(scale(f1, -1), deriv(g, 0)), mul(f0, deriv(g, 1)))
    funcs = [f0, f1]; layer = [f0, f1]; dims = []
    for n in range(nmax+1):
        keys = sorted(set().union(*[g.keys() for g in funcs]))
        M = sp.Matrix([[sp.Rational(g.get(kk, (0, 0))[0].numerator, g.get(kk, (0, 0))[0].denominator)
                        + sp.I*sp.Rational(g.get(kk, (0, 0))[1].numerator, g.get(kk, (0, 0))[1].denominator)
                        for kk in keys] for g in funcs])
        dims.append(M.rank())
        layer = [W(g) for g in layer]
        funcs = funcs + layer
    return dims

print("(a) dim span{W^j f_c : j <= n, c=0,1} (exact rational rank), n = 0..6")
print("   K2 scalar / C3 Hamiltonian scalar, f = sin k :", tower_dims(sin_(0), sin_(1), 6))
print("   K2 fermion, f = sin(2k)/2                   :", tower_dims(scale(sin_(0, 2), Fraction(1, 2)), scale(sin_(1, 2), Fraction(1, 2)), 6))
print("   (continuum control f = k would give dim 2 for all n: W(k) = Jk closes)")

# (b) periods of the W flow on the real torus: W = (-sin k1, sin k0) = J grad(-(cos k0 + cos k1))
def period(E):
    # start on the k1=0 axis at k0 with cos k0 + 1 = E  (level u2 = cos k0 + cos k1 = E)
    k0 = np.arccos(E - 1.0)
    rhs = lambda t, y: [-np.sin(y[1]), np.sin(y[0])]
    ev = lambda t, y: y[1]; ev.direction = 1.0
    sol = solve_ivp(rhs, [0, 500], [k0, 0.0], events=ev, rtol=1e-12, atol=1e-12, max_step=0.05)
    ts = sol.t_events[0]; ts = ts[ts > 1e-6]
    return ts[0]
print("\n(b) orbit period T(E) of the first-moment rotation flow, level cos k0 + cos k1 = E")
for E in (1.999, 1.9, 1.5, 1.0, 0.5, 0.2, 0.05):
    print(f"   E = {E:6.3f}  ->  T/2pi = {period(E)/(2*np.pi):.6f}")
print("   (continuum: T/2pi = 1 for every orbit; lattice: T varies and diverges at the van Hove level E=0)")
