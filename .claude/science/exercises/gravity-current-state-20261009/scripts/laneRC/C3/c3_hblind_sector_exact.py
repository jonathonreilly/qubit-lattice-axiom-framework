"""Lane RC / C3: the metric-blind (Killing) sector of the O(kappa) constraint algebra,
free lattice scalar of lane RN L1, checked in exact dyadic arithmetic on Z^3.

Why this sector decides the question (derivation in C3_report.md):
  at O(kappa) the matter-bilinear part of the brackets is
    {D[xi],H[N]}: {P[xi],T00[N]} + T00^(1)[N; h -> ghat(xi)] + P^(1)[xi; E -> S^T N]
    {D[xi],D[eta]}: {P[xi],P[eta]} + P^(1)[eta; h -> ghat(xi)] - P^(1)[xi; h -> ghat(eta)]
  where T00^(1), P^(1) are ANY h-linear / E-linear local completions.  For xi = const
  (p_xi = 0) ghat(xi) = 0 exactly; for N linear S^T N = 0 exactly (second differences);
  for eta linear and antisymmetric (a rotation) ghat(eta) = 0 exactly.  So at first order
  in the smearing momenta every completion term drops, and the lattice must satisfy the
  Poincare relations {P_c,K_b} = delta_bc H, {P_c,L_ab} = delta_bc P_a - delta_ac P_b by itself,
  with constant structure functions.

Fields: random integers with compact support inside a padded box (so the infinite-lattice
sums with linear smearings x_b are finite and exact).  All coefficients are dyadic, so
float64 arithmetic is exact here; we also assert integrality after scaling.
"""
import numpy as np

rng = np.random.default_rng(11102026)
AX = (0, 1, 2)
M2 = 0.25          # m^2 (dyadic so float64 is exact)
n_supp, pad = 5, 4
Lb = n_supp + 2 * pad
X = np.indices((Lb,) * 3).astype(float)   # site coordinates


def sh(f, j, s):
    """f(x + s e_j); fields vanish near the box edge, so roll == zero padding."""
    return np.roll(f, -s, axis=j)


def d(f, j):
    return sh(f, j, 1) - f


def lap(f):
    return sum(sh(f, j, 1) + sh(f, j, -1) - 2 * f for j in AX)


def T00(phi, pi):
    t = 0.5 * pi**2 + 0.5 * M2 * phi**2
    for j in AX:
        dj = d(phi, j)
        t = t + 0.25 * (dj**2 + sh(dj, j, -1) ** 2)
    return t


def P(phi, pi):
    return [0.5 * (pi + sh(pi, j, 1)) * d(phi, j) for j in AX]


def Dc(f, c):
    """the flow generated by P_tot_c: phi -> D_c phi, pi -> D_c pi (central difference)."""
    return 0.5 * (sh(f, c, 1) - sh(f, c, -1))


def Ac(f, c):
    return 0.5 * (sh(f, c, 1) + sh(f, c, -1))


def deriv(fun, phi, pi, c):
    """delta_c fun = {fun, P_tot_c}, exact for quadratic densities (polarization)."""
    a, b = Dc(phi, c), Dc(pi, c)
    fp, fm = fun(phi + a, pi + b), fun(phi - a, pi - b)
    if isinstance(fp, list):
        return [(u - v) / 2 for u, v in zip(fp, fm)]
    return (fp - fm) / 2


def rand_fields():
    phi = np.zeros((Lb,) * 3); pi = np.zeros((Lb,) * 3)
    s = slice(pad, pad + n_supp)
    phi[s, s, s] = rng.integers(-5, 6, (n_supp,) * 3)
    pi[s, s, s] = rng.integers(-5, 6, (n_supp,) * 3)
    return phi, pi


def Hm(phi, pi):
    return np.sum(T00(phi, pi))


def Ptot(phi, pi):
    return [np.sum(p) for p in P(phi, pi)]


def Ec(phi, pi, c):
    """candidate closed form: energy with the cos k_c weight, sum 1/2 pi A_c pi + 1/2 phi A_c w^2 phi."""
    w2phi = -lap(phi) + M2 * phi
    return np.sum(0.5 * pi * Ac(pi, c) + 0.5 * phi * Ac(w2phi, c))


def Qca(phi, pi, c, a):
    """candidate closed form: total momentum with the cos k_c weight on phi (symbol cos k_c sin k_a)."""
    return np.sum(P(Ac(phi, c), pi)[a])


print("=== zeroth order: sum_x delta_c T00 = {H_m, P_tot_c} and sum_x delta_c P_a = {P_tot_a, P_tot_c} ===")
mx0 = 0.0
for _ in range(5):
    phi, pi = rand_fields()
    for c in AX:
        mx0 = max(mx0, abs(np.sum(deriv(T00, phi, pi, c))))
        mx0 = max(mx0, max(abs(np.sum(q)) for q in deriv(P, phi, pi, c)))
print("max |.| =", mx0, "(exactly 0: zeroth-order structure functions vanish)")

print("\n=== {H,H} control: {K_b, H_m} with K_b = sum x_b T00 must be +-P_tot_b (lattice energy continuity) ===")
# {K_b, H_m} = sum x_b {T00(x), H_m} = sum x_b dT00/dt ... sign: {F,H} = dF/dt
def eom(phi, pi):
    return pi, lap(phi) - M2 * phi
mxHH = 0.0
for _ in range(5):
    phi, pi = rand_fields()
    a, b = eom(phi, pi)
    dT = (T00(phi + a, pi + b) - T00(phi - a, pi - b)) / 2
    Pt = Ptot(phi, pi)
    for bb in AX:
        mxHH = max(mxHH, abs(np.sum(X[bb] * dT) + Pt[bb]))
print("max |{K_b,H_m} + P_tot_b| =", mxHH, " -> the h-blind {H,H} relation closes exactly (as L1 found)")

print("\n=== boost sector {D,H}: L_bc := {K_b, P_tot_c} = sum_x x_b delta_c T00(x) ===")
mxid = 0.0
rows, rhs = [], {}
samples = []
for _ in range(40):
    phi, pi = rand_fields()
    dT = [deriv(T00, phi, pi, c) for c in AX]
    Lbc = np.array([[np.sum(X[bb] * dT[c]) for c in AX] for bb in AX])
    E = [Ec(phi, pi, c) for c in AX]
    # closed form: L_bc = -delta_bc E_c  (check exactly)
    mxid = max(mxid, np.max(np.abs(Lbc + np.diag(E))))
    samples.append((Lbc, Hm(phi, pi), Ptot(phi, pi), E, phi, pi))
print("max |L_bc + delta_bc E_c| =", mxid, " (exact identity: {K_b,P_tot_c} = -delta_bc sum_k cos k_c * energy_k)")
print("continuum requirement: L_bc = -delta_bc H_m + const * P_tot (structure functions constant at this order)")

# least-squares fit of L_bc by the most generous constant span: H_m, P_tot_j, K_e, sum x_e P_j
def generous_basis(phi, pi):
    t = T00(phi, pi); p = P(phi, pi)
    B = [Hm(phi, pi)] + Ptot(phi, pi) + [np.sum(X[e] * t) for e in AX]
    B += [np.sum((X[e] + 0.5 * (e == j)) * p[j]) for e in AX for j in AX]
    return B
for (bb, c) in [(0, 0), (1, 1), (0, 1)]:
    A = []; y = []
    for _ in range(60):
        phi, pi = rand_fields()
        dT = deriv(T00, phi, pi, c)
        y.append(np.sum(X[bb] * dT)); A.append(generous_basis(phi, pi))
    A = np.array(A); y = np.array(y)
    if np.max(np.abs(y)) == 0:
        print(f"(b,c)=({bb},{c}): L_bc identically 0 (continuum value also 0)"); continue
    coef, *_ = np.linalg.lstsq(A, y, rcond=None)
    res = np.linalg.norm(A @ coef - y) / np.linalg.norm(y)
    print(f"(b,c)=({bb},{c}): relative residual of fit by span(H, P_tot, K_e, sum x P) = {res:.4f};  coef on H = {coef[0]:+.4f}")

print("\n   defect identity: E_c - H_m = -(1/4) sum_x [ (d_c pi)^2 + d_c phi * d_c(w^2 phi) ]  (pure lattice artifact, O(a^2 k^2))")
mxdef = 0.0
for (_, H, _, E, phi, pi) in samples[:10]:
    w2phi = -lap(phi) + M2 * phi
    for c in AX:
        dfc = -0.25 * np.sum(d(pi, c) ** 2 + d(phi, c) * d(w2phi, c))
        mxdef = max(mxdef, abs(E[c] - H - dfc))
print("max |E_c - H_m - defect formula| =", mxdef)
rel = [abs(E[c] - H) / abs(H) for (_, H, _, E, _, _) in samples for c in AX]
print(f"random lattice-scale fields: |E_c - H_m|/|H_m| median {np.median(rel):.3f}")

print("\n=== rotation sector {D,D}: R_c;ab := {L_ab, P_tot_c},  L_ab = sum_x [X^(a)_b P_a(x) - X^(b)_a P_b(x)] ===")
print("    (the symmetric part sym(p' x eta) is absorbable by P^(1)[uniform strain]; the antisymmetric part is h-blind)")
mxrot = 0.0
fits = {}
for (a, b, c) in [(0, 1, 1), (0, 1, 0), (0, 1, 2), (1, 2, 2)]:
    A = []; y = []
    for _ in range(60):
        phi, pi = rand_fields()
        dP = deriv(P, phi, pi, c)
        Xa_b = X[b] + 0.5 * (a == b); Xb_a = X[a] + 0.5 * (a == b)
        R = np.sum(Xa_b * dP[a]) - np.sum(Xb_a * dP[b])
        # closed form guess: R = -(delta_bc Q_ca - delta_ac Q_cb)
        guess = -((b == c) * Qca(phi, pi, c, a) - (a == c) * Qca(phi, pi, c, b))
        mxrot = max(mxrot, abs(R - guess))
        y.append(R); A.append(generous_basis(phi, pi))
    A = np.array(A); y = np.array(y)
    if np.max(np.abs(y)) == 0:
        print(f"(a,b,c)=({a},{b},{c}): R identically 0 (continuum value also 0)"); continue
    coef, *_ = np.linalg.lstsq(A, y, rcond=None)
    res = np.linalg.norm(A @ coef - y) / np.linalg.norm(y)
    print(f"(a,b,c)=({a},{b},{c}): relative residual of fit by span(H, P_tot, K_e, sum x P) = {res:.4f}; coef on P_tot = {np.round(coef[1:4], 4)}")
print("max |R - closed form -(delta_bc Q_ca - delta_ac Q_cb)| =", mxrot, " (Q_ca has symbol cos k_c sin k_a)")
