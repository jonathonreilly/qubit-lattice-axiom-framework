"""G3: the zone-face obstruction to the uniform-strain Ward identity for a sawtooth momentum.
(a) Flow dk/ds = f(k) generated by D = sum_x x P(x): f = sin k is complete (fixed points 0, pi);
    f = sawtooth reaches the face k = pi in finite flow time ln(pi/k0): incomplete -> no unitary group (E channel).
(b) Free SLAC field (energy current = sawtooth), E channel: the only available h-completion keeps the fixed
    Brillouin cube, E0(eps) = 1/2 int_BZ omega(e^{h} k) d^3k/(2pi)^3 ; mu_E = d^2 E0/d eps^2 per cell (natural size).
    T2 channel: the sawtooth shear flow (s(k_y), s(k_x)) is divergence-free with continuous normal component at the faces:
    a measure-preserving bijection, so E0 is h-independent (checked by Monte Carlo on the flowed cube).
"""
import numpy as np
from numpy.polynomial.legendre import leggauss
def saw(k): return (k + np.pi) % (2*np.pi) - np.pi
print("== (a) flow time to reach the zone face from k0 ==")
for k0 in [0.5, 1.0, 2.0, 3.0]:
    print(f"  k0={k0}: sawtooth flow reaches pi at s = ln(pi/k0) = {np.log(np.pi/k0):.3f};  sin flow: never (k(s) = 2 atan(tan(k0/2) e^s) < pi)")
print("  -> the dilation generator sum_x x_j P_j with sawtooth P is not essentially self-adjoint (flow incomplete at the face)")

print("\n== (b) free SLAC field, E channel with the fixed-BZ completion: mu_E per cell (h = eps diag(1,-1,0)) ==")
n = 60; xg, wg = leggauss(n); kk = np.pi*xg; ww = np.pi*wg
KX, KY, KZ = np.meshgrid(kk, kk, kk, indexing='ij'); WW = ww[:, None, None]*ww[None, :, None]*ww[None, None, :]
def E0(eps, m, chan):
    if chan == 'E':
        w2 = m**2 + np.exp(2*eps)*KX**2 + np.exp(-2*eps)*KY**2 + KZ**2
    else:  # T2 metric (fixed-BZ) completion: (e^h k)^2 with h_xy = eps
        c, s = np.cosh(eps), np.sinh(eps)
        kx = c*KX + s*KY; ky = s*KX + c*KY
        w2 = m**2 + kx**2 + ky**2 + KZ**2
    return 0.5*np.sum(WW*np.sqrt(w2))/(2*np.pi)**3
for m in [0.0, 0.5, 1.0]:
    for chan in ['E', 'T2']:
        e = 0.02
        d1 = (E0(e, m, chan) + E0(-e, m, chan) - 2*E0(0, m, chan))/e**2
        d2 = (E0(e/2, m, chan) + E0(-e/2, m, chan) - 2*E0(0, m, chan))/(e/2)**2
        mu = (4*d2 - d1)/3
        print(f"  m={m}: channel {chan:2s} fixed-BZ completion mu = {mu:+.6f} per cell")
print("  (natural-size comparison: RN L1 linear-only NN-KG E-channel susceptibility -0.0037 at m=0;")
print("   these fixed-BZ values are the T0 'cutoff fixed by grid labels' effect, not removable by a determined seagull in the E channel)")

print("\n== (c) T2 channel: sawtooth shear flow is measure-preserving on the torus (unitary exists) ==")
rng = np.random.default_rng(3)
def flowT2(kx, ky, eps, nsteps=200):
    x, y = kx.copy(), ky.copy(); h = 1.0/nsteps
    for _ in range(nsteps):
        # midpoint rule with wrap (piecewise-smooth field; normal component continuous at faces)
        xm = saw(x + 0.5*h*eps*saw(y)); ym = saw(y + 0.5*h*eps*saw(x))
        x = saw(x + h*eps*saw(ym)); y = saw(y + h*eps*saw(xm))
    return x, y
N = 400000
kx = rng.uniform(-np.pi, np.pi, N); ky = rng.uniform(-np.pi, np.pi, N)
fx, fy = flowT2(kx, ky, 0.08)
H, _, _ = np.histogram2d(fx, fy, bins=8, range=[[-np.pi, np.pi], [-np.pi, np.pi]])
print(f"  image of uniform sample under eps=0.08 flow: 8x8 cell counts rel. std = {H.std()/H.mean():.4f} (Poisson {1/np.sqrt(H.mean()):.4f})")
# check: how many points cross a face (normal <-> umklapp relabel for multi-leg configurations)
cross = np.mean(np.abs(fy - (ky + 0.08*saw(kx))) > np.pi)  # crude: y wrapped
print(f"  fraction of single legs whose k_y wrapped across the face at eps=0.08: {cross:.4f}  (~ eps*<|s|>/(2pi)*... )")
