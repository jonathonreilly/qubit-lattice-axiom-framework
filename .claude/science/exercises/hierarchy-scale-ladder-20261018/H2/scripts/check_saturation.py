#!/usr/bin/env python3
"""Independent code path for A3 (charge-111 spurions): solve the equivariance constraints directly
(no Reynolds averaging, no shared code with orders_group.py) and compute
  dim V_{<=n}(phi) = dim span{ p(phi) : p equivariant polynomial map R -> Herm(V16)_odd, deg p odd <= n }
and dim Fix(Stab phi) on the chirality-odd Hermitian operators, for O_h irreps E, T1, T2 (g and u)
carried with translation character 111, at fixed lines of explicit subgroups.
Node space: 8 cube-point nodes x spin-1/2, naive-type action (variant A1-A1).
"""
import itertools
import numpy as np

# ---- O_h from generators
C4z = np.array([[0, -1, 0], [1, 0, 0], [0, 0, 1]])
C3 = np.array([[0, 0, 1], [1, 0, 0], [0, 1, 0]])
INV = -np.eye(3, dtype=int)
G = [np.eye(3, dtype=int)]
frontier = [np.eye(3, dtype=int)]
while frontier:
    new = []
    for X in frontier:
        for g in (C4z, C3, INV):
            Y = g @ X
            if not any((Y == Z).all() for Z in G): G.append(Y); new.append(Y)
    frontier = new
assert len(G) == 48

def su2(R):
    R = R.astype(float)
    if np.allclose(R, np.eye(3)): return np.eye(2, dtype=complex)
    th = np.arccos(np.clip((np.trace(R) - 1) / 2, -1, 1))
    w, v = np.linalg.eig(R); n = np.real(v[:, np.argmin(np.abs(w - 1))]); n /= np.linalg.norm(n)
    S = [np.array([[0, 1], [1, 0]]), np.array([[0, -1j], [1j, 0]]), np.array([[1, 0], [0, -1]])]
    for sgn in (1, -1):
        U = np.cos(th / 2) * np.eye(2) - 1j * np.sin(th / 2) * sum(sgn * n[i] * S[i] for i in range(3))
        if all(np.allclose(U @ S[j] @ U.conj().T, sum(R[i, j] * S[i] for i in range(3))) for j in range(3)):
            return U
    raise RuntimeError
NODES = list(itertools.product((0, 1), repeat=3))
def node_op(M):
    d = int(round(np.linalg.det(M))); R = d * M; P = np.abs(M)
    Pm = np.zeros((8, 8))
    for a, s in enumerate(NODES):
        s2 = tuple(int(x) % 2 for x in P @ np.array(s))
        if d == -1: s2 = tuple(1 - x for x in s2)
        Pm[NODES.index(s2), a] = 1
    return np.kron(Pm, su2(R))
def trans_op(t):
    return np.kron(np.diag([(-1.0) ** int(np.dot(s, t)) for s in NODES]), np.eye(2))
T111 = trans_op((1, 1, 1))

# ---- O_h irreps by explicit polynomial spaces
def irrep(name, M):
    d = int(round(np.linalg.det(M))); R = (d * M).astype(float); P = np.abs(R)
    par = d if name.endswith('u') else 1
    base = name[:-1]
    sgn = int(round(np.linalg.det(P)))
    if base == 'E':   # traceless diagonal quadratic forms, basis (x^2-y^2)/sqrt2, (2z^2-x^2-y^2)/sqrt6
        B = np.array([[1, -1, 0], [-1, -1, 2]], float).T / np.array([np.sqrt(2), np.sqrt(6)])
        m = B.T @ P @ B
    elif base == 'T1': m = R
    elif base == 'T2': m = sgn * R
    return par * m

# ---- group Gamma generated by point elements and translations; generators suffice for constraints
GENS = [(np.zeros(3, int), C4z), (np.zeros(3, int), C3), (np.zeros(3, int), INV), (np.array([1, 0, 0]), np.eye(3, dtype=int))]
def D(g):
    t, M = g; return trans_op(t) @ node_op(M)
def rho(name, g):
    t, M = g; return ((-1.0) ** int(t.sum())) * irrep(name, M)

# ---- real coordinates on Herm(16)_odd (X = -T111 X T111)
rng = np.random.default_rng(3)
def herm_basis_odd():
    B = []
    for i in range(16):
        for j in range(i, 16):
            for part in ((1, 0), (0, 1)) if i != j else ((1, 0),):
                X = np.zeros((16, 16), complex)
                if i == j: X[i, i] = 1
                elif part == (1, 0): X[i, j] = X[j, i] = 1
                else: X[i, j] = 1j; X[j, i] = -1j
                Y = (X - T111 @ X @ T111) / 2
                if np.abs(Y).max() > 1e-12: B.append(Y)
    # orthonormalise
    V = np.array([np.concatenate([b.real.ravel(), b.imag.ravel()]) for b in B])
    q, r = np.linalg.qr(V.T)
    keep = np.abs(np.diag(r)) > 1e-10
    return q[:, keep].T
WB = herm_basis_odd()   # rows: orthonormal real coordinates
NW = WB.shape[0]
def to_vec(X): return WB @ np.concatenate([X.real.ravel(), X.imag.ravel()])
def from_vec(v):
    z = WB.T @ v; n = 256; return (z[:n] + 1j * z[n:]).reshape(16, 16)
def Ad_mat(g):
    Dg = D(g); cols = []
    for k in range(NW):
        e = np.zeros(NW); e[k] = 1
        cols.append(to_vec(Dg @ from_vec(e) @ Dg.conj().T))
    return np.array(cols).T

def monomials(d, n): return [a for a in itertools.product(range(n + 1), repeat=d) if sum(a) == n]
def mono_eval(x, mons): return np.array([np.prod(x ** np.array(a)) for a in mons])

def equivariant_space(name, n):
    d = irrep(name, np.eye(3, dtype=int)).shape[0]
    mons = monomials(d, n); nm = len(mons)
    X = rng.normal(size=(nm + 8, d))
    Mx = np.array([mono_eval(x, mons) for x in X])
    blocks = []
    for g in GENS:
        A = Ad_mat(g); r = rho(name, g)
        Mgx = np.array([mono_eval(r @ x, mons) for x in X])
        S = np.linalg.lstsq(Mx, Mgx, rcond=None)[0].T          # monomials(r x) = S monomials(x)
        assert np.allclose(Mx @ S.T, Mgx, atol=1e-8)
        blocks.append(np.kron(S, np.eye(NW)) - np.kron(np.eye(nm), A))   # acts on column-major vec(C)
    K = np.vstack(blocks)
    s, vt = np.linalg.svd(K.T @ K, hermitian=True)[1:]; s = np.sqrt(np.abs(s))
    rank = int(np.sum(s > 1e-6 * s[0]))
    null = vt[rank:]
    # convert column-major vec back to C (NW x nm)
    return [v.reshape(nm, NW).T for v in null], mons, d

def fixed_dim(stab):
    # dim of H-fixed odd Hermitian operators: rank of the H-average
    P = sum(Ad_mat(h) for h in stab) / len(stab)
    return int(np.sum(np.linalg.svd(P, compute_uv=False) > 0.5))

def all_group():
    els = []
    for t in itertools.product((0, 1), repeat=3):
        for M in G: els.append((np.array(t), M))
    return els
GAMMA = all_group()

def run(name):
    d = irrep(name, np.eye(3, dtype=int)).shape[0]
    NS = (1, 3, 5) if d == 2 else (1, 3)
    spaces = {n: equivariant_space(name, n) for n in NS}
    # candidate directions: fixed lines of explicit subgroups (stabilisers of coordinate/diagonal directions)
    cands = []
    for H in subgroups_for(d):
        P = sum(rho(name, h) for h in H) / len(H)
        w, v = np.linalg.eigh((P + P.T) / 2)
        if np.sum(w > 0.5) == 1: cands.append(v[:, np.argmax(w)])
    seen = []
    for phi in cands:
        if any(abs(abs(np.dot(phi, p)) - 1) < 1e-8 for p in seen): continue
        seen.append(phi)
        stab = [g for g in GAMMA if np.allclose(rho(name, g) @ phi, phi)]
        dims = []
        acc = []
        for n in NS:
            null, mons, _ = spaces[n]
            for C in null:
                acc.append(C @ mono_eval(phi, mons))
            dims.append(np.linalg.matrix_rank(np.array(acc), tol=1e-8) if acc else 0)
        print(f"111 {name:<3} phi={np.round(phi, 3)} |Stab|={len(stab):<3} dimV<=1,3(,5) = {dims}  dimFix = {fixed_dim(stab)}  "
              f"(equivariant maps per degree: {[len(spaces[n][0]) for n in NS]})")

def subgroups_for(d):
    # stabilisers in Gamma of a few natural vectors (point part only, with translations that act trivially)
    out = []
    pts = [(np.zeros(3, int), M) for M in G]
    for gens in itertools.combinations(range(48), 2):
        pass
    # explicit choices: D4h(z), D3d[111], D2h, C4h(z), C2h(z), C3v-type, C2v
    def gen_sub(gs):
        H = [(np.zeros(3, int), np.eye(3, dtype=int))]
        fr = list(H)
        while fr:
            nw = []
            for x in fr:
                for g in gs:
                    y = (np.array((x[0] + np.abs(x[1]) @ g[0]) % 2), x[1] @ g[1])
                    if not any((y[0] == z[0]).all() and (y[1] == z[1]).all() for z in H): H.append(y); nw.append(y)
            fr = nw
        return H
    Z = np.zeros(3, int)
    C2x = np.diag([1, -1, -1]); C2z = np.diag([-1, -1, 1]); C2d = np.array([[0, 1, 0], [1, 0, 0], [0, 0, -1]])
    out.append(gen_sub([(Z, C4z), (Z, C2x), (Z, INV)]))          # D4h(z)
    out.append(gen_sub([(Z, C3), (Z, np.array([[0, -1, 0], [-1, 0, 0], [0, 0, -1]])), (Z, INV)]))  # D3d
    out.append(gen_sub([(Z, C2x), (Z, C2z), (Z, INV)]))          # D2h
    out.append(gen_sub([(Z, C4z), (Z, INV)]))                    # C4h
    out.append(gen_sub([(Z, C2d), (Z, C2z), (Z, INV)]))          # D2h'
    out.append(gen_sub([(Z, C3), (Z, INV)]))                     # S6
    out.append(gen_sub([(Z, C2d), (Z, INV)]))                    # C2h'
    return out

if __name__ == '__main__':
    print(f"odd Hermitian coordinates: {NW}")
    for name in ('Eg', 'Eu', 'T1g', 'T1u', 'T2g', 'T2u'):
        run(name)
