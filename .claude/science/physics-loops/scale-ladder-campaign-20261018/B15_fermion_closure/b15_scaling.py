#!/usr/bin/env python3
"""B15 floating-point lattice check (independent implementation: numpy array rolls on an L^3 torus of side 2 pi,
spacing a = 2 pi / L; the continuum target is generated by sympy from closed-form smooth fields).

Measures rel(L) = || [h_N,h_M] psi + v^2 L_w psi || / || v^2 L_w psi ||, L_w the spinor (Kosmann) Lie derivative,
w = N grad M - M grad N, for smooth periodic N, M, psi. Diagnostic only (floating point); slope from L=16,32,64.
Cases:
  weyl_t0.5   naive Weyl, endpoint-mean bond timing       expect rel ~ a^2
  weyl_t1     naive Weyl, one-endpoint timing             expect rel ~ a
  doubler     psi = (-1)^{n_1} chi, target Kosmann with the doubler's spin tau = (s1, -s2, -s3)   expect ~ a^2
  dirac_m     naive Dirac + mass m=1.3, endpoint mean     expect ~ a^2 (mass drops out)
  wilson_r1   naive Dirac + Wilson r=1, endpoint mean     expect ~ a (Clifford-odd O(a) term)
PASS criteria declared before running: fitted log-slope between L=32 and 64 within 0.25 of the expected power.
"""
from __future__ import annotations

import math

import numpy as np
import sympy as sp

V = 0.8
RES = {"pass": 0, "fail": 0}


def check(tag, ok, msg):
    RES["pass" if ok else "fail"] += 1
    print(("PASS" if ok else "FAIL") + f": {tag} {msg}", flush=True)


x, y, z = sp.symbols("x y z", real=True)
XS = (x, y, z)
Nexpr = 1 + sp.Rational(3, 10) * sp.sin(x) * sp.cos(y) + sp.Rational(1, 5) * sp.cos(z + x)
Mexpr = 1 + sp.Rational(1, 4) * sp.cos(x + y) + sp.Rational(1, 5) * sp.sin(z) * sp.cos(y)
CHI = [sp.sin(x) + sp.I * sp.cos(y + z), sp.cos(2 * x - z) + sp.Rational(1, 2) * sp.sin(y)]
S = [sp.Matrix([[0, 1], [1, 0]]), sp.Matrix([[0, -sp.I], [sp.I, 0]]), sp.Matrix([[1, 0], [0, -1]])]


def lie_target(chi, sig):
    w = [Nexpr * sp.diff(Mexpr, q) - Mexpr * sp.diff(Nexpr, q) for q in XS]
    div = sum(sp.diff(w[k], XS[k]) for k in range(3))
    curl = [sp.diff(w[2], y) - sp.diff(w[1], z), sp.diff(w[0], z) - sp.diff(w[2], x), sp.diff(w[1], x) - sp.diff(w[0], y)]
    ch = sp.Matrix(chi)
    out = sum((w[k] * ch.diff(XS[k]) for k in range(3)), sp.zeros(2, 1)) + div / 2 * ch
    out += sum((sp.I / 4 * curl[k] * (sig[k] * ch) for k in range(3)), sp.zeros(2, 1))
    return [sp.lambdify(XS, e, "numpy") for e in out]


T_STD = lie_target(CHI, S)
# The staggered map gives B[sigma'] with sigma' = (-s1, s2, s3), whose algebra has the opposite orientation; the
# proper Pauli set (spin) of the doubler is tau = -sigma' = (s1, -s2, -s3), and its Kosmann term is (i/4) curl w . tau.
# (First run used +(i/4) curl w . sigma' - a sign error in the expectation, see b15_scaling_firstrun.log.)
T_FLIP = lie_target(CHI, [S[0], -S[1], -S[2]])
Nf = sp.lambdify(XS, Nexpr, "numpy")
Mf = sp.lambdify(XS, Mexpr, "numpy")
CHIf = [sp.lambdify(XS, e, "numpy") for e in CHI]

s1 = np.array([[0, 1], [1, 0]], complex)
s2 = np.array([[0, -1j], [1j, 0]], complex)
s3 = np.array([[1, 0], [0, -1]], complex)
I2 = np.eye(2)
SIGN = [s1, s2, s3]
ALPHA = [np.kron(s1, s) for s in SIGN]
BETA = np.kron(s3, I2)


def apply(mat, f):
    return np.einsum("ab,b...->a...", mat, f)


def hop(n, f, a, t, mats, r=0.0, beta=None, mass=0.0):
    out = np.zeros_like(f)
    for j in range(3):
        ax = j + 1  # f has component axis 0
        wj = t * n + (1 - t) * np.roll(n, -1, axis=j)
        wjm = np.roll(wj, 1, axis=j)
        fp, fm = np.roll(f, -1, axis=ax), np.roll(f, 1, axis=ax)
        out += (-1j * V / (2 * a)) * apply(mats[j], wj * fp - wjm * fm)
        if r:
            out += (r / (2 * a)) * apply(beta, wj * (f - fp) + wjm * (f - fm))
    if mass:
        out += mass * n * apply(beta, f)
    return out


def run(case, L):
    a = 2 * math.pi / L
    g = np.arange(L) * a
    X, Y, Zg = np.meshgrid(g, g, g, indexing="ij")
    n, m = Nf(X, Y, Zg), Mf(X, Y, Zg)
    chi = np.array([np.broadcast_to(c(X, Y, Zg), X.shape) for c in CHIf], complex)
    tgt = np.array([np.broadcast_to(c(X, Y, Zg), X.shape) for c in (T_FLIP if case == "doubler" else T_STD)], complex)
    kw = dict(t=0.5, mats=SIGN)
    psi = chi
    if case == "weyl_t1":
        kw["t"] = 1.0
    if case == "doubler":
        stag = (-1.0) ** np.arange(L)[:, None, None]
        psi = chi * stag
        tgt = tgt * stag
    if case in ("dirac_m", "wilson_r1"):
        kw["mats"] = ALPHA
        kw["beta"] = BETA
        psi = np.concatenate([chi, 0.7 * chi[::-1]])
        tgt_up = tgt
        # target 1 (x) L_w acting on (chi, 0.7 chi_swapped): recompute lower block target directly
        lower = np.array([np.broadcast_to(c(X, Y, Zg), X.shape) for c in LOWER_T], complex)
        tgt = np.concatenate([tgt_up, 0.7 * lower])
        if case == "dirac_m":
            kw["mass"] = 1.3
        else:
            kw["r"] = 1.0
    br = hop(n, hop(m, psi, a, **kw), a, **kw) - hop(m, hop(n, psi, a, **kw), a, **kw)
    res = br + V ** 2 * tgt
    return np.linalg.norm(res) / np.linalg.norm(V ** 2 * tgt)


LOWER_T = lie_target(CHI[::-1], S)

if __name__ == "__main__":
    expect = {"weyl_t0.5": 2, "weyl_t1": 1, "doubler": 2, "dirac_m": 2, "wilson_r1": 1}
    for case, pw in expect.items():
        rs = {L: run(case, L) for L in (16, 32, 64)}
        sl = math.log(rs[32] / rs[64]) / math.log(2)
        sl1 = math.log(rs[16] / rs[32]) / math.log(2)
        print(f"   {case}: rel = " + ", ".join(f"L={L}: {r:.3e}" for L, r in rs.items()) + f"; slopes {sl1:.2f}, {sl:.2f}")
        check(case, abs(sl - pw) < 0.25, f"relative residual of [h_N,h_M] + v^2 L_w falls as a^{sl:.2f} (expected a^{pw})")
    print(f"TOTAL: PASS={RES['pass']} FAIL={RES['fail']}")
