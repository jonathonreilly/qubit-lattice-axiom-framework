# ---- detailed census for the best family-(A) word: Berry fluxes and refined speeds at every distinct node class
def berry(W,k0,E,r=0.01,n=16):
    th=np.linspace(0,np.pi,n+1); phs=np.linspace(0,2*np.pi,2*n,endpoint=False); Uv=[]
    for t in th:
        row=[]
        for p_ in phs:
            e,v=np.linalg.eig(W(k0+r*np.array([np.sin(t)*np.cos(p_),np.sin(t)*np.sin(p_),np.cos(t)])))
            a_=wrap(np.angle(e)-E); idx=np.argsort(np.where(np.abs(a_)<0.3,a_,9))[0]; row.append(v[:,idx]/np.linalg.norm(v[:,idx]))
        Uv.append(row)
    tot=0
    for i_ in range(n):
        for j_ in range(2*n):
            a_,b_,c_,d_=Uv[i_][j_],Uv[i_+1][j_],Uv[i_+1][(j_+1)%(2*n)],Uv[i_][(j_+1)%(2*n)]
            tot+=np.angle(np.vdot(a_,b_)*np.vdot(b_,c_)*np.vdot(c_,d_)*np.vdot(d_,a_))
    return tot/(2*np.pi)
