#!/usr/bin/env python3
"""C3 boundary case: in 2D the AREA-PRESERVING relabellings of a lattice scalar DO admit an exact, non-local lattice
closure (the Fairlie-Fletcher-Zachos sine / gl(N) algebra), because that algebra contains no uniform translation, so
Theorem B (which needs D = uniform translation in the algebra) does not apply.

Lattice scalar phi on Z_N^2 <-> N x N matrix Phi = sum_m phihat_m J_m, J_m = g^{m1} h^{m2} (g shift, h clock, hg = w gh).
Relabelling by a lattice 'stream function' f:  delta Phi = kappa [F, Phi], F = sum_p fhat_p J_p, kappa = N/(2 pi i).
In the momentum basis: X_p e_q = kappa c(p,q) e_{p+q},  c(p,q) = w^{p2 q1} - w^{p1 q2}  (computed from the matrices).
Checks (floating point):
  E1  exact closure [X_p, X_r] = kappa c(p,r) X_{p+r} for all p, r (Jacobi of gl(N); machine precision);
  E2  continuum limit: kappa c(p,q) -> (p2 q1 - p1 q2) at fixed integer p, q with relative error O(1/N) (slope fitted);
  E3  translation covariance: the Z_N^2 translation of phi acts diagonally on momenta (phase), X commutes with it up
      to the momentum phase of f;
  E4  non-locality: real-space range of the relabelling generated by a SITE-localised f is the whole torus;
  E5  no uniform translation can be adjoined: with D_1 = SLAC derivative along x_1 (or the naive one),
      [D_1, X_p] is not in span(X_p) (Theorem A in this setting).
"""
import numpy as np

RES = {"pass": 0, "fail": 0}


def check(tag, ok, msg):
    RES["pass" if ok else "fail"] += 1
    print(("PASS" if ok else "FAIL") + f": {tag} {msg}", flush=True)


def nbar(n, N):
    r = n % N
    return r - N if r > N // 2 else r


def setup(N):
    w = np.exp(2j * np.pi / N)
    g = np.roll(np.eye(N), 1, axis=0)
    h = np.diag(w ** np.arange(N))
    J = {}
    for a in range(N):
        for b in range(N):
            J[(a, b)] = np.linalg.matrix_power(g, a) @ np.linalg.matrix_power(h, b)
    return w, J


def struct_c(N, w, J):
    c = {}
    for p in J:
        for q in J:
            r = ((p[0] + q[0]) % N, (p[1] + q[1]) % N)
            Cm = J[p] @ J[q] - J[q] @ J[p]
            # Cm = c * J[r]; J[r] unitary -> c = tr(J_r^dag Cm)/N
            cc = np.trace(J[r].conj().T @ Cm) / N
            assert np.linalg.norm(Cm - cc * J[r]) < 1e-9
            c[(p, q)] = cc
    return c


def X_mats(N, c):
    idx = {m: i for i, m in enumerate(sorted({p for p, _ in c}))}
    kappa = N / (2j * np.pi)
    X = {}
    for p in idx:
        M = np.zeros((N * N, N * N), complex)
        for q in idx:
            r = ((p[0] + q[0]) % N, (p[1] + q[1]) % N)
            M[idx[r], idx[q]] = kappa * c[(p, q)]
        X[p] = M
    return X, idx, kappa


if __name__ == "__main__":
    for N in (5, 7):
        w, J = setup(N)
        c = struct_c(N, w, J)
        X, idx, kappa = X_mats(N, c)
        worst = 0.0
        for p in X:
            for r in X:
                s = ((p[0] + r[0]) % N, (p[1] + r[1]) % N)
                D = X[p] @ X[r] - X[r] @ X[p] - kappa * c[(p, r)] * X[s]
                worst = max(worst, np.abs(D).max())
        check(f"E1_N{N}", worst < 1e-9, f"exact closure of the area-preserving lattice relabellings on Z_{N}^2: max |[X_p,X_r] - kappa c(p,r) X_(p+r)| = {worst:.1e}")
        # E5: adjoin a uniform translation along x_1 (acts on phihat_q by i dbar(q1))
        for nm, dsym in (("SLAC", lambda q: 2 * np.pi * nbar(q, N) / N), ("naive", lambda q: np.sin(2 * np.pi * q / N))):
            Dm = np.diag([1j * dsym(q[0]) for q in sorted(idx, key=lambda m: idx[m])])
            wr = 0.0
            for p in X:
                if p == (0, 0):
                    continue
                Y = Dm @ X[p] - X[p] @ Dm
                nx = np.vdot(X[p], X[p]).real
                if np.linalg.norm(Y) < 1e-12:
                    continue
                cc = np.vdot(X[p], Y) / nx
                wr = max(wr, np.linalg.norm(Y - cc * X[p]) / np.linalg.norm(Y))
            check(f"E5_{nm}_N{N}", wr > 1e-3, f"adjoining the uniform translation D_1 ({nm}) breaks closure: max rel. residual of [D_1,X_p] off span X_p = {wr:.3e}")
        # E4: real-space range for site-localised f (all momenta with equal weight)
        F = np.exp(-2j * np.pi * np.outer(np.arange(N), np.arange(N)) / N) / np.sqrt(N)
        F2 = np.kron(F, F)  # momentum (q1,q2) <- position (x1,x2), index q1*N+q2 matches sorted idx
        Xf = sum(X[p] for p in X) / (N * N)
        Xr = F2.conj().T @ Xf @ F2
        # range = max torus distance between output site and input sites with nonzero kernel, from the f-site (0,0)
        rng_max = 0
        for out in range(N * N):
            for inn in range(N * N):
                if abs(Xr[out, inn]) > 1e-10:
                    for s in (out, inn):
                        d = max(abs(nbar(s // N, N)), abs(nbar(s % N, N)))
                        rng_max = max(rng_max, d)
        check(f"E4_N{N}", rng_max == N // 2, f"site-localised f: the relabelling kernel reaches torus distance {rng_max} = N//2 from the f-site (non-local)")
    # E2: continuum limit of the structure constants
    p, q = (1, 2), (2, -1)
    sig = p[1] * q[0] - p[0] * q[1]
    errs = []
    Ns = [11, 21, 41, 81, 161]
    for N in Ns:
        w = np.exp(2j * np.pi / N)
        cc = w ** (p[1] * q[0]) - w ** (p[0] * q[1])
        errs.append(abs(N / (2j * np.pi) * cc - sig) / abs(sig))
    slope = np.polyfit(np.log(Ns), np.log(errs), 1)[0]
    check("E2", abs(slope + 1) < 0.1, f"kappa c(p,q) -> p2 q1 - p1 q2 = {sig}: rel. errors {', '.join(f'{e:.2e}' for e in errs)}, slope {slope:.2f} (O(a) deviation of the exact structure constants)")
    print(f"TOTAL: PASS={RES['pass']} FAIL={RES['fail']}")
