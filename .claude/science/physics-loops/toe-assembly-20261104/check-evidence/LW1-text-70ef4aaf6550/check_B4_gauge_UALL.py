import numpy as np, itertools
from functools import reduce
rng=np.random.default_rng(7)
def kron(*ms): return reduce(np.kron,ms)
def spin(S):
    d=int(round(2*S+1)); m=np.array([-S+k for k in range(d)])
    E=np.diag(m).astype(complex); J=np.zeros((d,d),complex)
    for k in range(d-1): J[k+1,k]=np.sqrt(S*(S+1)-m[k]*(m[k]+1))
    return E,J
def expm_h(H,t):  # exp(-i t H), H Hermitian
    w,U=np.linalg.eigh(H); return (U*np.exp(-1j*t*w))@U.conj().T
def comm(a,b): return a@b-b@a
print("--- link algebra")
for S in (0.5,1,1.5,2,2.5):
    E,J=spin(S); Sx=(J+J.conj().T)/2
    R=expm_h(Sx,np.pi)
    print(f"S={S}: |[E,J]-J|={abs(comm(E,J)-J).max():.1e}  |R E R^-1 + E|={abs(R@E@R.conj().T+E).max():.1e}  |R J R^-1 - J^dag|={abs(R@J@R.conj().T-J.conj().T).max():.1e}  J|S>=0:{abs(J[:,-1]).max()==0}")
def fermions(n):
    a=np.array([[0,1],[0,0]],complex); Z=np.diag([1,-1]).astype(complex); I=np.eye(2)
    return [kron(*([Z]*k+[a]+[I]*(n-k-1))) for k in range(n)]
print("--- face: 4 sites (0,0),(1,0),(1,1),(0,1) in the i<j plane, 4 positively oriented links")
for S in (0.5,1):
    E,J=spin(S); d=E.shape[0]
    c=fermions(4); dF=16; IL=np.eye(d**4); IF=np.eye(dF)
    cs=[np.kron(x,IL) for x in c]
    def link(op,k): return np.kron(IF,kron(*[op if j==k else np.eye(d) for j in range(4)]))
    Es=[link(E,k) for k in range(4)]; Js=[link(J,k) for k in range(4)]
    # sites: 0=x,1=x+e_i,2=x+e_i+e_j,3=x+e_j ; links (src,tgt): l0=(0,1) dir i, l1=(1,2) dir j, l2=(3,2) dir i, l3=(0,3) dir j
    links=[(0,1),(1,2),(3,2),(0,3)]; eta=[1,-1,1,1]   # eta_j(x+e_i) = -eta_j(x) for i<j ; face product -1
    ns=[x.conj().T@x for x in cs]
    Gs=[]
    for v in range(4):
        G=ns[v].copy()
        for k,(a,b) in enumerate(links):
            if a==v: G=G+Es[k]
            if b==v: G=G-Es[k]
        Gs.append(G)
    A=[cs[b].conj().T@Js[k]@cs[a] for k,(a,b) in enumerate(links)]
    H=sum(eta[k]*(A[k]+A[k].conj().T) for k in range(4))/np.sqrt(3)
    N=sum(ns)
    print(f"S={S}: max|[G_v,A_l]|={max(abs(comm(G,a)).max() for G in Gs for a in A):.1e}  |[G_v,H]|={max(abs(comm(G,H)).max() for G in Gs):.1e}  |[N,H]|={abs(comm(N,H)).max():.1e}")
    U=expm_h(H,0.83)
    WE=expm_h(sum(e@e for e in Es),0.37)
    print(f"     |[G_v,exp(-iaH)]|={max(abs(comm(G,U)).max() for G in Gs):.1e}  |[G_v,W_E]|={max(abs(comm(G,WE)).max() for G in Gs):.1e}  |[n_x,W_E]|={max(abs(comm(n,WE)).max() for n in ns):.1e}")
    # control: wrong orientation of one link term (J -> J^dag) breaks Gauss
    Abad=cs[1].conj().T@Js[0].conj().T@cs[0]
    print(f"     control |[G_0,c_y^dag J^dag c_x]|={abs(comm(Gs[0],Abad)).max():.2f} (nonzero expected)")
    # plaquette monomial: oriented loop 0->1->2->3->0 : J0 J1 J2^dag J3^dag
    Jp=Js[0]@Js[1]@Js[2].conj().T@Js[3].conj().T
    print(f"     plaquette |[G_v,J_p]|={max(abs(comm(G,Jp)).max() for G in Gs):.1e}; control non-oriented product J0 J1 J2 J3: {max(abs(comm(G,Js[0]@Js[1]@Js[2]@Js[3])).max() for G in Gs):.2f}")
    # empty matter subspace: H annihilates it for every link state
    P0=np.kron(np.diag([1.0]+[0]*15),IL)   # JW vacuum |0000> is index 0 with a=[[0,1],[0,0]] lowering |1>->|0>
    assert abs(N@P0).max()<1e-12
    print(f"     |H P_empty|={abs(H@P0).max():.1e}  |U P_empty - P_empty|={abs(U@P0-P0).max():.1e}")
    # link reversal covariance: reverse link 0 by spin rotation: c_1^dag J c_0 -> c_1^dag J^dag c_0 = (c_0^dag J c_1)^dag i.e. hop term of the reversed link
    R=link(expm_h((J+J.conj().T)/2,np.pi),0)
    lhs=R@(A[0]+A[0].conj().T)@R.conj().T
    rhs=cs[0].conj().T@Js[0]@cs[1]; rhs=rhs+rhs.conj().T
    print(f"     link reversal: |R(A+A^dag)R^-1 - hop term of reversed link|={abs(lhs-rhs).max():.1e}")
print("--- UALL: 3 fermion modes, Lie algebra generated by even skew-Hermitian operators on pairs")
c=fermions(3); I8=np.eye(8); P=reduce(lambda a,b:a@b,[I8-2*x.conj().T@x for x in c])
def pair_even_basis(i,j):
    ops=[I8,c[i],c[i].conj().T,c[i].conj().T@c[i]]; ops2=[I8,c[j],c[j].conj().T,c[j].conj().T@c[j]]
    out=[]
    for a in ops:
        for b in ops2:
            m=a@b
            if abs(P@m@P-m).max()<1e-12:
                out+= [m-m.conj().T, 1j*(m+m.conj().T)]
    return out
gens=[g for (i,j) in [(0,1),(1,2),(0,2)] for g in pair_even_basis(i,j)]
def span_basis(mats):
    V=np.array([np.concatenate([m.real.ravel(),m.imag.ravel()]) for m in mats])
    u,s,vt=np.linalg.svd(V,full_matrices=False); r=(s>1e-9).sum(); return vt[:r]
def tomat(v): return (v[:64]+1j*v[64:]).reshape(8,8)
basis=span_basis(gens)
while True:
    mats=[tomat(v) for v in basis]
    new=mats+[comm(a,b) for a in mats for b in mats]
    nb=span_basis(new)
    if len(nb)==len(basis): break
    basis=nb
mats=[tomat(v) for v in basis]
print("dim generated real Lie algebra:",len(basis)," dim of all even skew-Hermitian (u(4)+u(4)) = 32")
print("max |tr(P X)| over generated algebra:",max(abs(np.trace(P@m)) for m in mats)," tr(P iP)=",np.trace(P@(1j*P)))
iP=1j*P; v=np.concatenate([iP.real.ravel(),iP.imag.ravel()])
