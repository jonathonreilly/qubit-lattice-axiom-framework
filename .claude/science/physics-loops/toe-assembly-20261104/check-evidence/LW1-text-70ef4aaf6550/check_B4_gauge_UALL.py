print("--- B3: one-site frames, 2 modes; d = a + b n + u c + v c^dag must anticommute with other mode and satisfy CAR")
c=fermions(2); n0=c[0].conj().T@c[0]; I4=np.eye(4)
def car_ok(a,b,u,v):
    d=a*I4+b*n0+u*c[0]+v*c[0].conj().T
    ac=lambda x,y:x@y+y@x
    return max(abs(ac(d,c[1])).max(),abs(ac(d,c[1].conj().T)).max(),abs(d@d).max(),abs(ac(d,d.conj().T)-I4).max())<1e-10
