"""Combined link x matter group law, faithful group on D=+1 states, and vacuum invariance."""
import itertools, numpy as np
from mj import *
from rot import *
import matter as MT

groups = consistent_link_groups(); ML = matter_lifts()
Q = MT.quat_2O(); Ds = [MT.su2(q) for q in Q]
def qidx(D):
    for i, E in enumerate(Ds):
        if np.allclose(D, E): return i
# combined generated group: elements (link signed perm, quaternion index)
def comb_mul(a, b):  # apply b then a
    return (sp_compose(a[0], b[0]), qidx(Ds[a[1]] @ Ds[b[1]]))
mneg = qidx(-np.eye(2))
summ = {}
for gi, Gp in enumerate(groups):
    # generators: C4z and C3 lifts (pick first link lift and first matter lift)
    gens = []
    for R in (C4z, C3):
        p = tuple(dir_perm(R)); ls = sorted(y for y in Gp if y[0] == p)[0]
        qi = [i for i, D in enumerate(Ds) if (np.rint(MT.so3(D)).astype(int) == R).all()][0]
        gens.append((ls, qi))
    idn = ((tuple(range(6)), (1,) * 6), qidx(np.eye(2)))
    Gc = {idn}; fr = [idn]
    while fr:
        nw = []
        for x in fr:
            for gg in gens:
                y = comb_mul(gg, x)
                if y not in Gc: Gc.add(y); nw.append(y)
        fr = nw
    minusL = ((tuple(range(6)), (-1,) * 6), qidx(np.eye(2)))
    minusM = ((tuple(range(6)), (1,) * 6), mneg)
    both = ((tuple(range(6)), (-1,) * 6), mneg)
    # squares of C2 lifts modulo the diagonal (which acts as prod_v D_v = 1 on D=+1)
    def is_c2(x):
        R = perm_to_rot(x[0][0]); return round(np.trace(R)) == -1
    sq = {'axis': set(), 'edge': set()}
    for x in Gc:
        if not is_c2(x): continue
        R = perm_to_rot(x[0][0]); c = 'axis' if any(R[a, a] == 1 for a in range(3)) else 'edge'
        s = comb_mul(x, x)
        lab = {idn: '1', minusL: '-1_L', minusM: '-1_M', both: '-1_L-1_M'}[s]
        sq[c].add(lab)
    key = (len(Gc), minusL in Gc, minusM in Gc, both in Gc, tuple(sorted(sq['axis'])), tuple(sorted(sq['edge'])))
    summ[key] = summ.get(key, 0) + 1
print('combined group generated by (C4z, C3) lifts, over the 128 consistent link groups:')
for k, v in summ.items():
    print(f'  order={k[0]} contains -1_L:{k[1]} -1_M:{k[2]} (-1_L)(-1_M):{k[3]}  '
          f'axis-C2 squares {k[4]}  edge-C2 squares {k[5]}   [{v} groups]')
print('  On D=+1 states (-1_L)(-1_M) = conj by prod D = 1, so -1_L == -1_M == global matter parity.')
print('  => faithful group there: double cover of O with axis C2 lifts of order 4, edge C2 lifts of order 2')
print('     (the GL(2,3)-type cover, class (axis -, edge +)), NOT O and NOT 2O.')

# ---------- vacuum invariance on the torus (L=4, L=6) ----------
for L in [4, 6]:
    lat = Lat(L); N = lat.N
    g = generators(lat); base = g['D'] + g['Pu'] + g['Pd'] + g['W']
    def wilson(a):
        op = (1.0 + 0j, np.zeros(N, dtype=np.int64))
        for t in range(L):
            v = [0, 0, 0]; v[a] = t
            op = mul(op, u_edge(lat, tuple(v), a))
        return op
    Wl = [wilson(a) for a in range(3)]
    Gp = groups[0]
    res = {}
    for signs in itertools.product([1, -1], repeat=3):
        ext = base + [(s * w[0], w[1]) for s, w in zip(signs, Wl)]
        GE = StabGroup(ext)
        assert 5 * N - GE.rank == 0
        okall = True
        for ri, R in enumerate(ROTS):
            p = tuple(dir_perm(R)); ls = [y for y in Gp if y[0] == p][0]
            act = Action(lat, R, ls, ML[ri][0][2])
            for gen in ext:
                img = act.conj(to_poly(gen))
                val, _ = GE.code_poly_value(img)
                if abs(val - 1) > 1e-8: okall = False; break
            if not okall: break
        res[signs] = okall
    print(f'L={L}: Wilson-loop sign choices (x,y,z) giving a stabilizer state invariant under all 24 rotations:',
          [s for s, o in res.items() if o])
