# homomorphism check on random pairs: U(u)U(u') = U(uu') (lookup by u)
lookup = {key(u): U for u, U in els}
hom = all(np.allclose(U1 @ U2, lookup[key(u1 @ u2)]) for (u1, U1), (u2, U2) in itertools.product(els, els))
print('U is a representation of 2O on the matter pair:', hom)
minus = lookup[key(-np.eye(2))]
print('U(-1) equals the matter parity Z_up Z_dn:', np.allclose(minus, par))
print('U preserves n_up + n_dn and the matter parity:', all(np.allclose(U @ num @ U.conj().T, num) and np.allclose(U @ par @ U.conj().T, par) for _, U in els))
dbl = all(np.allclose(U @ cdag[s] @ U.conj().T, sum(u[t, s] * cdag[t] for t in range(2))) for u, U in els for s in range(2))
print('U c_s^dag U^dag = sum_t u_ts c_t^dag (the doublet transforms as spin-1/2):', dbl)
# squares of C2 lifts on the 1-particle doublet
c2 = [(u, U) for u, U in els if np.isclose(np.trace(u).real, 0) and np.allclose(u @ u, -np.eye(2))]
print('number of C2 lifts (order 4 in 2O):', len(c2), '; each squares to -1 on the doublet:', all(np.allclose((U @ U)[1:3, 1:3], -np.eye(2)) for _, U in c2))
