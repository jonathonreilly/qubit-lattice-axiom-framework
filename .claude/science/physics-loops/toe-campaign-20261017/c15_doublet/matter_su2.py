"""On-site spin-1/2 action on the matter pair (2 qubits: up, dn modes) for the 48 lifts of the cube rotations.
Checks: U(u) U(u') = U(u u'); U(-1) = matter parity; U preserves n_up + n_dn and the matter parity;
U c_s^dag U^dag = sum_s' u_{s's} c_s'^dag (doublet transforms as spin-1/2)."""
import itertools
import numpy as np
from scipy.linalg import expm
I2 = np.eye(2); X = np.array([[0, 1], [1, 0]]); Y = np.array([[0, -1j], [1j, 0]]); Z = np.diag([1, -1])
sp = np.array([[0, 0], [1, 0]])   # |0> -> |1> : creation in occupation basis (|0> empty, |1> occupied)
cdag = [np.kron(sp, I2), np.kron(Z, sp)]                 # JW: c_dn^dag carries Z_up
c = [m.conj().T for m in cdag]
num = sum(cd @ cc for cd, cc in zip(cdag, c))
par = np.kron(Z, Z)
pauli = [X, Y, Z]
S = [0.5 * sum(cdag[a] @ c[b] * pauli[k][a, b] for a in range(2) for b in range(2)) for k in range(3)]
def su2(axis, theta):
    n = np.array(axis, float); n /= np.linalg.norm(n)
    return expm(-0.5j * theta * sum(n[k] * pauli[k] for k in range(3)))
def Umat(axis, theta):
    n = np.array(axis, float); n /= np.linalg.norm(n)
    return expm(-1j * theta * sum(n[k] * S[k] for k in range(3)))
# 2O generated by C4z and C3(111) lifts
gens = [((0, 0, 1), np.pi / 2), ((1, 1, 1), 2 * np.pi / 3)]
els = [(np.eye(2, dtype=complex), np.eye(4, dtype=complex))]
key = lambda u: tuple(np.round(u.flatten(), 6))
seen = {key(els[0][0])}
frontier = list(els)
while frontier:
    nf = []
    for (u, U) in frontier:
        for ax, th in gens:
            u2 = su2(ax, th) @ u; U2 = Umat(ax, th) @ U
            if key(u2) not in seen:
                seen.add(key(u2)); nf.append((u2, U2)); els.append((u2, U2))
    frontier = nf
