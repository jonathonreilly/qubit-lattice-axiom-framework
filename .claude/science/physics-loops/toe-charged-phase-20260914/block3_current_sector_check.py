"""Checks of finite Fourier currents and affine integer Gaussian sectors.

Distinct routes: symbolic determinant, direct angle averages, character sums,
integer chain homotopy, direct versus Poisson lattice sums. Finite checks do
not establish a thermodynamic phase. Output includes all tested domains.
"""
from itertools import product, combinations
from pathlib import Path
import json, math
import numpy as np
from fractions import Fraction as F
from sympy import Matrix, symbols, expand

rows={}
# Exact one-plaquette scalar determinant; real symmetric hopping is an
# admissible member of the general nearest-neighbor matrix family.
z,M=symbols('z M',nonzero=True)
D=Matrix([[M,z,0,1],[1/z,M,1,0],[0,1,M,1],[1,0,1,M]])
det=expand(D.det());c=M**4-4*M**2+2
assert expand(det-(c-z-1/z))==0
W=expand(det*det.subs(z,1/z))
coeff={r:expand(W).coeff(z,r).subs(M,5) for r in range(-2,3)}
assert coeff=={-2:1,-1:-1054,0:277731,1:-1054,2:1}
assert expand(W-sum(expand(W).coeff(z,r)*z**r for r in range(-2,3)))==0
assert coeff[0]+2*coeff[1]+2*coeff[2]>0
rows['symbolic_scalar_determinant']={'determinant':str(det),'M':5,'paired_fourier_coefficients':{str(k):str(v) for k,v in coeff.items()},'negative_coefficients_despite_positive_weight':True}
# The four-link current of each coefficient is r times the oriented boundary.
C=np.array([[1,1,1,1]],dtype=int)
G=np.zeros((4,4),dtype=int)
for l in range(4):G[l,l]=-1;G[l,(l+1)%4]=1
assert not np.any(C@G)
for r in coeff:assert not np.any(G.T@(r*C[0]))
# Direct normalized Villain real Gaussian vs Fourier character sum.
def villain(theta,beta):
    n=np.arange(-30,31)
    return np.sqrt(2*np.pi*beta)*np.exp(-beta*(np.asarray(theta)[...,None]+2*np.pi*n)**2/2).sum(axis=-1)
def weight(theta):return (527-2*np.cos(theta))**2
partition=[]
for beta in [.2,1.,5.,20.]:
    ks=np.arange(-100,101);gw=np.exp(-ks**2/(2*beta))
    grid=2*np.pi*np.arange(32768)/32768
    direct=float(np.mean(villain(grid,beta)*weight(grid)))
    dual=sum(float(v)*math.exp(-r*r/(2*beta)) for r,v in coeff.items())
    assert abs(direct/dual-1)<1e-12
    for N in [2,3,5,9,17]:
        th=2*np.pi*np.arange(N)/N
        dn=float(np.mean(villain(th,beta)*weight(th)))
        cn=sum(float(v)*gw[(ks+r)%N==0].sum() for r,v in coeff.items())
        assert abs(dn/cn-1)<1e-12
        # Actual positive pure-gauge q law on this one-plaquette complex.
        qr=np.arange(-30,31);probs=np.exp(-(N*qr)**2/(2*beta));probs/=probs.sum()
        moment=float(probs@(qr**2)) # ||q||^2 / 4 edges = r^2.
        b=N*N/(16*beta)
        theta=float(np.exp(-b*np.arange(-1000,1001)**2/2).sum())
        bound=2*math.log(theta)/b
        assert moment<=bound+1e-13
        partition.append({'beta':beta,'N':N,'direct_partition':dn,'dual_partition':float(cn),'relative_error':abs(dn/cn-1),'pure_q_second_moment_per_edge':moment,'theta_density_bound':bound})
rows['direct_angles_vs_character_sums']=partition
# Affine sectors for A=(1,1,0): k=(s-n,n,r), kernel lattice generated by
# (-1,1,0),(0,0,1). Nonzero shifts occur for odd s and challenge the theta max.
sector=[]
for beta in [.15,.7,2.,8.]:
    v=np.arange(-100,101);n,r=np.meshgrid(v,v,indexing='ij')
    Z0=float(np.exp(-(2*n*n+r*r)/(2*beta)).sum())
    for s in range(-7,8):
        Z=float(np.exp(-((s-n)**2+n*n+r*r)/(2*beta)).sum())
        ratio=Z/Z0;lower=math.exp(-s*s/(2*beta));upper=math.exp(-s*s/(4*beta))
        assert lower*(1-1e-12)<=ratio<=upper*(1+1e-12)
        # Direct shifted lattice theta / Poisson dual; covol=sqrt(2).
        x=s/2
        direct_theta=float(np.exp(-(v+x)**2/beta).sum())
        poisson=math.sqrt(math.pi*beta)*float((np.exp(-math.pi**2*beta*v*v)*np.cos(2*math.pi*v*x)).sum())
        assert abs(direct_theta-poisson)<2e-14
        sector.append({'beta':beta,'s':s,'ratio':ratio,'integer_fill_lower':lower,'real_fill_upper':upper,'theta_poisson_error':abs(direct_theta-poisson)})
rows['affine_integer_gaussian_comparison']=sector
# Integer cochain homotopy and its transposed current filling, implemented
# directly here so this exploratory check has no hidden local helper input.
def box(d,L):
    cells=[[(p,S) for S in combinations(range(d),k) for p in product(*[range(L if i in S else L+1) for i in range(d)])] for k in range(d+1)]
    ix=[{v:i for i,v in enumerate(ck)} for ck in cells];Ds=[];Hs=[None]
    for k in range(d):
        a=np.zeros((len(cells[k+1]),len(cells[k])),dtype=np.int64)
        for row,(p,S) in enumerate(cells[k+1]):
            for j,axis in enumerate(S):
                R=tuple(v for v in S if v!=axis);up=list(p);up[axis]+=1
                a[row,ix[k][tuple(up),R]]+=(-1)**j;a[row,ix[k][p,R]]-=(-1)**j
        Ds.append(a)
    for k in range(1,d+1):
        h=np.zeros((len(cells[k-1]),len(cells[k])),dtype=np.int64)
        for row,(y,R) in enumerate(cells[k-1]):
            for axis in range(min(R) if R else d):
                for t in range(y[axis]):
                    p=tuple(0 if j<axis else t if j==axis else y[j] for j in range(d))
                    h[row,ix[k][p,(axis,)+R]]+=1
        Hs.append(h)
    return cells,Ds,Hs
rng=np.random.default_rng(71403);fills=[]
for d,L in [(2,1),(2,3),(3,1),(3,2),(4,1)]:
    cells,Ds,Hs=box(d,L);G,C=Ds[:2]
    assert np.array_equal(G@Hs[1]+Hs[2]@C,np.eye(len(cells[1]),dtype=int))
    norm2=float(np.linalg.norm(C.astype(float),2)**2);assert norm2<=4*d+1e-12
    for _ in range(20):
        k=rng.integers(-3,4,size=len(cells[2]));s=C.T@k;fill=Hs[2].T@s
        assert not np.any(G.T@s)
        assert np.array_equal(C.T@fill,s)
    fills.append({'d':d,'L':L,'cells':[len(v) for v in cells],'curl_norm_squared':norm2,'integer_current_fill_checks':20})
rows['current_homotopy_and_norm']=fills
# Per-edge screening threshold and the distinct no-alias threshold.
for m in [1,2,4]:
    for N in [2*m+1,4*m,4*m+1]:
        for q in range(-5,6):
            for j in range(-2*m,2*m+1):
                assert abs(N*q-j)>=(N-2*m)*abs(q)
        residues=[j%N for j in range(-2*m,2*m+1)]
        assert (len(set(residues))==len(residues))==(N>4*m)
rows['distinct_screening_and_injectivity_thresholds']=True
# The canonical q weight can stay negative even after summing fermion
# currents: one square, M=5>4, beta=1, N=7, q=one boundary.
# x=exp(-1/2) is trapped by exact rational Taylor arithmetic.
ehalf=sum(F(1,2)**n/math.factorial(n) for n in range(21))
tail=F(1,2)**21/math.factorial(21)/(1-F(1,44))
xlo=F(60653,100000);xhi=F(60654,100000)
assert 1/(ehalf+tail)>xlo and 1/ehalf<xhi
upper=1-1054*xlo**11+277731*xhi**24-1054*xlo**39+xhi**56
assert upper<0
rows['negative_marginalized_cyclic_q_weight']={'M':5,'beta':1,'N':7,'q_cycle':1,'scaled_weight_upper_exact':str(upper),'scaled_weight_upper_float':float(upper),'interval_for_exp_minus_half':[str(xlo),str(xhi)],'claim':'canonical Fourier alias weight after summing j is negative; original angle law remains positive'}
# The physical-source identity is checked against the positive joint (theta,n)
# integral, not only by differentiating the same character formula.
source=[]
for beta,N in [(1.,7),(5.,9),(.2,5)]:
    theta=2*np.pi*np.arange(N)/N;ns=np.arange(-30,31)
    field=theta[:,None]+2*np.pi*ns
    base=np.exp(-beta*field**2/2)*weight(theta)[:,None]
    norm=base.sum();mean=float((base*field).sum()/norm)
    var=float((base*field**2).sum()/norm-mean**2)
    ks=np.arange(-100,101);dual_weights=np.zeros(len(ks))
    for j,w in coeff.items():dual_weights+=float(w)*np.exp(-ks**2/(2*beta))*((ks+j)%N==0)
    dualnorm=dual_weights.sum();dualmean=dual_weights@ks/dualnorm
    signedvar=dual_weights@(ks**2)/dualnorm-dualmean**2
    assert abs(mean)<1e-12 and abs(var-(1/beta-signedvar/beta**2))<1e-12
    for h in [-.3,.1,.4]:
        direct=float((base*np.exp(h*field)).sum()/norm)
        predicted=math.exp(h*h/(2*beta))*np.sum(dual_weights*np.exp(-1j*ks*h/beta))/dualnorm
        assert abs(predicted.imag)<1e-13 and abs(direct-predicted.real)<1e-12
    source.append({'beta':beta,'N':N,'physical_variance':var,'signed_dual_variance':float(signedvar),'source_checks':[-.3,.1,.4]})
rows['physical_source_identity']=source
# Closed-chain extension, not a phase result.
print(json.dumps(rows,indent=2),flush=True)
Path(__file__).with_name('BLOCK3_CURRENT_SECTOR_CHECK.json').write_text(json.dumps(rows,indent=2)+'\n')
