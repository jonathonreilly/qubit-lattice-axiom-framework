#!/usr/bin/env python3
"""C2b / KI+ group theory: which point groups G of Z^3 x Z_tau (a_tau = a), containing the
Lattice axiom's proper cubic rotations O on the spatial axes, make the dimension-4 kinetic
forms of a vector-index field and of the Maxwell field unique?

For every subgroup G of B4 that contains O (time axis 0 fixed, O acting on axes 1..3) we compute
by exact character averaging (integer matrices, Fraction arithmetic):
  n_S   = dim (Sym^2 R^4)^G        rank-2 symmetric invariants (scalar d_mu phi d_nu phi, gamma_mu d_nu
                                    symmetric part)
  n_A   = dim (Lambda^2 R^4)^G      antisymmetric rank-2 invariants (extra psibar gamma_[mu d_nu] psi terms)
  n_F   = dim (Sym^2 Lambda^2)^G    quadratic forms in F_{mu nu}
A 'KI+-sufficient' group has n_S = 1, n_A = 0, and n_F = 1 (if G contains improper elements) or
n_F = 2 with the second invariant the pseudoscalar F Ftilde (if G is proper).
The minimal such groups are reported. Claim type: exact enumeration (finite group, exact arithmetic).
"""
import itertools
import sys
from fractions import Fraction
import numpy as np

PASS = FAIL = 0


def check(name, ok, tag='exact'):
    global PASS, FAIL
    PASS += bool(ok); FAIL += (not ok)
    print(f"{'PASS' if ok else 'FAIL'} [{tag}] {name}", flush=True)


def signed_perms(n):
    out = []
    for p in itertools.permutations(range(n)):
        for s in itertools.product((1, -1), repeat=n):
            M = np.zeros((n, n), dtype=np.int64)
            for i in range(n):
                M[p[i], i] = s[i]
            out.append(M)
    return out


B4 = signed_perms(4)
key = lambda M: M.tobytes()
idx = {key(M): i for i, M in enumerate(B4)}
mul = np.zeros((384, 384), dtype=np.int64)
for i, A in enumerate(B4):
    for j, Bm in enumerate(B4):
        mul[i, j] = idx[key(A @ Bm)]

# O: proper rotations of axes 1..3, time axis fixed
O = [i for i, M in enumerate(B4) if M[0, 0] == 1 and round(np.linalg.det(M[1:, 1:])) == 1]
check('|O| = 24 (proper cubic rotations on the spatial axes, time fixed)', len(O) == 24)


def closure(gens):
    """Subgroup generated by gens (BFS with right multiplication by generators)."""
    gens = list(set(gens))
    e = idx[key(np.eye(4, dtype=np.int64))]
    S = {e}; frontier = [e]
    while frontier:
        new = []
        for a in frontier:
            for g in gens:
                c = mul[a, g]
                if c not in S:
                    S.add(c); new.append(c)
        frontier = new
    return frozenset(S)


# Lambda^2 representation from 2-minors
pairs = list(itertools.combinations(range(4), 2))


def lam2(M):
    L = np.zeros((6, 6), dtype=np.int64)
    for a, (i, j) in enumerate(pairs):
        for b, (k, l) in enumerate(pairs):
            L[a, b] = M[i, k]*M[j, l] - M[i, l]*M[j, k]
    return L


chiV = [int(np.trace(M)) for M in B4]
chiV2 = [int(np.trace(M @ M)) for M in B4]
L2 = [lam2(M) for M in B4]
chiL = [int(np.trace(L)) for L in L2]
chiL2 = [int(np.trace(L @ L)) for L in L2]
det = [int(round(np.linalg.det(M))) for M in B4]


def counts(G):
    n = len(G)
    nS = Fraction(sum(chiV[g]**2 + chiV2[g] for g in G), 2*n)
    nA = Fraction(sum(chiV[g]**2 - chiV2[g] for g in G), 2*n)
    nF = Fraction(sum(chiL[g]**2 + chiL2[g] for g in G), 2*n)
    return nS, nA, nF


def is_FFtilde_extra(G):
    """For a proper group with n_F = 2, check that the invariant space is span{F^2, F Ftilde}."""
    # projector onto invariants in Sym^2(Lambda^2) realised on 6x6 symmetric matrices Q -> L^T Q L
    basis = []
    for a in range(6):
        for b in range(a, 6):
            E = np.zeros((6, 6)); E[a, b] = E[b, a] = 1; basis.append(E)
    P = np.zeros((21, 21))
    for g in G:
        L = L2[g].astype(float)
        for c, E in enumerate(basis):
            T = L.T @ E @ L
            P[:, c] += np.array([T[a, b] for a in range(6) for b in range(a, 6)])
    P /= len(G)
    # invariant space = image of P; compare with span{I6, eps} (F^2 and F Ftilde in the minor basis)
    eps = np.zeros((6, 6))
    for a, (i, j) in enumerate(pairs):
        for b, (k, l) in enumerate(pairs):
            if len({i, j, k, l}) == 4:
                perm = [i, j, k, l]
                sgn = round(np.linalg.det(np.eye(4)[perm]))
                eps[a, b] = sgn
    vec = lambda Q: np.array([Q[a, b] for a in range(6) for b in range(a, 6)])
    target = np.column_stack([vec(np.eye(6)), vec(eps)])
    r_img = np.linalg.matrix_rank(P, 1e-9)
    r_join = np.linalg.matrix_rank(np.column_stack([P, target]), 1e-9)
    return r_img == 2 and r_join == 2


# enumerate all subgroups of B4 containing O: close O with 1 and 2 extra generators (B4 is 2-generated
# over O at most index 16; we iterate until no new groups appear)
Ogens = [g for g in O]
groups = {closure(Ogens)}
frontier = set(groups)
while frontier:
    new = set()
    for G in frontier:
        for g in range(384):
            if g not in G:
                H = closure(list(G) + [g])
                if H not in groups:
                    new.add(H)
    groups |= new
    frontier = new
print(f"subgroups of B4 containing O: {len(groups)}; orders {sorted(len(G) for G in groups)}")
check('B4 itself is among them, order 384', any(len(G) == 384 for G in groups))

rows = []
for G in sorted(groups, key=len):
    nS, nA, nF = counts(G)
    proper = all(det[g] == 1 for g in G)
    time_mixing = any(B4[g][0, 0] == 0 for g in G)
    has_T = any(B4[g][0, 0] == -1 for g in G)
    ok = nS == 1 and nA == 0 and ((nF == 1) or (proper and nF == 2 and is_FFtilde_extra(G)))
    rows.append((len(G), proper, time_mixing, has_T, nS, nA, nF, ok, G))
    print(f"  |G|={len(G):3d} proper={proper!s:5} mixes t with space={time_mixing!s:5} contains t->-t={has_T!s:5}"
          f"  n_S={nS} n_A={nA} n_F={nF}  KI+-sufficient={ok}")

suff = [r for r in rows if r[7]]
minorder = min(r[0] for r in suff)
mins = [r for r in suff if r[0] == minorder]
print(f"minimal KI+-sufficient order: {minorder}; number of such groups: {len(mins)}")
check('O alone gives n_S = 2 (c_t, c_s free) -- reproduces C2 count', counts(closure(O))[0] == 2)
check('O alone gives n_F = 3 (E^2, B^2, E.B) -- reproduces C2 review count', counts(closure(O))[2] == 3)
check('every KI+-sufficient group mixes time with space', all(r[2] for r in suff))
check('a proper (det = +1) KI+-sufficient group exists, so time reflection is not needed', any(r[1] for r in suff))
# describe a minimal group
G = mins[0][8]
print("a minimal group: proper =", mins[0][1], ", contains time reversal =", mins[0][3])
# does a minimal group contain the 90-degree (t,x) rotation?  find time-mixing elements' orders
from collections import Counter
orders = Counter()
for g in G:
    if B4[g][0, 0] == 0:
        k, M = 1, B4[g].copy()
        while not np.array_equal(M, np.eye(4, dtype=np.int64)):
            M = M @ B4[g]; k += 1
        orders[k] += 1
print("orders of time-mixing elements in that minimal group:", dict(orders))
# is the minimal group the smallest group containing O and the 3-cycle-free 'axis 4-cycle'?
cyc = np.zeros((4, 4), dtype=np.int64)
for i in range(4):
    cyc[(i+1) % 4, i] = 1          # t->x->y->z->t (det -1: odd permutation)
rot_tx = np.eye(4, dtype=np.int64); rot_tx[0, 0] = rot_tx[1, 1] = 0; rot_tx[0, 1] = -1; rot_tx[1, 0] = 1
Gc = closure(O + [idx[key(cyc)]]); Gr = closure(O + [idx[key(rot_tx)]])
print(f"<O, 4-cycle t->x->y->z->t>: order {len(Gc)}, counts {counts(Gc)};  <O, 90deg (t,x) rotation>: order {len(Gr)}, counts {counts(Gr)}")
check('<O, 90-degree (t,x) rotation> is KI+-sufficient', any(r[8] == Gr and r[7] for r in rows))
print(f"TOTAL: PASS={PASS} FAIL={FAIL}")
sys.exit(1 if FAIL else 0)
