#!/usr/bin/env python3
"""C4 step 5: an implementation-independent recount of the O-covariant radius-1 classification.

Different route from c4_02 (no F2 linear algebra, no symplectic vectors, no shared enumerator):
  * For each soldering action rho and each generator label a in {X, Z}, the stabiliser
    S_a = {R : rho(R) sigma_a = +- sigma_a} is computed; a covariant image of sigma_a must be a
    signed Pauli string with beta_R(P) = eps_R P for R in S_a.  Candidates are generated by assigning
    labels to S_a-orbit representatives of the cell and propagating, then checked with explicit
    2x2 complex Pauli matrices on each site (phases tracked by matrix products, not tables).
  * If rho links X to Z, P_Z is derived from P_X; otherwise P_Z runs over its own candidates.
  * QCA conditions: P_X, P_Z Hermitian Pauli strings; {P_X,P_Z} = 0; [P_a, T_t P_b] = 0 for all
    t != 0 (explicit commutation count of anticommuting sites); full covariance for all 24 R checked
    on X, Y, Z with Y = i X Z by explicit matrix phases.
Only the list of 24 matrices of O and the menu formulas are shared with the other scripts
(re-derived here).
"""
import itertools
import numpy as np

P = F = 0


def check(name, ok):
    global P, F
    if ok:
        P += 1
        print('PASS', name, flush=True)
    else:
        F += 1
        print('FAIL', name, flush=True)


O = []
for p in itertools.permutations(range(3)):
    for s in itertools.product((1, -1), repeat=3):
        M = np.zeros((3, 3), int)
        for i in range(3):
            M[p[i], i] = s[i]
        if round(np.linalg.det(M)) == 1:
            O.append(M)


def psign(M):
    return int(round(np.linalg.det(np.abs(M))))


Hf = np.array([[-1, 0, 0], [0, 0, 1], [0, 1, 0]])
ACT = {
    'trivial': lambda M: np.eye(3, dtype=int),
    'sign': lambda M: np.diag([1, psign(M), psign(M)]),
    'sign-f': lambda M: np.eye(3, dtype=int) if psign(M) == 1 else Hf,
    'axis': lambda M: psign(M) * np.abs(M),
    'full': lambda M: M,
}
SM = [np.eye(2, dtype=complex), np.array([[0, 1], [1, 0]], complex), np.array([[0, -1j], [1j, 0]], complex),
      np.array([[1, 0], [0, -1]], complex)]
CELL = list(itertools.product((-1, 0, 1), repeat=3))


def site_image(Qm, a):
    """rotated single-site label: sum_b Q[b,a-1] sigma_b -> (b, sign)."""
    col = Qm[:, a - 1]
    b = int(np.nonzero(col)[0][0])
    return b + 1, int(col[b])


# A signed Pauli string: (coef complex in {+-1, +-i}, {site: label})
def rot_string(M, Qm, Pst):
    c, d = Pst
    out = {}
    for s, a in d.items():
        b, sg = site_image(Qm, a)
        c = c * sg
        out[tuple(int(v) for v in M @ np.array(s))] = b
    return (c, out)


def mul(A, B):
    c = A[0] * B[0]
    d = dict(A[1])
    for s, b in B[1].items():
        a = d.get(s, 0)
        m = SM[a] @ SM[b]
        # identify m = phase * sigma_k
        for k in range(4):
            tr = np.trace(SM[k].conj().T @ m) / 2
            if abs(tr) > 0.5:
                c = c * tr
                if k:
                    d[s] = k
                else:
                    d.pop(s, None)
                break
    return (complex(round(c.real), round(c.imag)), d)


def same(A, B):
    return abs(A[0] - B[0]) < 1e-9 and A[1] == B[1]


def anticomm_count(A, B):
    return sum(1 for s, a in A[1].items() if B[1].get(s, 0) not in (0, a))


def shift(A, t):
    return (A[0], {(s[0] + t[0], s[1] + t[1], s[2] + t[2]): a for s, a in A[1].items()})


SHIFTS = [t for t in itertools.product(range(-2, 3), repeat=3) if t != (0, 0, 0)]


def candidates(act, a):
    Q = [ACT[act](M) for M in O]
    stab = [(i, site_image(Q[i], a)[1]) for i in range(24) if site_image(Q[i], a)[0] == a]
    # orbits of stab on cell
    orbits, seen = [], set()
    for r in CELL:
        if r in seen:
            continue
        orb = {}
        for i, _ in stab:
            q = tuple(int(v) for v in O[i] @ np.array(r))
            orb.setdefault(q, i)
        seen |= set(orb)
        orbits.append((r, orb))
    out = []
    for labs in itertools.product(range(4), repeat=len(orbits)):
        d = {}
        ok = True
        for (r, orb), l in zip(orbits, labs):
            if l == 0:
                continue
            for q, i in orb.items():
                d[q] = site_image(Q[i], l)[0]
        Pst = (1 + 0j, d)
        for i, eps in stab:
            img = rot_string(O[i], Q[i], Pst)
            if img[1] != d or abs(img[0] - eps) > 1e-9:
                ok = False
                break
        if ok:
            out.append(Pst)
            out.append((-1 + 0j, dict(d)))
    return Q, out


def is_qca(PX, PZ):
    if anticomm_count(PX, PZ) % 2 != 1:
        return False
    for t in SHIFTS:
        for A, B in ((PX, PX), (PZ, PZ), (PX, PZ)):
            if anticomm_count(A, shift(B, t)) % 2:
                return False
    return True


def covariant(PX, PZ, Q):
    PY = mul((1j, {}), mul(PX, PZ))
    im = {1: PX, 2: PY, 3: PZ}
    for i in range(24):
        for a in (1, 2, 3):
            b, sg = site_image(Q[i], a)
            lhs = (im[b][0] * sg, im[b][1])
            rhs = rot_string(O[i], Q[i], im[a])
            if not same(lhs, rhs):
                return False
    return True


EXPECT = {'trivial': 528, 'sign': 176, 'sign-f': 32, 'axis': 1, 'full': 1}  # from c4_02 (other route)
for act in ('trivial', 'sign', 'sign-f', 'axis', 'full'):
    Q, cX = candidates(act, 1)
    _, cZ = candidates(act, 3)
    link = [(i, site_image(Q[i], 1)) for i in range(24) if site_image(Q[i], 1)[0] == 3]
    cX = [c for c in cX if all(anticomm_count(c, shift(c, t)) % 2 == 0 for t in SHIFTS)]
    cZ = [c for c in cZ if all(anticomm_count(c, shift(c, t)) % 2 == 0 for t in SHIFTS)]
    found = []
    for PX in cX:
        if link:
            i, (_, sg) = link[0]
            img = rot_string(O[i], Q[i], PX)
            Zs = [(img[0] * sg, img[1])]
        else:
            Zs = cZ
        for PZ in Zs:
            if is_qca(PX, PZ) and covariant(PX, PZ, Q):
                found.append((PX, PZ))
    print(f'{act}: {len(cX)} self-commuting X-candidates, {len(found)} signed covariant QCAs')
    check(f'{act}: independent recount = {EXPECT[act]} signed O-covariant radius-1 QCAs', len(found) == EXPECT[act])
    if act in ('axis', 'full'):
        PX, PZ = found[0]
        check(f'{act}: the unique one is the identity', same(PX, (1, {(0, 0, 0): 1})) and same(PZ, (1, {(0, 0, 0): 3})))
print(f'TOTAL: PASS={P} FAIL={F}')
