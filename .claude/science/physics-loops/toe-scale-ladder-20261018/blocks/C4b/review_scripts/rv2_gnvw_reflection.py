#!/usr/bin/env python3
"""Reviewer script rv2 (independent): GNVW index from the support-algebra DEFINITION, and (I7).

Chain of qubits on a ring of NQ = 10 sites, grouped into cells of 2 qubits (Hilbert dim d = 4),
cells c = {2c, 2c+1}, c = 0..4.  All test QCAs move information by <= 2 qubits, i.e. they are
nearest-neighbour in cells, and no light cone wraps the ring for the window used.

GNVW (CMP 310, 419 (2012)), as recalled: for a nearest-neighbour QCA, with
  A = A_{2x} (x) A_{2x+1},  R_left = S(alpha(A), A_{2x-1} (x) A_{2x}),  R_right = S(alpha(A), A_{2x+1} (x) A_{2x+2}),
alpha(A) = R_left (x) R_right, and ind(alpha) = sqrt(dim R_right) / d   (d = dim of the Hilbert space of a cell).
S(B, C) = support algebra of B on the factor C = algebra generated by all slices of elements of B.
Here: 2x = cell 2, 2x+1 = cell 3; R_left on cells (1,2), R_right on cells (3,4).

Consequence checked: dim R_left * dim R_right = dim alpha(A) = d^4, and the reflection
P: qubit j -> NQ-1-j (cell c -> 4-c, a cell-wise reflection) gives ind(P alpha P^-1) = 1/ind(alpha).
"""
import numpy as np

NQ = 10
d = 4
rng = np.random.default_rng(7)
P_ = F_ = 0


def check(name, ok, extra=''):
    global P_, F_
    P_ += ok
    F_ += (not ok)
    print('PASS' if ok else 'FAIL', name, ('::' + extra) if extra else '')


I2 = np.eye(2)
X = np.array([[0, 1], [1, 0]], complex)
Z = np.diag([1., -1]).astype(complex)


def op_on(single, q):
    """operator tensor of shape (2,)*2NQ: index order (out_0..out_{NQ-1}, in_0..in_{NQ-1})."""
    mats = [I2.astype(complex)] * NQ
    mats = list(mats)
    mats[q] = single
    T = mats[0]
    for m in mats[1:]:
        T = np.kron(T, m)
    return T.reshape((2,) * (2 * NQ))


def apply_gate(T, G, q1, q2):
    """T -> G T G^dag for two-qubit gate G (4x4) on qubits (q1,q2)."""
    G4 = G.reshape(2, 2, 2, 2)
    # left multiply on out indices q1,q2
    T = np.tensordot(G4, T, axes=([2, 3], [q1, q2]))
    T = np.moveaxis(T, [0, 1], [q1, q2])
    # right multiply by G^dag on in indices
    Gd4 = G.conj().T.reshape(2, 2, 2, 2)
    T = np.tensordot(T, Gd4, axes=([NQ + q1, NQ + q2], [0, 1]))
    T = np.moveaxis(T, [2 * NQ - 2, 2 * NQ - 1], [NQ + q1, NQ + q2])
    return T


def apply_perm(T, f):
    """site permutation: operator at q -> operator at f(q)."""
    src = list(range(2 * NQ))
    newT = np.empty_like(T)
    axes = [0] * (2 * NQ)
    for q in range(NQ):
        axes[f(q)] = q
        axes[NQ + f(q)] = NQ + q
    return np.transpose(T, axes)


def rand_u(n):
    A = rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n))
    Q, R = np.linalg.qr(A)
    return Q * (np.diag(R) / abs(np.diag(R)))


# QCA = list of ops: ('perm', f) or ('gate', G, q1, q2); applied in order (Heisenberg: alpha = Ad(U), U = product)
def apply_qca(T, ops):
    for op in ops:
        if op[0] == 'perm':
            T = apply_perm(T, op[1])
        else:
            T = apply_gate(T, op[1], op[2], op[3])
    return T


shiftR = ('perm', lambda q: (q + 1) % NQ)
shiftL = ('perm', lambda q: (q - 1) % NQ)
refl = ('perm', lambda q: NQ - 1 - q)


def brick(offset, seed_gates):
    return [('gate', seed_gates[(q // 2)], q % NQ, (q + 1) % NQ) for q in range(offset, offset + NQ, 2)]


def gates():
    return [rand_u(4) for _ in range(NQ)]


def reflect(ops):
    """P alpha P^-1 as a list: Heisenberg order: first P^-1 (=P), then alpha, then P."""
    return [refl] + ops + [refl]


def slices(T, keep):
    """span of slices of operator T on qubits `keep` (as matrices on keep), assuming other legs arbitrary."""
    other = [q for q in range(NQ) if q not in keep]
    perm = keep + [NQ + q for q in keep] + other + [NQ + q for q in other]
    M = np.transpose(T, perm).reshape(4 ** len(keep), -1)
    U, s, Vh = np.linalg.svd(M, full_matrices=False)
    r = int((s > 1e-9 * s[0]).sum())
    k = len(keep)
    return [U[:, i].reshape(2 ** k, 2 ** k) for i in range(r)]


def algebra_dim(gens, n):
    """dimension of the unital *-algebra generated by gens (n x n matrices)."""
    basis = [np.eye(n, dtype=complex).ravel()]
    cur = np.array(basis)

    def add(vs, cur):
        M = np.vstack([cur] + [v.ravel()[None, :] for v in vs])
        U, s, Vh = np.linalg.svd(M, full_matrices=False)
        r = int((s > 1e-8 * s[0]).sum())
        return Vh[:r]
    cur = add(gens + [g.conj().T for g in gens], cur)
    while True:
        mats = [v.reshape(n, n) for v in cur]
        prods = [a @ b for a in mats for b in mats]
        new = add(prods, cur)
        if new.shape[0] == cur.shape[0]:
            return cur.shape[0]
        cur = new


def index(ops):
    # A = cells 2,3 = qubits 4..7; generators X,Z on each
    imgs = [apply_qca(op_on(s, q), ops) for q in range(4, 8) for s in (X, Z)]
    for T in imgs:   # support check: image inside cells 1..4 = qubits 2..9
        M = np.transpose(T, [0, 1, NQ, NQ + 1] + [q for q in range(2, NQ)] + [NQ + q for q in range(2, NQ)]).reshape(16, -1)
        # must be identity (x) something on qubits 0,1
        assert np.linalg.matrix_rank(M, tol=1e-9) == 1
    left_keep, right_keep = [2, 3, 4, 5], [6, 7, 8, 9]
    gL = [s for T in imgs for s in slices(T, left_keep)]
    gR = [s for T in imgs for s in slices(T, right_keep)]
    dL = algebra_dim(gL, 16)
    dR = algebra_dim(gR, 16)
    return np.sqrt(dR) / d, dL, dR


cases = {
    'identity': ([], 1.0),
    'qubit right shift': ([shiftR], 2.0),
    'qubit left shift': ([shiftL], 0.5),
    'random brickwork depth 2': (brick(0, gates()) + brick(1, gates()), 1.0),
    'right shift o brickwork': (brick(1, gates()) + [shiftR], 2.0),
    'left shift o brickwork': ([shiftL] + brick(0, gates()), 0.5),
    'shift^2 (two qubits = one cell)': ([shiftR, shiftR], 4.0),
}
for name, (ops, expect) in cases.items():
    ind, dL, dR = index(ops)
    indP, dLP, dRP = index(reflect(ops))
    print(f'{name:34s} ind={ind:.6f} (dimRL={dL}, dimRR={dR})   ind(P a P^-1)={indP:.6f} (dimRL={dLP}, dimRR={dRP})')
    check(f'{name}: ind = {expect}', abs(ind - expect) < 1e-9)
    check(f'{name}: dim R_L * dim R_R = d^4 = 256', dL * dR == 256)
    check(f'{name}: (I7) ind(P a P^-1) = 1/ind(a)', abs(indP * ind - 1) < 1e-9)
print(f'TOTAL: PASS={P_} FAIL={F_}')
