#!/usr/bin/env python3
"""Lemma 4.5h of parts/hard-core--independent.md, over all vertex patterns.

On the torus with n = 2 blocks per side, every vertex of the block lattice sees all 16 blocks, so a set of
removed blocks is a pattern of kept orthants around a vertex. There are 2^16 sets, and up to the group of order
384 generated by coordinate permutations and translations of Z_2^4, 402 classes (I first wrote 222, which is the count that also identifies complements). Patterns on larger
tori that are more than a block apart look locally like one of these.

For each class with at least one coarse plaquette with four chart bonds, at L = 5 and L = 7, compute a lower
estimate of phi(L) := max |f_p| / max |F'|: over HC_SAMPLES random coarse data, B' uniform in [-1, 1] on chart bonds,
with the same seeds at both L, then the lift by conjugate gradients as in checks/hard-core--independent_lift_sup.py.
    s_est(pattern) := log( phi(5) / phi(7) ) / log(7 / 5).

Pre-registered criteria, written before the first run.
    PASS-SCAN: s_est >= 0.5 for every pattern.
    WARN-SCAN: some pattern has 0.2 <= s_est < 0.5. Report those, and rerun them with the linear program.
    FAIL-SCAN: some pattern has s_est < 0.2. Then look at that pattern with the linear program and larger L
    before anything else, since it might have no decay, against Lemma 4.5h.
    Random data give only lower estimates of phi, so a low s_est can be an artefact of sampling at a pattern where
    the worst data are rare. Patterns where phi(7) is below 1e-6 (the lift is flat, no curvature to carry) are skipped.

Second stage, criteria written before it runs: for masks given in HC_MASKS (the lowest s_est of the scan, and
those with a loop in the kept pattern), the linear program of lift_sup.py with HC_TOP plaquettes at L = 5, 7, 9.
    s_lp := log( phi(5) / phi(9) ) / log(9 / 5).
    PASS-LP: s_lp >= 0.6 for all. FAIL-LP: s_lp < 0.3 for some. Neither: report.

Run under the numeric lock, BLAS threads 1, nice, RSS checked against 2 GB.
"""
import importlib.util
import itertools
import os
import pathlib
import sys
import time

os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
os.environ.setdefault("VECLIB_MAXIMUM_THREADS", "1")

import numpy as np
import scipy.sparse.linalg as sl

HERE = pathlib.Path(__file__)
spec = importlib.util.spec_from_file_location("coer_g", HERE.with_name("hard-core--independent_coer_g.py"))
cg_mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cg_mod)
spec2 = importlib.util.spec_from_file_location("lift_sup", HERE.with_name("hard-core--independent_lift_sup.py"))
ls_mod = importlib.util.module_from_spec(spec2)
spec2.loader.exec_module(ls_mod)

DIM = 4
BLOCKS = list(itertools.product(range(2), repeat=DIM))
INDEX = {b: i for i, b in enumerate(BLOCKS)}


def group():
    out = []
    for perm in itertools.permutations(range(DIM)):
        for flip in itertools.product(range(2), repeat=DIM):
            table = []
            for b in BLOCKS:
                c = tuple((b[perm[i]] + flip[i]) % 2 for i in range(DIM))
                table.append(INDEX[c])
            out.append(table)
    return out


def classes():
    G = group()
    seen = np.zeros(2**16, dtype=bool)
    reps = []
    for mask in range(2**16):
        if seen[mask]:
            continue
        reps.append(mask)
        for table in G:
            m = 0
            for i in range(16):
                if mask >> i & 1:
                    m |= 1 << table[i]
            seen[m] = True
    return reps


def phi_est(L, removed, seed, samples):
    Dd, Ds, Q, cross, nl, block_id, site_ok, nsites = cg_mod.build(L, 2, removed)
    pi0, nb, counts = cg_mod.block_proj(block_id, site_ok, nsites)
    index = ls_mod.chart_bonds(removed)
    D = ls_mod.coarse_d(index)
    nbonds = Q.shape[0]
    if nbonds == 0 or D.shape[0] == 0:
        return None
    QQinv = np.linalg.pinv((Q @ Q.T).toarray())
    Qt = Q.T.tocsr()

    def proj(v):
        return v - Qt @ (QQinv @ (Q @ v))

    def h0(v):
        return Dd.T @ (Dd @ v) + Ds.T @ pi0(Ds @ v)

    op = sl.LinearOperator((nl, nl), matvec=lambda v: proj(h0(proj(v))), dtype=float)
    rng = np.random.default_rng(seed)
    best = 0.0
    for _ in range(samples):
        data = rng.uniform(-1, 1, nbonds)
        cf = np.abs(D @ data).max()
        if cf < 1e-9:
            continue
        a_p = Qt @ (QQinv @ data)
        rhs = -proj(h0(a_p))
        x, info = sl.cg(op, rhs, rtol=1e-7, maxiter=3000)
        f = Dd @ (a_p + proj(x))
        best = max(best, float(np.abs(f).max()) / cf)
    cg_mod.check_rss()
    return best


def main_lp(masks):
    worst = 10.0
    for mask in masks:
        removed = [BLOCKS[i] for i in range(16) if mask >> i & 1]
        res = {L: ls_mod.run_pattern(L, removed, f"m{mask}") for L in (5, 7, 9)}
        s = np.log(res[5] / res[9]) / np.log(9 / 5)
        print(f"mask={mask} s_lp={s:.3f}", flush=True)
        worst = min(worst, s)
    print("FAIL-LP" if worst < 0.3 else ("PASS-LP" if worst >= 0.6 else "NEITHER-LP"))


def main():
    if os.environ.get("HC_MASKS"):
        main_lp([int(a) for a in os.environ["HC_MASKS"].split(",")])
        return
    samples = int(os.environ.get("HC_SAMPLES", "6"))
    reps = classes()
    print(f"classes: {len(reps)}", flush=True)
    worst = []
    t0 = time.time()
    done = 0
    for mask in reps:
        removed = [BLOCKS[i] for i in range(16) if mask >> i & 1]
        if len(removed) == 16:
            continue
        index = ls_mod.chart_bonds(removed)
        D = ls_mod.coarse_d(index) if index else np.zeros((0, 0))
        if D.shape[0] == 0:
            continue
        p5 = phi_est(5, removed, mask, samples)
        p7 = phi_est(7, removed, mask, samples)
        done += 1
        if p5 is None or p7 is None or p7 < 1e-6:
            continue
        s = np.log(p5 / p7) / np.log(7 / 5)
        worst.append((s, mask, p5, p7, len(removed)))
        print(f"mask={mask:5d} removed={len(removed):2d} coarse={D.shape[0]:3d} phi5={p5:.4f} phi7={p7:.4f} s={s:.3f} t={time.time()-t0:.0f}", flush=True)
    worst.sort()
    print("lowest:", [(round(w[0], 3), w[1]) for w in worst[:10]])
    smin = worst[0][0]
    print(f"patterns run: {done}, s_min = {smin:.3f}")
    print("FAIL-SCAN" if smin < 0.2 else ("WARN-SCAN" if smin < 0.5 else "PASS-SCAN"))


if __name__ == "__main__":
    main()
