def gens_fibre_last():
    """Generators with base = qubits (0,1), fibre = qubit 2."""
    T = []
    for l in lam:
        M = np.zeros((4, 4), dtype=complex); M[:3, :3] = l / 2
        T.append(np.kron(U @ M @ U.conj().T, np.eye(2)))
    J = [np.kron(np.eye(4), s) for s in (sx, sy, sz)]
    Psym = U @ np.diag([1, 1, 1, 0]) @ U.conj().T
    Y = np.kron((1 / 3) * Psym - (np.eye(4) - Psym), np.eye(2))
    return T, J, Y


def perm_matrix(perm):
    """Matrix moving tensor factor i -> perm[i] on (C^2)^3 (basis |b0 b1 b2>)."""
    P = np.zeros((8, 8))
    for idx, b in enumerate(itertools.product([0, 1], repeat=3)):
        nb = [0, 0, 0]
        for i in range(3):
            nb[perm[i]] = b[i]
        P[int("".join(map(str, nb)), 2), idx] = 1
    return P


