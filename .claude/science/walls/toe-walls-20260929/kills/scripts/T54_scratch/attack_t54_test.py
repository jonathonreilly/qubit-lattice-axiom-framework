print(" dim of span of the 3 axis-conjugates (before closure):", dim)
for it in range(6):
    # add commutators of a maximal independent subset
    V = np.array([vec(m) for m in cur])
    u, s, vt = np.linalg.svd(V, full_matrices=False)
    idx = []
    # pick independent subset greedily
    sel = []
    Q = np.zeros((0, V.shape[1]))
    for m in cur:
        x = vec(m)
        if Q.shape[0] == 0:
            r = np.linalg.norm(x)
        else:
            r = np.linalg.norm(x - Q.T @ (Q @ x))
        if r > 1e-8:
            Q = np.vstack([Q, (x - (Q.T @ (Q @ x) if Q.shape[0] else 0)) / r]); sel.append(m)
    new = []
    for a, b in itertools.combinations(sel, 2):
        new.append(a @ b - b @ a)
    cur = sel + new
    nd = rank_of(cur)
    # compress
    print(f"  closure iteration {it+1}: dim = {nd}")
    if nd == dim:
        break
    dim = nd
