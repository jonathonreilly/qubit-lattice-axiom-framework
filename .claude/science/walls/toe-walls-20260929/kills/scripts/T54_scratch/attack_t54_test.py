def census(Ng, nA=36, nB=32, nP=40):
    K = 8 * Ng
    a1 = 2 * np.pi * (np.arange(nA) + 0.13) / nA   # offset avoids grid points on Weyl-chamber walls
    a2 = 2 * np.pi * (np.arange(nA) + 0.29) / nA
    b = 2 * np.pi * (np.arange(nB) + 0.11) / nB
    ps = 2 * np.pi * (np.arange(nP) + 0.07) / nP
    A1_, A2_, B_, P_ = np.meshgrid(a1, a2, b, ps, indexing="ij")
    A3_ = -A1_ - A2_
    e = [np.exp(1j * A1_), np.exp(1j * A2_), np.exp(1j * A3_)]
    dens3 = np.abs((e[0] - e[1]) * (e[0] - e[2]) * (e[1] - e[2])) ** 2 / 6.0
    dens2 = 1 - np.cos(2 * B_)
    dens = dens3 * dens2
    zs = []
    for c in range(3):
        for s in (+1, -1):
            zs.append(e[c] * np.exp(1j * s * B_) * np.exp(1j * P_))
    for s in (+1, -1):
        zs.append(np.exp(1j * s * B_) * np.exp(-3j * P_))
    I = np.zeros(K + 1, dtype=complex)
    for j in range(K + 1):
        zeta = np.exp(2j * np.pi * j / (K + 1))
        prod = np.ones_like(dens, dtype=complex)
        for z in zs:
            prod = prod * (1 + zeta * z) ** Ng
        I[j] = (prod * dens).mean()
    coef = np.array([sum(I[j] * np.exp(-2j * np.pi * j * k / (K + 1)) for j in range(K + 1)) / (K + 1) for k in range(K + 1)])
    return coef

