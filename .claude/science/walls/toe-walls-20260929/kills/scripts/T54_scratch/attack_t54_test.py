print("\n== PART B: covariant closure of the three axis-conjugate gauge algebras")
def vec(A):
    # A must be anti-Hermitian (i * Hermitian generator, or a commutator of such)
    return np.concatenate([A.real.ravel(), A.imag.ravel()])
basis_mats = []        # Hermitian generators (used for the commutant)
for f in (0, 1, 2):
    T, J, Y = axes[f]
    basis_mats += T + J + [Y]
anti = [1j * m for m in basis_mats]   # anti-Hermitian versions (used for the Lie closure)
def rank_of(mats):
    V = np.array([vec(m) for m in mats])
    s = np.linalg.svd(V, compute_uv=False)
    return int((s > 1e-9).sum())
print(" dim of each single embedding (real span):", rank_of([1j * m for m in axes[0][0] + axes[0][1] + [axes[0][2]]]))
cur = list(anti)
