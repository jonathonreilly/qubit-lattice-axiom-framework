def jw_ops(n):
    I = np.eye(2); Zp = np.diag([1, -1]); a = np.array([[0, 1], [0, 0]])
    ops = []
    for k in range(n):
        m = np.array([[1.0]])
        for j in range(n):
            m = np.kron(m, Zp if j < k else (a if j == k else I))
        ops.append(m)
    return ops
