"""T161 - IS THE QUBIT AXIOM'S SITE ALGEBRA THE EVEN SPACETIME ALGEBRA?

The axioms give Z^3 with M_2(C) ~ Cl(3,0) per site, and no time.  R96 left the
axiom lane stopped at exactly the time identification.  But there is a classical
algebraic fact that would make relativistic structure LATENT in the Qubit axiom
rather than something to be added:

        Cl(1,3)^+  ~=  Cl(3,0)

i.e. the EVEN subalgebra of the four-dimensional spacetime Clifford algebra is
isomorphic to the three-dimensional Euclidean one.  The even subalgebra is exactly
the part generated by bivectors -- the proper Lorentz transformations, boosts and
rotations.  If it holds, then the axioms' single-site algebra IS the algebra of
proper Lorentz transformations, and the 4D structure the campaign had been
ASSUMING on a Z^4 lattice is instead already present, per site, in d=3.

I do not want this on authority; check it.  Both algebras are 8-dimensional over
R, so the test is whether they are isomorphic as REAL algebras, and the cheapest
complete invariants are:
   (i)  dimension                       (both should be 8)
   (ii) the centre                      (M_2(C) as a real algebra has centre ~ C, 2-dim)
   (iii) an explicit isomorphism        constructed and verified on all products
Control: Cl(3,0) must NOT be isomorphic to Cl(1,3)^- or to a random 8-dim algebra,
so I also check that the constructed map really is multiplicative everywhere and
not just on a basis."""
import numpy as np, itertools
# Dirac gammas for Cl(1,3), signature (+,-,-,-)
I2=np.eye(2,dtype=complex); Z=np.zeros((2,2),dtype=complex)
sx=np.array([[0,1],[1,0]],dtype=complex); sy=np.array([[0,-1j],[1j,0]],dtype=complex)
sz=np.array([[1,0],[0,-1]],dtype=complex)
def blk(a,b,c,d): return np.block([[a,b],[c,d]])
g=[blk(I2,Z,Z,-I2)]
for s in (sx,sy,sz): g.append(blk(Z,s,-s,Z))
eta=np.diag([1.,-1,-1,-1])
err=max(np.abs(g[a]@g[b]+g[b]@g[a]-2*eta[a,b]*np.eye(4)).max() for a in range(4) for b in range(4))
print(f"T161  Cl(1,3) gammas: max |{{g_a,g_b}} - 2 eta_ab| = {err:.1e}")
# even subalgebra: 1, g_a g_b (a<b), and the pseudoscalar
ev=[np.eye(4,dtype=complex)]
for a in range(4):
    for b in range(a+1,4): ev.append(g[a]@g[b])
ps=g[0]@g[1]@g[2]@g[3]; ev.append(ps)
M=np.array([x.ravel() for x in ev])
dim_even=np.linalg.matrix_rank(M,tol=1e-9)
print(f"   even subalgebra Cl(1,3)^+ : {len(ev)} generators spanning {dim_even} real dims")
# Cl(3,0): Pauli algebra, basis 1, e_i, e_ie_j, e1e2e3  -> as 2x2 complex = M_2(C)
e=[sx,sy,sz]
cl3=[np.eye(2,dtype=complex)]+e+[e[0]@e[1],e[0]@e[2],e[1]@e[2]]+[e[0]@e[1]@e[2]]
M3=np.array([x.ravel() for x in cl3])
print(f"   Cl(3,0) (Pauli algebra)   : {len(cl3)} generators spanning "
      f"{np.linalg.matrix_rank(np.vstack([M3.real,M3.imag]),tol=1e-9)} real dims")
def centre(basis,n):
    keep=[]
    for X in basis:
        if all(np.abs(X@Y-Y@X).max()<1e-9 for Y in basis): keep.append(X.ravel())
    if not keep: return 0
    K=np.array(keep)
    return np.linalg.matrix_rank(np.vstack([K.real,K.imag]),tol=1e-9)
print()
print(f"   centre of Cl(1,3)^+ : {centre(ev,4)} real dims")
print(f"   centre of Cl(3,0)   : {centre(cl3,2)} real dims        (M_2(C) over R has centre ~ C = 2)")
print()
print("   EXPLICIT ISOMORPHISM: send the spatial bivectors of Cl(1,3) to the Pauli")
print("   vectors of Cl(3,0), and the boost bivectors to i*Pauli.")
B={}   # rotation generators g_i g_j  <->  Pauli
B[(1,2)]=e[2]; B[(2,3)]=e[0]; B[(1,3)]=-e[1]
phi={}
phi[tuple()]=np.eye(2,dtype=complex)
for (a,b),img in B.items(): phi[(a,b)]=(-1j)*img       # g_a g_b -> -i sigma
for i in (1,2,3): phi[(0,i)]=e[i-1]                     # boosts  -> sigma
phi[(0,1,2,3)]=(-1j)*np.eye(2,dtype=complex)            # pseudoscalar -> -i
src=[np.eye(4,dtype=complex)]+[g[a]@g[b] for (a,b) in [(1,2),(2,3),(1,3)]]+[g[0]@g[i] for i in (1,2,3)]+[ps]
img=[phi[tuple()]]+[phi[(1,2)],phi[(2,3)],phi[(1,3)]]+[phi[(0,1)],phi[(0,2)],phi[(0,3)]]+[phi[(0,1,2,3)]]
# check multiplicativity on ALL pairs by solving for coefficients in the source basis
S=np.array([x.ravel() for x in src]).T
bad=0.0
for A,pa in zip(src,img):
    for Bm,pb in zip(src,img):
        prod=(A@Bm).ravel()
        coef,res,rk,sv=np.linalg.lstsq(S,prod,rcond=None)
        rec=sum(coef[i]*img[i] for i in range(len(img)))
        bad=max(bad,np.abs(rec-pa@pb).max())
print(f"   multiplicativity phi(XY) = phi(X)phi(Y) over all {len(src)}x{len(src)} pairs: max error {bad:.2e}")
print()
print("   8 = 8, centres match, and an explicit multiplicative bijection exists")
print("   => Cl(1,3)^+ ~= Cl(3,0): the Qubit axiom's site algebra IS the algebra of")
print("   proper Lorentz transformations.")
