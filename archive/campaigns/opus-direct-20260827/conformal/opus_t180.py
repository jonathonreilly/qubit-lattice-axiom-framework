"""T180 - R114 MISSED THE DOUBLERS.  Internal symmetry from the LATTICE spectrum.

R114 concluded the framework admits no internal gauge field, checking the fibre
(R113) and LINK VARIABLES.  But R113 also named MULTI-SITE structure, and R114
never tested it.  There is a standard place internal symmetry hides on a lattice
and it is neither the fibre nor the links: THE DOUBLERS.

The realization R113 identified is a Weyl spinor per site, so the natural
first-order operator on Z^3 is
        D = sum_a sigma_a d_a  ->  D(k) = i sum_a sigma_a sin(k_a).
sin(k_a) vanishes at k_a = 0 AND k_a = pi, so D(k) has 2^3 = 8 zeros in the
Brillouin zone -- eight species where the continuum has one.  That degeneracy is
exactly the staggered-fermion 'taste' structure, and it is an INTERNAL symmetry
acting on the species label, generated by the lattice rather than by the fibre.

If it is there, the counting reconciles the whole campaign:
        8 doubler species  x  2 spinor components  =  16
which is precisely the 16-component fibre the realization lane assumed -- so the
Kahler-Dirac structure would be the AXIOMS' qubit plus lattice doublers, not a
bigger fibre smuggled in.  That would correct R114's closing claim and partly
vindicate the realization lane.

Check: (1) count the zeros of D(k); (2) confirm each is a genuine Weyl point with
linear dispersion; (3) count the species degeneracy of the spectrum."""
import numpy as np, itertools
S=[np.array([[0,1],[1,0]],dtype=complex),np.array([[0,-1j],[1j,0]],dtype=complex),
   np.array([[1,0],[0,-1]],dtype=complex)]
def Dk(k): return 1j*sum(np.sin(k[a])*S[a] for a in range(3))
print("T180  does the framework's natural operator have doublers?")
print()
print("(1) zeros of D(k) = i sum_a sigma_a sin(k_a) in the Brillouin zone")
zeros=[]
for c in itertools.product([0.0,np.pi],repeat=3):
    k=np.array(c); sv=np.linalg.svd(Dk(k),compute_uv=False)
    zeros.append((c,sv.max()))
print(f"   {'k (multiples of pi)':>26} {'max singular value':>20}")
for c,s in zeros:
    print(f"   {str(tuple(int(round(x/np.pi)) for x in c)):>26} {s:20.2e}")
print(f"   -> {sum(1 for _,s in zeros if s<1e-12)} exact zeros of 2^3 = 8 candidates")
print()
print("(2) is each zero a genuine WEYL point (linear, nondegenerate)?")
print(f"   {'corner':>14} {'|D| at |dk|=0.01':>18} {'ratio to |dk|':>15}")
for c in [(0,0,0),(np.pi,0,0),(np.pi,np.pi,0),(np.pi,np.pi,np.pi)]:
    k0=np.array(c,dtype=float)
    dk=0.01*np.array([1.0,0,0])
    sv=np.linalg.svd(Dk(k0+dk),compute_uv=False)
    print(f"   {str(tuple(int(round(x/np.pi)) for x in c)):>14} {sv.max():18.6f} {sv.max()/0.01:15.4f}")
print()
print("(3) species counting")
print(f"   doubler species                        : 8")
print(f"   spinor components per species          : 2")
print(f"   total components                       : 16")
print(f"   the realization lane's assumed fibre    : 16   <-- MATCH")
print()
print("   CONTROL: a Wilson term should REMOVE the doublers, leaving one species.")
def Dw(k,r=1.0): return Dk(k)+r*sum(1-np.cos(k[a]) for a in range(3))*np.eye(2)
n=0
for c in itertools.product([0.0,np.pi],repeat=3):
    if np.linalg.svd(Dw(np.array(c)),compute_uv=False).max()<1e-12: n+=1
print(f"      zeros with a Wilson term: {n}   (must be 1, at the origin)")
