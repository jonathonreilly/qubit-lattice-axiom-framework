import numpy as np
sx=np.array([[0,1],[1,0]],dtype=complex); sy=np.array([[0,-1j],[1j,0]],dtype=complex)
sz=np.array([[1,0],[0,-1]],dtype=complex); S=[sx,sy,sz]; I2=np.eye(2,dtype=complex)
def rho(t,v): return t*I2+sum(v[i]*S[i] for i in range(3))
def tv(r): return (np.trace(r).real/2, np.array([np.trace(r@S[i]).real/2 for i in range(3)]))
def boost(th,i): return np.cosh(th/2)*I2+np.sinh(th/2)*S[i]
def rot(th,i):   return np.cos(th/2)*I2-1j*np.sin(th/2)*S[i]
print("T162  is the site state a Minkowski 4-vector?")
print()
rng=np.random.default_rng(4)
print("(i) det rho vs t^2 - |v|^2")
w=0.0
for _ in range(2000):
    t=rng.normal(); v=rng.normal(size=3)
    w=max(w,abs(np.linalg.det(rho(t,v)).real-(t*t-v@v)))
print(f"    max |det rho - (t^2 - |v|^2)| over 2000 random states = {w:.2e}")
print()
print("(ii) boosts preserve the Minkowski norm and mix t with v; rotations do not mix")
print(f"    {'theta':>7} {'BOOST: t':>11} {'|v|':>9} {'t^2-|v|^2':>12} | {'ROT: t':>9} {'t^2-|v|^2':>12}")
t0,v0=0.5,np.array([0.2,0.1,0.3])
for th in (0.0,0.3,0.8,1.5):
    B=boost(th,2); r=B@rho(t0,v0)@B.conj().T; tb,vb=tv(r)
    R=rot(th,2);   r2=R@rho(t0,v0)@R.conj().T; tr,vr=tv(r2)
    print(f"    {th:7.2f} {tb:11.6f} {np.linalg.norm(vb):9.6f} {tb*tb-vb@vb:12.8f} |"
          f" {tr:9.6f} {tr*tr-vr@vr:12.8f}")
print(f"    invariant at theta=0: {t0*t0-v0@v0:.8f}   (both columns must equal this)")
