print("    CONTROL -- does the boost actually mix t and v?")
B=boost(0.8,2); tb,vb=tv(B@rho(t0,v0)@B.conj().T)
R=rot(0.8,2);   tr,vr=tv(R@rho(t0,v0)@R.conj().T)
print(f"       boost changes t: {t0:.6f} -> {tb:.6f}   (must differ)")
print(f"       rotation keeps t: {t0:.6f} -> {tr:.6f}   (must be equal)")
print()
print("(iii) PURE states are NULL vectors")
print(f"    {'state':>34} {'t':>9} {'|v|':>9} {'det = t^2-|v|^2':>18} {'rank':>5}")
for nm,r in (("pure |0><0|",np.array([[1,0],[0,0]],dtype=complex)),
             ("pure (|0>+|1>)/sqrt2",0.5*np.array([[1,1],[1,1]],dtype=complex)),
             ("maximally mixed I/2",0.5*I2),
             ("mixed, p=0.8",np.diag([0.8,0.2]).astype(complex))):
    t,v=tv(r)
    print(f"    {nm:>34} {t:9.6f} {np.linalg.norm(v):9.6f} {np.linalg.det(r).real:18.10f}"
          f" {np.linalg.matrix_rank(r,tol=1e-9):5d}")
print()
print("    rank 1 <=> det 0 <=> t = |v| <=> ON THE LIGHT CONE.")
print("    The Record axiom locks exactly one possibility; if possibilities are pure")
print("    states, records are null vectors and the Bloch sphere IS the light cone.")
