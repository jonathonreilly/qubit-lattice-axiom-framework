"""T197 - IS M_12(C) REALLY MINIMAL?  Testing R128's caveat instead of carrying it.

R128 concluded the site algebra must reach M_12(C), with the caveat that this is
minimal only WITHIN the M_4 (x) M_k tower.  That caveat is exactly the sort of
unchecked dependency that produced three successive wrong answers (M_4, M_8, M_12),
so test it rather than carry it.

M_8(C) is not only M_4 (x) M_2.  The complex Clifford algebra Cl(6) (x) C is
isomorphic to M_8(C), so M_8(C) admits SIX mutually anticommuting elements, where
gamma (x) I_2 uses only the four from M_4.  Using three of the six for the spatial
Gamma_a leaves a genuinely different structure -- and possibly larger blocks than
the u(4) the tensor tower gives.

If the Cl(6) construction on M_8(C) reaches a block u(m) with m >= 5, then
M_8(C) suffices after all and R128's M_12 is too pessimistic.

EFFICIENCY NOTE: the fibre is 8 doublers x 8 = 64, which timed out before when
using all 24 lattice elements.  The octahedral group is GENERATED by two elements,
so imposing commutation with those two is equivalent and cuts the commutator
system from 27 blocks to 5.

CONTROLS: the six gammas must mutually anticommute; the two chosen lattice
elements must generate all 24."""
import numpy as np, itertools
s=[np.array([[0,1],[1,0]],dtype=complex),np.array([[0,-1j],[1j,0]],dtype=complex),
   np.array([[1,0],[0,-1]],dtype=complex)]
def clifford(d):
    """d mutually anticommuting hermitian matrices, built by the standard tower"""
    if d<=2: return [s[0],s[1]][:d]
    if d==3: return [s[0],s[1],s[2]]
    G=clifford(d-2); n=G[0].shape[0]
    out=[np.kron(g,s[2]) for g in G]
    out.append(np.kron(np.eye(n),s[0])); out.append(np.kron(np.eye(n),s[1]))
    return out
G6=clifford(6)
n=G6[0].shape[0]
print("T197  M_8(C) via Cl(6): does a different Gamma structure do better?")
print(f"   CONTROL six gammas, size {n}x{n}, mutual anticommutation: "
      f"{max(np.abs(G6[a]@G6[b]+G6[b]@G6[a]-2*(a==b)*np.eye(n)).max() for a in range(6) for b in range(6)):.1e}")
R8=[tuple(r) for r in itertools.product([0,1],repeat=3)]; I8={r:i for i,r in enumerate(R8)}
def cubic():
    R=[]
    for p in itertools.permutations(range(3)):
        for sg in itertools.product([1,-1],repeat=3):
            M=np.zeros((3,3))
            for i,q in enumerate(p): M[i,q]=sg[i]
            if abs(np.linalg.det(M)-1)<1e-9: R.append(M)
    return R
ROT=cubic()
# two generators of the octahedral group
def gens():
    for i in range(len(ROT)):
        for j in range(len(ROT)):
            seen=[np.eye(3)]; frontier=[np.eye(3)]
            for _ in range(8):
                new=[]
                for X in frontier:
                    for Y in (ROT[i],ROT[j]):
                        Z=X@Y
                        if not any(np.allclose(Z,W) for W in seen): seen.append(Z); new.append(Z)
                frontier=new
                if not new: break
            if len(seen)==24: return ROT[i],ROT[j]
    return None,None
g1,g2=gens()
print(f"   CONTROL two elements generate all 24: {g1 is not None}")
def corner_perm(R):
    P=np.zeros((8,8))
    for r in R8:
        v=np.array(r)*2-1; w=R@v
        P[I8[tuple(((w+1)/2).astype(int))],I8[r]]=1.0
    return P
def spin_rep(R,G):
    """rotation acting on the fibre via the bivector generators of the first three gammas"""
    ang=np.arccos(np.clip((np.trace(R)-1)/2,-1,1))
    if abs(ang)<1e-9: return np.eye(G[0].shape[0],dtype=complex)
    if abs(ang-np.pi)<1e-9:
        w,v=np.linalg.eigh((R+np.eye(3))/2); ax=v[:,np.argmax(w)]
    else:
        ax=np.array([R[2,1]-R[1,2],R[0,2]-R[2,0],R[1,0]-R[0,1]])/(2*np.sin(ang))
    ax=ax/np.linalg.norm(ax)
    Sg=sum(ax[i]*(G[(i+1)%3]@G[(i+2)%3]) for i in range(3))/2.0
    from scipy.linalg import expm
    return expm(-ang*Sg/1.0*0.5*2/2)
def parts(a,sg):
    Mi=np.zeros((8,8),dtype=complex); Mc=np.zeros((8,8),dtype=complex)
    for r in R8:
        t=list(r)
        if sg>0:
            if r[a]==0: t[a]=1; Mi[I8[tuple(t)],I8[r]]+=1
            else:       t[a]=0; Mc[I8[tuple(t)],I8[r]]+=1
        else:
            if r[a]==1: t[a]=0; Mi[I8[tuple(t)],I8[r]]+=1
            else:       t[a]=1; Mc[I8[tuple(t)],I8[r]]+=1
    return Mi,Mc
N=8*n
Gm=[]
for mu in range(3):
    Pi,Pc=parts(mu,1); Mi,Mc=parts(mu,-1)
    Gm.append(np.kron(1j*Pc+1j*Mc,G6[mu])/2.0)
L=[np.kron(corner_perm(R),spin_rep(R,G6)) for R in (g1,g2)]
mats=Gm+L
print(f"   fibre {N}, using {len(mats)} generators (3 Gamma + 2 lattice)")
M=np.vstack([np.kron(m,np.eye(N))-np.kron(np.eye(N),m.T) for m in mats])
sv=np.linalg.svd(M,compute_uv=False)
d=int(np.sum(sv<=max(M.shape)*np.finfo(float).eps*sv.max()))
print(f"   internal symmetry (Gamma + lattice) dim = {d}")
print(f"   M_4 (x) M_2 gave blocks u(4);  a block u(m) needs m^2 <= {d}")
print(f"   largest conceivable block: u({int(np.floor(np.sqrt(d)))})"
      f"   {'could reach u(5)' if d>=25 else 'CANNOT reach u(5)'}")
