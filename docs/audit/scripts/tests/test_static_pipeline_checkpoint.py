#!/usr/bin/env python3
"""Regression tests for the full-pipeline static checkpoint."""
from __future__ import annotations

import json
import os
from contextlib import ExitStack
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

PROJECT_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(PROJECT_ROOT))

from docs.audit.scripts import static_pipeline_checkpoint as checkpoint


class StaticInputFingerprintTest(unittest.TestCase):
    def test_seed_deleted_tracked_shard_is_not_reopened(self) -> None:
        """The seed receipt fingerprints the post-seed filesystem, not index ghosts."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = Path(tmp)
            data = repo / "docs" / "audit" / "data"
            ledger = data / "ledger" / "aa"
            scripts = repo / "scripts"
            ledger.mkdir(parents=True)
            scripts.mkdir()
            live = ledger / "live.json"
            live.write_text('{"claim_id": "live", "runner_path": null}\n')

            tracked_listing = "\n".join(
                (
                    "docs/audit/data/ledger/aa/deleted.json",
                    "docs/audit/data/ledger/aa/live.json",
                )
            ) + "\n"
            listed = subprocess.CompletedProcess(
                args=["git", "ls-files"],
                returncode=0,
                stdout=tracked_listing,
                stderr="",
            )

            with (
                mock.patch.object(checkpoint, "REPO_ROOT", repo),
                mock.patch.object(checkpoint, "DATA", data),
                mock.patch.object(checkpoint, "run_git", return_value=listed),
            ):
                digest, detail = checkpoint.static_input_fingerprint()

            self.assertIsNotNone(digest, detail)
            self.assertEqual("static input tree fingerprinted", detail)


class FullBuildLedgerTransitionTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = Path(self.tmp.name)
        self.data = self.repo / "docs/audit/data"
        self.ledger = self.data / "ledger/aa/old.json"
        self.ledger.parent.mkdir(parents=True)
        (self.repo / "scripts").mkdir()
        (self.repo / "source.txt").write_text("source v1")
        (self.repo / "docs/live.md").write_text("Runner: scripts/live.py")
        (self.repo / "scripts/live.py").write_text("assert True")
        self.write_row(runner_path="scripts/retired.py",
                       helper_runner_paths=["scripts/retired_helper.py"])
        # Files absent from this Git-visible list emulate ignored filesystem
        # inputs. No checkpoint/producer receipt is accidentally self-hashed.
        listed = subprocess.CompletedProcess([], 0, "source.txt\n", "")
        stack = self.enterContext(ExitStack())
        for name, value in [("REPO_ROOT", self.repo), ("DATA", self.data),
                            ("CHECKPOINT", self.data / "checkpoint.json")]:
            stack.enter_context(mock.patch.object(checkpoint, name, value))
        stack.enter_context(mock.patch.object(checkpoint, "run_git", return_value=listed))
        stack.enter_context(mock.patch.dict(os.environ, {
            checkpoint.BUILD_NONCE_ENV: "a" * 32,
        }))

    def write_row(self, **fields):
        self.ledger.write_text(json.dumps({"claim_id": "old", **fields}))

    def fingerprint(self, include):
        digest, detail = checkpoint.static_input_fingerprint(include_ledger_static=include)
        self.assertIsNotNone(digest, detail)
        return digest

    def test_full_producer_transition_accepts_retired_missing_ledger_runners(self):
        before = self.fingerprint(False)
        before_static = self.fingerprint(True)
        ok, detail = checkpoint.begin_checkpoint()
        self.assertTrue(ok, detail)
        (self.data / "citation_graph.json").write_text('{"nodes": []}')
        ok, detail = checkpoint.record_producer_receipt("citation_graph")
        self.assertTrue(ok, detail)
        # Seeder retires stale rows; manifest is also generated by this build.
        self.ledger.unlink()
        (self.data / "citation_graph_manifest.json").write_text('{"fresh": true}')
        self.assertEqual(before, self.fingerprint(False))
        self.assertNotEqual(before_static, self.fingerprint(True))
        ok, detail = checkpoint.record_producer_receipt("seed_ledger")
        self.assertTrue(ok, detail)
        ok, detail = checkpoint.prepare_checkpoint()
        self.assertTrue(ok, detail)
        (self.data / "runner_classification.json").write_text('{"per_runner": {}}')
        for operation in [lambda: checkpoint.record_producer_receipt("runner_classification"),
                          checkpoint.capture_checkpoint, checkpoint.finalize_checkpoint,
                          checkpoint.verify_checkpoint]:
            ok, detail = operation()
            self.assertTrue(ok, detail)

    def _sparse_listing(self, blob_id):
        def fake_run_git(args):
            if args[:2] == ["ls-files", "-s"]:
                return subprocess.CompletedProcess(
                    [], 0, f"H 100644 {'c' * 40} 0\tsource.txt\nS 100644 {blob_id} 0\tgone.txt\n", ""
                )
            return subprocess.CompletedProcess([], 0, "source.txt\ngone.txt\n", "")
        return mock.patch.object(checkpoint, "run_git", side_effect=fake_run_git)

    def test_sparse_excluded_input_binds_its_index_blob(self):
        with self._sparse_listing("a" * 40):
            first = self.fingerprint(True)
            self.assertEqual(first, self.fingerprint(True))
        with self._sparse_listing("b" * 40):
            self.assertNotEqual(first, self.fingerprint(True))

    def test_sparse_flagged_file_present_on_disk_is_read(self):
        (self.repo / "gone.txt").write_text("v1")
        with self._sparse_listing("a" * 40):
            first = self.fingerprint(True)
            (self.repo / "gone.txt").write_text("v2")
            self.assertNotEqual(first, self.fingerprint(True))

    def test_missing_input_without_sparse_flag_still_fails_closed(self):
        listed = subprocess.CompletedProcess([], 0, "source.txt\ngone.txt\n", "")
        with mock.patch.object(checkpoint, "run_git", return_value=listed):
            digest, detail = checkpoint.static_input_fingerprint(include_ledger_static=True)
        self.assertIsNone(digest)
        self.assertIn("cannot read static input gone.txt", detail)

    def test_source_mutation_still_rejects_prepare(self):
        self.assertTrue(checkpoint.begin_checkpoint()[0])
        (self.data / "citation_graph.json").write_text('{}')
        self.assertTrue(checkpoint.record_producer_receipt("citation_graph")[0])
        self.ledger.unlink()
        (self.repo / "source.txt").write_text("changed during graph build")
        self.assertTrue(checkpoint.record_producer_receipt("seed_ledger")[0])
        ok, detail = checkpoint.prepare_checkpoint()
        self.assertFalse(ok)
        self.assertIn("source inputs changed", detail)

    def test_live_and_ignored_source_guards_in_both_modes(self):
        for include in [False, True]:
            for relative in ["source.txt", "docs/live.md", "scripts/live.py",
                             "scripts/ignored_helper.py"]:
                with self.subTest(include=include, path=relative):
                    before = self.fingerprint(include)
                    path = self.repo / relative
                    prior = path.read_bytes() if path.exists() else None
                    path.write_text("changed source")
                    self.assertNotEqual(before, self.fingerprint(include))
                    if prior is None:
                        path.unlink()
                    else:
                        path.write_bytes(prior)

    def test_ignored_root_runner_candidate_missing_and_content_guard(self):
        # Graph normalize_runner_path accepts bare root-relative foo.py as well
        # as scripts/foo.py. Do not lose ignored outside-scripts live inputs.
        (self.repo / "docs/live.md").write_text("Runner: root_runner.py")
        path = self.repo / "root_runner.py"
        for include in [False, True]:
            with self.subTest(include=include):
                missing = self.fingerprint(include)
                path.write_text("assert True")
                present = self.fingerprint(include)
                self.assertNotEqual(missing, present)
                path.write_text("assert False")
                self.assertNotEqual(present, self.fingerprint(include))
                path.unlink()
                self.assertEqual(missing, self.fingerprint(include))

    def test_ledger_only_outside_script_paths_remain_bound_after_seed(self):
        self.write_row(runner_path="private/runner.py",
                       helper_runner_paths=["private/helper.py"])
        (self.repo / "private").mkdir()
        for relative in ["private/runner.py", "private/helper.py"]:
            with self.subTest(path=relative):
                pre = self.fingerprint(False)
                missing = self.fingerprint(True)
                path = self.repo / relative
                path.write_text("v1")
                present = self.fingerprint(True)
                self.assertNotEqual(missing, present)
                self.assertEqual(pre, self.fingerprint(False))
                path.write_text("v2")
                self.assertNotEqual(present, self.fingerprint(True))
                path.unlink()
                self.assertEqual(missing, self.fingerprint(True))

    def test_ledger_unknown_static_fields_and_missing_paths_stay_guarded(self):
        pre = self.fingerprint(False)
        full = self.fingerprint(True)
        self.write_row(runner_path="scripts/different_missing.py", new_unknown_field=1)
        self.assertEqual(pre, self.fingerprint(False))
        self.assertNotEqual(full, self.fingerprint(True))
        full = self.fingerprint(True)
        self.write_row(runner_path="scripts/different_missing.py", new_unknown_field=2)
        self.assertEqual(pre, self.fingerprint(False))
        self.assertNotEqual(full, self.fingerprint(True))
        # Invalid ledger attachments remain fail-closed in prepared/full mode.
        self.write_row(runner_path="../escape.py")
        self.assertEqual(pre, self.fingerprint(False))
        digest, detail = checkpoint.static_input_fingerprint()
        self.assertIsNone(digest)
        self.assertIn("escapes repository", detail)


if __name__ == "__main__":
    unittest.main()
