#!/usr/bin/env python3
"""J:confirm:J-attack:PR8151 — independent chessboard-orbit geometry.

Finder (claude-opus-5) used a BFS of (cell, bond) pairs under theta_{i,k}.
This script represents the group generated by those reflections as the
affine maps, independently on each coordinate, x -> ±x + 2m (mod S), applies
each map to both endpoints of the seed bond {0, e_1} as frozensets, and
counts the orbit. The 3D witness is a constant/alternate assignment on
even-even lines, counted by looping over sites (not the finder's val dict).
The comparison (m/p)^{3/4}/6 > 6m/p is exact in Fraction.
"""
from __future__ import annotations

import itertools
from fractions import Fraction


def maps_1d(S: int) -> list:
    """All maps x |-> eps*x + 2m (mod S) generated by the reflections 2k-x."""
    out = []
    for eps in (1, -1):
        for m in range(S):
            out.append((eps, 2 * m % S))
    # unique functions
    seen = {}
    for eps, sh in out:
        table = tuple((eps * x + sh) % S for x in range(S))
        seen[table] = (eps, sh)
    return list(seen.values())


def apply_site(x, maps, S):
    return tuple((eps * x[i] + sh) % S for i, (eps, sh) in enumerate(maps))


def orbit_of_seed_bond(d: int, S: int) -> set[frozenset]:
    maps = [maps_1d(S) for _ in range(d)]
    seed = ((0,) * d, (1,) + (0,) * (d - 1))
    bonds: set[frozenset] = set()
    for combo in itertools.product(*maps):
        a = apply_site(seed[0], combo, S)
        b = apply_site(seed[1], combo, S)
        bonds.add(frozenset((a, b)))
    return bonds


def even_transverse_dir1(d: int, S: int) -> set[frozenset]:
    out = set()
    for x in range(S):
        for t in itertools.product(range(0, S, 2), repeat=d - 1):
            a = (x,) + t
            b = ((x + 1) % S,) + t
            out.add(frozenset((a, b)))
    return out


def witness_3d(S: int) -> tuple[int, int, bool]:
    """Direction-1 bonds on even-even transverse lines are a!=b; else constant."""
    N = S ** 3
    bad = 0
    event = True
    def val(x, y, z):
        if y % 2 == 0 and z % 2 == 0:
            return x % 2
        return 0
    for x, y, z in itertools.product(range(S), repeat=3):
        for dx, dy, dz in ((1, 0, 0), (0, 1, 0), (0, 0, 1)):
            u = ((x + dx) % S, (y + dy) % S, (z + dz) % S)
            isbad = val(x, y, z) != val(*u)
            bad += isbad
            if (dx, dy, dz) == (1, 0, 0) and y % 2 == 0 and z % 2 == 0 and not isbad:
                event = False
    return N, bad, event


def main() -> None:
    hits: list[str] = []
    for d, S in ((2, 4), (2, 6), (2, 8), (3, 4), (3, 6)):
        orb = orbit_of_seed_bond(d, S)
        even = even_transverse_dir1(d, S)
        N = S ** d
        print(f"d={d} S={S}: orbit {len(orb)} bonds; even-transverse dir-1 {len(even)}; N={N}; equal={orb==even}")
        if orb != even:
            hits.append(f"orbit != even-transverse dir-1 on (Z/{S}Z)^{d}")
        if len(orb) == N:
            hits.append(f"orbit has all {N} dir-1 bonds, contrary to the finder's smaller event")
        if len(orb) != N // (2 ** (d - 1)):
            hits.append(f"orbit size {len(orb)} != N/2^{d-1} = {N // (2 ** (d - 1))}")

    for S in (4, 6):
        N, bad, ev = witness_3d(S)
        print(f"3D S={S}: N={N} bad={bad} fraction={Fraction(bad, N)} event={ev}")
        if not ev or Fraction(bad, N) != Fraction(3, 4):
            hits.append(f"3D witness failed on S={S}")

    # (m/p)^{3/4}/6 > 6 m/p  iff  (p/m)^{1/4} > 36  iff p/m > 36^4
    # check by raising both sides to the 4th: (m/p)^3 / 6^4 > 6^4 (m/p)^4
    # i.e. 1 > 6^8 (m/p) wait, better: set t=m/p, t^{3/4}/6 > 6 t iff t^{-1/4} > 36 iff 1/t > 36^4
    thr = 36 ** 4
    t = Fraction(1, thr + 1)  # m/p just below 1/36^4, i.e. p/m just above 36^4
    # avoid roots: compare (t**3) / 6**4  ?  6**4 * t**4   after raising the inequality t^{3/4}/6 > 6t to 4th power
    # (t^{3/4}/6)^4 > (6t)^4  => t^3 / 1296 > 1296 t^4  since 6^4=1296
    left = t ** 3 / (6 ** 4)
    right = (6 ** 4) * (t ** 4)
    print(f"exact: at p/m = {thr}+1, (m/p)^{{3}}/6^4 = {left} vs 6^4 (m/p)^4 = {right}; left>right {left > right}")
    if not (left > right):
        hits.append("threshold inequality failed at p/m = 36^4 + 1")
    t2 = Fraction(1, thr)  # equality case of the fourth-power comparison? 36^4 exactly
    # at p/m = 36^4, t=1/36^4, t^{-1/4}=36, so t^{3/4}/6 = 6t, equality
    left2 = t2 ** 3 / (6 ** 4)
    right2 = (6 ** 4) * (t2 ** 4)
    print(f"exact equality at p/m=36^4: {left2} == {right2}: {left2 == right2}")

    if hits and any("orbit != even" in h or "witness failed" in h or "threshold" in h for h in hits):
        print("SUMMARY: not reproduced - " + "; ".join(hits))
        return
    if any(len(orbit_of_seed_bond(d, S)) != S ** d for d, S in ((2, 4), (3, 4))):
        print(
            "HIT: confirmed - affine group orbit of the seed dir-1 bond is the even-transverse "
            "dir-1 bonds (N/2 in 2D, N/4 in 3D), not every dir-1 bond; explicit 3D configs have "
            f"exactly 3N/4 bad bonds; (m/p)^{{3/4}}/6 > 6m/p for p/m > 36^4 = {thr}"
        )
        print(
            "SUMMARY: confirmed T3 witness is the even-transverse sublattice, not every "
            "direction-i bond; 3D D_even has 3N/4-bad configs so T4's 6m/p does not bound it "
            f"for p/m > 36^4"
        )
    else:
        print("SUMMARY: not reproduced - orbit filled every direction-1 bond")


if __name__ == "__main__":
    main()
