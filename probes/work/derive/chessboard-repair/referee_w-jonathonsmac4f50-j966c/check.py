# ------------------------------------------------------------------ R1 orbits
def orbit(side, d, x0, i):
    """orbit of the bond {x0, x0 + e_i} under the group generated by the site reflections theta_{j,k}"""
    def refl(bond, j, k):
        x, dirn = bond
        y = list(x)
        if j != dirn:
            y[j] = (2 * k - x[j]) % side
            return (tuple(y), dirn)
        # the bond {x, x + e_j} goes to {2k - x_j, 2k - x_j - 1}: lower end 2k - x_j - 1
        y[j] = (2 * k - x[j] - 1) % side
        return (tuple(y), dirn)
    start = (tuple(x0), i)
    seen = {start}
    stack = [start]
    while stack:
        b = stack.pop()
        for j in range(d):
            for k in range(side):
                nb = refl(b, j, k)
                if nb not in seen:
                    seen.add(nb)
                    stack.append(nb)
    return seen


