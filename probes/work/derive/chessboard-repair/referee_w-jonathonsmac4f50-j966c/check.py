# ------------------------------------------------------------------ R2 the line lemma
def canonical_proper_cycles(n, alphabet=6):
    out = []

    def rec(seq, mx):
        if len(seq) == n:
            if seq[-1] != seq[0]:
                out.append(tuple(seq))
            return
        for c in range(min(mx + 2, alphabet)):
            if c != seq[-1]:
                rec(seq + [c], max(mx, c))
    rec([0], 0)
    return out


