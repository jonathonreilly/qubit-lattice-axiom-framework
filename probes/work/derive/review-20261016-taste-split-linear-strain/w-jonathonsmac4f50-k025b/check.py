class Lat:
    def __init__(self, L):
        self.L = L
        V = self.V = L ** 3
        X = self.X = np.array(np.unravel_index(np.arange(V), (L, L, L))).T
        self.cls = (X[:, 0] % 2) + 2 * (X[:, 1] % 2) + 4 * (X[:, 2] % 2)
        eta = [np.ones(V), (-1.0) ** X[:, 0], (-1.0) ** (X[:, 0] + X[:, 1])]

        def mk(a, vals):
            Y = X.copy()
            Y[:, a] += 1
            S = np.zeros((V, V))
            S[self.idx(Y), np.arange(V)] = vals
            return S

        self.Sp = [mk(a, eta[a]) for a in range(3)]            # eta-twisted shifts (the Gamma_a e^{ik_a} hops)
        self.T = [mk(a, np.ones(V)) for a in range(3)]         # plain shifts e^{ik_a}
        self.A = sum(S - S.T for S in self.Sp)                 # real antisymmetric, h = -i A/2
        self.eps = (-1.0) ** X.sum(1)
        self.h0 = -0.5j * self.A
        self.epsM = np.diag(self.eps).astype(complex)
        T = self.T
        self.S1 = [(T[a] - T[a].T) / 2j for a in range(3)]     # sin k_a
        self.C1 = [(T[a] + T[a].T) / 2 for a in range(3)]      # cos k_a
        U = [T[a] @ T[a] for a in range(3)]
        self.S2 = [(U[a] - U[a].T) / 2j for a in range(3)]     # sin 2k_a
        self.Ssym = [(self.Sp[a] + self.Sp[a].T) / 2 for a in range(3)]   # Gamma_a cos k_a
        # split-mass folding-class sign patterns (derived by exact nullspace at L = 8, see section A; closed form here)
        self.cx = {(0, 1): (-1.0) ** (X[:, 0] + X[:, 2]), (1, 2): (-1.0) ** (X[:, 0] + X[:, 1]), (0, 2): -((-1.0) ** X[:, 0])}
        self.pair = {0: (1, 2), 1: (2, 0), 2: (0, 1)}          # vector component a  <->  O_23, O_31, O_12
        self.O = [self.mkO(a) for a in range(3)]

    def idx(self, Y):
        L = self.L
        return np.ravel_multi_index((Y % L).T, (L, L, L))

    def cxfor(self, i, j):
        return self.cx[tuple(sorted((i, j)))]

    def mkO(self, a):
        i, j = self.pair[a]
        return 1j * np.diag(self.cxfor(i, j)) @ (self.C1[i] @ self.C1[j])

    def v(self, hm, a):                                        # flow velocity /t :  (1/2) sum_b h_ab p_b ,  p_b = sin(2k_b)/2
        out = np.zeros((self.V, self.V), complex)
        for b in range(3):
            if hm[a, b] != 0:
                out = out + 0.25 * hm[a, b] * self.S2[b]
        return out

    def dH(self, hm):                                          # d/dt of sum_a Gamma_a s_a(Phi_t k)
        d = np.zeros((self.V, self.V), complex)
        for a in range(3):
            for b in range(3):
                if hm[a, b] != 0:
                    d += 0.25 * hm[a, b] * (self.Ssym[a] @ self.S2[b])
        return d

    def dO(self, a, hm):                                       # d/dt of  i diag(cx) g(Phi_t k),  g = cos k_i cos k_j
        i, j = self.pair[a]
        dg = -(self.S1[i] @ self.C1[j] @ self.v(hm, i)) - (self.C1[i] @ self.S1[j] @ self.v(hm, j))
        return 1j * np.diag(self.cxfor(i, j)) @ dg


