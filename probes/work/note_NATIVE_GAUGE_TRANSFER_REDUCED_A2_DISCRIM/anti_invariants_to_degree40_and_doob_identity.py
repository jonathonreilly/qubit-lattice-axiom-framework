def run_D1():
    print("=" * 78)
    print("D1  wall-reflection group, Q invariance, delta sign")
    I2 = ((1, 0), (0, 1))
    G = {I2}
    frontier = [I2]
    while frontier:
        nxt = []
        for g in frontier:
            for s in (SX, SY, SXY):
                h = matmul(s, g)
                if h not in G:
                    G.add(h)
                    nxt.append(h)
        frontier = nxt
    ok_q = all(compose_linear(Qp, g) == Qp for g in G)
    det = lambda g: g[0][0] * g[1][1] - g[0][1] * g[1][0]
    ok_d = all(compose_linear(DELTA, g) == scale(DELTA, det(g)) for g in G)
    flips = [compose_linear(DELTA, s) == scale(DELTA, -1) for s in (SX, SY, SXY)]
    print(f"  group order {len(G)}; Q invariant under all: {ok_q}; delta o g = det(g) delta for all: {ok_d}; "
          f"each wall flips delta: {flips}; swap(x,y) fixes delta: {compose_linear(DELTA, SWAP) == DELTA}")
    if len(G) != 6 or not ok_q or not all(flips):
        hit("wall reflections: group order / Q invariance / delta flip fails")
    return len(G), G


def nullspace(rows, ncols):
    """exact reduced row echelon; rows: list of lists of Fractions"""
    A = [r[:] for r in rows]
    piv_cols = []
    r = 0
    for c in range(ncols):
        pr = next((i for i in range(r, len(A)) if A[i][c] != 0), None)
        if pr is None:
            continue
        A[r], A[pr] = A[pr], A[r]
        inv = 1 / A[r][c]
        A[r] = [v * inv for v in A[r]]
        for i in range(len(A)):
            if i != r and A[i][c] != 0:
                f = A[i][c]
                A[i] = [a - f * b for a, b in zip(A[i], A[r])]
        piv_cols.append(c)
        r += 1
        if r == len(A):
            break
    free = [c for c in range(ncols) if c not in piv_cols]
    basis = []
    for fcol in free:
        vec = [Fr(0)] * ncols
        vec[fcol] = Fr(1)
        for i, pc in enumerate(piv_cols):
            vec[pc] = -A[i][fcol]
        basis.append(vec)
    return basis


def div_exact(p, q):
    """exact division p / q in Q[x,y] (q homogeneous); returns (quotient, remainder-is-zero)"""
    # divide by leading monomial in lex order on (i, j)
    qlead = max(q)
    quot = {}
    rem = dict(p)
    while rem:
        lead = max(rem)
        if lead[0] < qlead[0] or lead[1] < qlead[1]:
            return quot, False
        c = rem[lead] / q[qlead]
        m = (lead[0] - qlead[0], lead[1] - qlead[1])
        quot[m] = quot.get(m, 0) + c
        rem = add(rem, scale(mul({m: c}, q), -1))
    return clean(quot), True


def count_2a3b(n):
    if n < 0:
        return 0
    return sum(1 for b in range(n // 3 + 1) if (n - 3 * b) % 2 == 0)


def run_D2(maxdeg=40):
    print("=" * 78)
    print(f"D2  anti-invariants and invariants for every degree 0..{maxdeg} (exact)")
    anti_dims, inv_dims, pred_anti, pred_inv = [], [], [], []
    all_div = True
    all_quot_inv = True
    for d in range(maxdeg + 1):
        mons = [(k, d - k) for k in range(d + 1)]
        # anti: p o s + p = 0 for s in {SX, SY}; inv: p o s - p = 0
        res = {}
        for sign, name in ((1, "anti"), (-1, "inv")):
            rows = []
            images = {s: [compose_linear({m: Fr(1)}, s) for m in mons] for s in (SX, SY)}
            for s in (SX, SY):
                for target in mons:
                    rows.append([images[s][c].get(target, Fr(0)) + (sign if mons[c] == target else 0)
                                 for c in range(len(mons))])
            res[name] = nullspace(rows, len(mons))
        anti_dims.append(len(res["anti"]))
        inv_dims.append(len(res["inv"]))
        pred_anti.append(count_2a3b(d - 3))
        pred_inv.append(count_2a3b(d))
        for vec in res["anti"]:
            p = clean({mons[c]: vec[c] for c in range(len(mons))})
            qt, ok = div_exact(p, DELTA)
            if not ok:
                all_div = False
                hit(f"degree {d}: an anti-invariant polynomial is not divisible by delta")
                continue
            if not (compose_linear(qt, SX) == qt and compose_linear(qt, SY) == qt):
                all_quot_inv = False
    print(f"  anti-invariant dims d=0..{maxdeg}: {anti_dims}")
    print(f"  predicted #(2a+3b=d-3):          {pred_anti}")
    print(f"  invariant dims:                  {inv_dims}")
    print(f"  predicted #(2a+3b=d):            {pred_inv}")
    print(f"  every anti-invariant basis element divisible by delta: {all_div}; quotient invariant: {all_quot_inv}")
    if anti_dims[:3] != [0, 0, 0] or anti_dims[3] != 1:
        hit(f"low-degree anti-invariant dims {anti_dims[:4]} differ from [0,0,0,1]")
    if anti_dims != pred_anti:
        hit("anti-invariant dimensions differ from delta x invariants count")
    if not all_quot_inv:
        hit("delta-quotient of an anti-invariant is not invariant")
    return anti_dims, inv_dims, pred_anti == anti_dims, pred_inv == inv_dims, all_div, all_quot_inv


def run_D3():
    print("=" * 78)
    print("D3  delta-Doob identity L(delta g) = delta L_delta g")
    dlx, dly = dx(DELTA), dy(DELTA)
    cxn = add(scale(dlx, 2), scale(dly, -1))    # (2 delta_x - delta_y); L_delta drift numerators / (3 delta)
    cyn = add(scale(dlx, -1), scale(dly, 2))
    Lhd = L(DELTA)
    print(f"  L delta = {Lhd or 0}")
    if Lhd:
        hit("delta is not L-harmonic")
    bad = 0
    count = 0
    for deg in range(13):
        for a in range(deg + 1):
            g = {(a, deg - a): Fr(1)}
            lhs = L(mul(DELTA, g))
            rhs = add(mul(DELTA, L(g)), scale(add(mul(cxn, dx(g)), mul(cyn, dy(g))), Fr(1, 3)))
            count += 1
            if add(lhs, scale(rhs, -1)):
                bad += 1
    # Gaussian class: g = p exp(-Q) -> represent derivatives on the prefactor
    Qx, Qy = dx(Qp), dy(Qp)

    def gdx(p):
        return add(dx(p), scale(mul(Qx, p), -1))

    def gdy(p):
        return add(dy(p), scale(mul(Qy, p), -1))

    def gL(p):
        return scale(add(gdx(gdx(p)), scale(gdx(gdy(p)), -1), gdy(gdy(p))), Fr(1, 3))
    badg = 0
    countg = 0
    for deg in range(9):
        for a in range(deg + 1):
            p = {(a, deg - a): Fr(1)}
            lhs = gL(mul(DELTA, p))
            rhs = add(mul(DELTA, gL(p)), scale(add(mul(cxn, gdx(p)), mul(cyn, gdy(p))), Fr(1, 3)))
            countg += 1
            if add(lhs, scale(rhs, -1)):
                badg += 1
    print(f"  monomials a+b<=12: {count} checked, failures {bad}; Gaussian class x^a y^b e^-Q, a+b<=8: "
          f"{countg} checked, failures {badg}")
    if bad or badg:
        hit(f"delta-Doob identity fails on {bad + badg} basis functions")
    # (u,v) form against (x,y) form at rational points
    tests = [{(a, b): Fr(1)} for a in range(4) for b in range(3)]
    worst = Fr(0)
    npts = 0
    all_exact = True
    for g in tests:
        gx, gy = dx(g), dy(g)
        gxx, gxy, gyy = dx(gx), dx(gy), dy(gy)
        for i in range(1, 11):
            for j in range(1, 21):
                x0, y0 = Fr(i, 3), Fr(j, 7)
                u0, v0 = x0 + y0, x0 - y0
                dval = ev(DELTA, x0, y0)
                Lxy_val = (ev(gxx, x0, y0) - ev(gxy, x0, y0) + ev(gyy, x0, y0)) / 3 + \
                    (ev(cxn, x0, y0) * ev(gx, x0, y0) + ev(cyn, x0, y0) * ev(gy, x0, y0)) / (3 * dval)
                gu = (ev(gx, x0, y0) + ev(gy, x0, y0)) / 2
                gv = (ev(gx, x0, y0) - ev(gy, x0, y0)) / 2
                guu = (ev(gxx, x0, y0) + 2 * ev(gxy, x0, y0) + ev(gyy, x0, y0)) / 4
                gvv = (ev(gxx, x0, y0) - 2 * ev(gxy, x0, y0) + ev(gyy, x0, y0)) / 4
                Luv_val = guu / 3 + gvv + Fr(2) * (3 * u0 ** 2 - v0 ** 2) / (3 * u0 * (u0 ** 2 - v0 ** 2)) * gu \
                    - Fr(4) * v0 / (u0 ** 2 - v0 ** 2) * gv
                all_exact &= isinstance(Luv_val, Fr) and isinstance(Lxy_val, Fr)
                worst = max(worst, abs(Luv_val - Lxy_val))
                npts += 1
    print(f"  (u,v) form vs (x,y) form: {npts} exact evaluations, max |difference| = {worst}")
    if not all_exact:
        raise RuntimeError("non-exact arithmetic in the (u,v) comparison")
    if worst != 0:
        hit("(u,v) form of L_delta differs from the (x,y) form")
    # u,v expressions for H, Q, L(u^2+v^2)
    return count, bad, countg, badg, npts, worst


def run_D4():
    print("=" * 78)
    print("D4  commutator exp(Q)[L, M_(H exp(-Q))] 1 and L_delta Q")
    Qx, Qy = dx(Qp), dy(Qp)

    def gdx(p):
        return add(dx(p), scale(mul(Qx, p), -1))

    def gdy(p):
        return add(dy(p), scale(mul(Qy, p), -1))
    # L(H e^-Q) e^Q (L 1 = 0)
    pre = scale(add(gdx(gdx(H)), scale(gdx(gdy(H)), -1), gdy(gdy(H))), Fr(1, 3))
    target = mul(H, add(Qp, {(0, 0): Fr(-4)}))
    ok = add(pre, scale(target, -1)) == {}
    val = ev(pre, 1, 2)
    print(f"  e^Q L(H e^-Q) == H (Q - 4) as polynomials: {ok}; value at (1,2): {val} (times e^-7)")
    if not ok or val != 9:
        hit(f"commutator identity fails or value {val} != 9 at (1,2)")
    # L_delta Q = L Q + (cx Q_x + cy Q_y)/(3 delta), exact as rational function: check delta*(L_delta Q - 4) == 0
    dlx, dly = dx(DELTA), dy(DELTA)
    cxn = add(scale(dlx, 2), scale(dly, -1))
    cyn = add(scale(dlx, -1), scale(dly, 2))
    num = add(mul(scale(DELTA, 3), L(Qp)), mul(cxn, Qx), mul(cyn, Qy))   # 3 delta L_delta Q
    ok2 = add(num, scale(DELTA, -12)) == {}
    print(f"  L_delta Q == 4 exactly: {ok2}")
    return ok, val, ok2


def run_D5():
    print("=" * 78)
    print("D5  the note's falsifier table, recomputed")
    x0, y0 = 1, 2
    d = lambda a, b: ev(DELTA, a, b)
    sxp = (-x0, x0 + y0)
    rows = {
        "delta(1,2)": d(x0, y0),
        "delta(s_x(1,2))": d(*sxp),
        "delta(swap(1,2))": d(y0, x0),
        "signed delta*anti (1,2)": d(x0, y0) * d(x0, y0),
        "signed delta*anti s_x(1,2)": d(*sxp) * d(*sxp),
        "|delta|*anti (1,2)": abs(d(x0, y0)) * d(x0, y0),
        "|delta|*anti s_x(1,2)": abs(d(*sxp)) * d(*sxp),
        "B2-style degree-4 product": Fr(x0 * y0 * (x0 + y0) * (x0 + 2 * y0)),
        "G2-style degree-6 product": Fr(x0 * y0 * (x0 + y0) * (x0 + 2 * y0) * (x0 + 3 * y0) * (2 * x0 + 3 * y0)),
        "A1 single-root product": Fr(x0),
    }
    # L(u^2+v^2) with u = x+y, v = x-y: u^2+v^2 = 2x^2 + 2y^2
    uv2 = {(2, 0): Fr(2), (0, 2): Fr(2)}
