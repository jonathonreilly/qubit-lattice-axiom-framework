def clean(p):
    return {k: v for k, v in p.items() if v != 0}


def add(*ps):
    out = {}
    for p in ps:
        for k, v in p.items():
            out[k] = out.get(k, 0) + v
    return clean(out)


def scale(p, c):
    return clean({k: v * c for k, v in p.items()})


def mul(p, q):
    out = {}
    for (i, j), a in p.items():
        for (k, l), b in q.items():
            out[(i + k, j + l)] = out.get((i + k, j + l), 0) + a * b
    return clean(out)


def dx(p):
    return clean({(i - 1, j): v * i for (i, j), v in p.items() if i > 0})


def dy(p):
    return clean({(i, j - 1): v * j for (i, j), v in p.items() if j > 0})


def ev(p, x, y):
    return sum((v * Fr(x) ** i * Fr(y) ** j for (i, j), v in p.items()), Fr(0))


def lin_power(a, b, n):
    """(a x + b y)^n"""
    return clean({(k, n - k): Fr(comb(n, k)) * Fr(a) ** k * Fr(b) ** (n - k) for k in range(n + 1)})


def compose_linear(p, M):
    """p(M00 x + M01 y, M10 x + M11 y)"""
    out = {}
    cache = {}
    for (i, j), v in p.items():
        key = (i, j)
        if key not in cache:
            cache[key] = mul(lin_power(M[0][0], M[0][1], i), lin_power(M[1][0], M[1][1], j))
        for k, w in cache[key].items():
            out[k] = out.get(k, 0) + v * w
    return clean(out)


X = {(1, 0): Fr(1)}
