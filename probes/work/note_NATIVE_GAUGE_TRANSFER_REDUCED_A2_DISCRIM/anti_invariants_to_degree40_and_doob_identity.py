Qp = {(2, 0): Fr(1), (1, 1): Fr(1), (0, 2): Fr(1)}  # x^2 + x y + y^2
H = scale(DELTA, Fr(1, 2))
SX = ((-1, 0), (1, 1))     # (x, y) -> (-x, x+y)
SY = ((1, 1), (0, -1))     # (x, y) -> (x+y, -y)
SXY = ((0, -1), (-1, 0))   # (x, y) -> (-y, -x)
SWAP = ((0, 1), (1, 0))


def matmul(A, B):
    return tuple(tuple(sum(A[i][k] * B[k][j] for k in range(2)) for j in range(2)) for i in range(2))


def L(p):
    return scale(add(dx(dx(p)), scale(dx(dy(p)), -1), dy(dy(p))), Fr(1, 3))


