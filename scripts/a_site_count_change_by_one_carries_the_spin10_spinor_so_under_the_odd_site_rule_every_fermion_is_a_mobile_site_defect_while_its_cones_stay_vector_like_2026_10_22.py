def move(occ, sign, x, y, nm=5):
    """Move whole content of slot y into empty slot x (mode-level fermionic swap); occ: dict slot->bits."""
    assert occ.get(x) is None
    before = [5 * s + m for s in sorted(occ) for m in range(nm) if (occ[s] >> m) & 1]
    new = dict(occ)
    new[x] = new.pop(y)
    relab = [(5 * x + (i - 5 * y)) if i // 5 == y else i for i in before]
    inv = sum(1 for i in range(len(relab)) for j in range(i + 1, len(relab)) if relab[i] > relab[j])
    return new, sign * (-1) ** inv


