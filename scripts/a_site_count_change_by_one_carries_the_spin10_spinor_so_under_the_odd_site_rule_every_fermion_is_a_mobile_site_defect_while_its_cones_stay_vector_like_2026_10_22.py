def ham_vac(J):
    H = np.zeros((len(vb), len(vb)), complex)
    for i, t in enumerate(vb):
        for x in range(L):
            y = (x + 1) % L
            for a2, b2, amp in Bnz[16 * t[x] + t[y]]:
                tt = list(t); tt[x], tt[y] = a2, b2
                H[vidx[tuple(tt)], i] += J * amp
    return H


def slots(state):
    v, t = state
    occ, it = {}, iter(t)
    for x in range(L):
        if x != v:
            occ[x] = next(it)
    return occ


def pack(occ):
    v = [x for x in range(L) if x not in occ][0]
    return (v, tuple(occ[x] for x in sorted(occ)))


def ham_def(J, t):
    H = np.zeros((len(db), len(db)), complex)
    for i, st in enumerate(db):
        occ = slots(st)
        for x in range(L):
            y = (x + 1) % L
            if x in occ and y in occ:
                for a2, b2, amp in Bnz[16 * occ[x] + occ[y]]:
                    o2 = dict(occ); o2[x], o2[y] = a2, b2
                    H[didx[pack(o2)], i] += J * amp
        v = st[0]
        for y in ((v - 1) % L, (v + 1) % L):
            o2 = dict(occ); o2[v] = o2.pop(y)
            lo, hi = sorted((v, y))
            sg = (-1) ** sum(1 for z in occ if lo < z < hi and z != y)
            H[didx[pack(o2)], i] += -t * sg
    return H


def casimir(states, occfun, index):
    C = np.zeros((len(states), len(states)), complex)
    for i, st in enumerate(states):
        occ = occfun(st)
        C[i, i] += 45 / 4 * len(occ)
        for x, y in itertools.combinations(sorted(occ), 2):
            for a2, b2, amp in Bnz[16 * occ[x] + occ[y]]:
                o2 = dict(occ); o2[x], o2[y] = a2, b2
                C[index(o2), i] += 2 * amp
    return C


