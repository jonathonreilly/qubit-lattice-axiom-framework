# ---------------------------------------------------------------- Fock helpers
def majoranas(nm):
    """Majoranas on nm modes, JW order mode 0 first; basis index bit m = n_m."""
    dim = 1 << nm
    gs = []
    for m in range(nm):
        rows, cols, vals = [], [], []
        for s in range(dim):
            if (s >> m) & 1:
                rows.append(s ^ (1 << m)); cols.append(s); vals.append((-1) ** popc(s & ((1 << m) - 1)))
        C = sp.csr_matrix((vals, (rows, cols)), shape=(dim, dim), dtype=complex)
        gs.append((C + C.T).tocsr())
        gs.append((1j * (C.T - C)).tocsr())
    return gs


def generators(gs, nsites):
    """M_ab = (i/2) sum_s g_a^s g_b^s, a<b in 0..9."""
