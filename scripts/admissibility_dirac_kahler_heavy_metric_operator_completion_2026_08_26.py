def measure_setup(point: tuple) -> dict:
    """THE SETUP, AND EVERY LINE OF IT IS A FORMULA.  A = cells{1..7},
    D = cells{2,3,4}, K_AD and M_2,AD the rectangular reflected pairings, the
    section the pivot columns of rref(K_AD), K_c and M_2c their extractions,
    T_2 = K_c^-1 M_2c, U the two-site shift, B_h its -1 eigenbasis."""
    record = carrier(point)
    inverse = record["inverse"]
    full = cells(POSITIVE_SLICES)
    domain = cells(INTERIOR_WINDOW)
    gram = reflected_pairing(inverse, full, full, 0)
    window = reflected_pairing(inverse, full, domain, 0)
    shifted = reflected_pairing(inverse, full, domain, 2)

    window_rank = exact_rank(window)
    kernel = sp.Matrix.hstack(*window.nullspace())
    annihilated = sp.expand(shifted * kernel)
    obstruction = exact_rank(window.col_join(shifted)) - window_rank

    _, pivots = rational_matrix(window).rref()
    pivots = tuple(pivots)
    reps = tuple(domain[column] for column in pivots)
    position = {cell: index for index, cell in enumerate(full)}
    rows = tuple(position[cell] for cell in reps)
    quotient_gram = gram.extract(rows, rows)
    quotient_form = shifted.extract(rows, pivots)
    operator = sp.expand(exact_inverse(quotient_gram) * quotient_form)

    involution = spatial_shift(reps, 2)
    one_site = spatial_shift(reps, 1)
    heavy_basis = eigen_basis(involution, -1)
    heavy_left = coordinate_left_inverse(heavy_basis)
    heavy_gram = sp.expand(heavy_basis.T * quotient_gram * heavy_basis)
    heavy_form = sp.expand(heavy_basis.T * quotient_form * heavy_basis)
    heavy = sp.expand(exact_inverse(heavy_gram) * heavy_form)
    form_defect = sp.expand(heavy_form - heavy_form.T)
    os_defect = sp.expand(heavy_gram * heavy - heavy.T * heavy_gram)

    facts = SetupFacts(
        point=point,
        carrier_rank=record["rank"],
        grade_complex=record["grade_complex"],
        hodge_reflection=record["hodge_reflection"],
        covariance=record["covariance"],
        inverse_residuals=record["inverse_residuals"],
        inverse_seconds=record["inverse_seconds"],
        span_size=len(full),
        domain_size=len(domain),
        window_rank=window_rank,
        window_nullity=window.cols - window_rank,
        window_annihilation=(exact_rank(annihilated)
                             if residual_count(annihilated) else 0,
                             residual_count(annihilated)),
        obstruction=obstruction,
        pivots=pivots,
        section=reps,
        quotient_symmetry=residual_count(quotient_gram - quotient_gram.T),
        quotient_minors=minor_signs(quotient_gram),
        quotient_factors=factor_census(operator),
        involution_residuals=(
            residual_count(involution * involution - sp.eye(QUOTIENT_DIM)),
            residual_count(involution.T * quotient_gram * involution
                           - quotient_gram),
            residual_count(operator * involution - involution * operator)),
        one_site_defect=residual_count(
            one_site.T * quotient_gram * one_site - quotient_gram),
        heavy_basis=tuple(tuple(int(heavy_basis[row, column])
                                for row in range(QUOTIENT_DIM))
                          for column in range(SECTOR_DIM)),
        heavy_form_defect=(residual_count(form_defect),
                           exact_rank(form_defect)),
        heavy_os_defect=(residual_count(os_defect), exact_rank(os_defect)),
        heavy_factors=factor_census(heavy))
    return {"facts": facts, "gram": quotient_gram, "form": quotient_form,
            "operator": operator, "reps": reps, "heavy": heavy,
            "heavy_gram": heavy_gram, "heavy_basis": heavy_basis,
            "heavy_left": heavy_left, "involution": involution,
            "one_site": one_site}


def measure_space(frame: dict, point: tuple) -> dict:
    """THE SYMMETRIZER SPACE, SOLVED AND THEN DISPLAYED AS A PARAMETERIZATION.
    Theta = Theta^T is imposed by construction on ten unknowns; the sixteen
    equations of Theta T_h = T_h^T Theta are turned into an exact coefficient
    matrix over QQ and its nullity IS the dimension."""
    heavy = frame["heavy"]
    unknowns = sp.symbols("th0:10")
    generic = symmetric_from(unknowns)
    equations = list(sp.expand(generic * heavy - heavy.T * generic))
    coefficients, right_hand = sp.linear_eq_to_matrix(equations, unknowns)
    assert all(value == 0 for value in right_hand)
    coefficient_rank = exact_rank(coefficients)

    full_unknowns = sp.symbols("g0:16")
    full_generic = sp.Matrix(4, 4, list(full_unknowns))
    intertwiner = sp.linear_eq_to_matrix(
        list(sp.expand(full_generic * heavy - heavy.T * full_generic)),
        full_unknowns)[0]
    commutant = sp.linear_eq_to_matrix(
        list(sp.expand(full_generic * heavy - heavy * full_generic)),
        full_unknowns)[0]

    solved = sp.solve(equations, unknowns, dict=True)[0]
    family = sp.expand(generic.subs(solved))
    free_symbols = [s for s in unknowns if s not in solved]
    free_entries = tuple((row, column) for (row, column) in UPPER
                         if family[row, column] in free_symbols)
    determined = tuple((row, column) for (row, column) in UPPER
                       if (row, column) not in free_entries)
    order = [sp.Symbol(f"t{row}{column}") for (row, column) in free_entries]
    rename = {family[row, column]: sp.Symbol(f"t{row}{column}")
              for (row, column) in free_entries}
    display = sp.expand(family.subs(rename, simultaneous=True))

    # The displayed primitive integer relations were normalized at FIXTURE.
    # They are not universal coefficients and must not be reported against the
    # second rational point, whose nullspace has a different normalization.
    forced = {}
    if point == FIXTURE:
        for (row, column) in determined:
            coefficients_row = FORCED_RELATIONS.get((row, column))
            if coefficients_row is None:               # pragma: no cover
                forced[(row, column)] = -1
                continue
            expression = sp.Integer(coefficients_row[0]) * display[row, column]
            for value, symbol in zip(coefficients_row[1:], order):
                expression += sp.Integer(value) * symbol
            forced[(row, column)] = 0 if sp.expand(expression) == 0 else 1

    product = sp.expand(display * heavy)
    family_residuals = (
        residual_count(display - display.T),
        residual_count(display * heavy - heavy.T * display),
        residual_count(product - product.T))

    one_site_heavy = sp.expand(frame["heavy_left"] * frame["one_site"]
                               * frame["heavy_basis"])
    cut_equations = equations + list(
        sp.expand(one_site_heavy.T * generic * one_site_heavy - generic))
    cut_coefficients = sp.linear_eq_to_matrix(cut_equations, unknowns)[0]
    cut_rank = exact_rank(cut_coefficients)
    cut_basis = cut_coefficients.nullspace()
    a_symbol, b_symbol = sp.symbols("a b")
    cut_family = sp.expand(
        a_symbol * symmetric_from(list(cut_basis[0]))
        + b_symbol * symmetric_from(list(cut_basis[1])))
    alpha, beta = FAMILY_ALPHA[point], FAMILY_BETA[point]
    radius = FAMILY_R[point]
    diagonal_entry = alpha * a_symbol + beta * b_symbol
    declared = sp.Matrix(
        [[diagonal_entry, 0, a_symbol, -radius * a_symbol],
         [0, diagonal_entry, radius * a_symbol, a_symbol],
         [a_symbol, radius * a_symbol, b_symbol, 0],
         [-radius * a_symbol, a_symbol, 0, b_symbol]])

    facts = SpaceFacts(
        unknowns=len(unknowns),
        equations=len(equations),
        coefficient_rank=coefficient_rank,
        dimension=len(unknowns) - coefficient_rank,
        intertwiner_dimension=16 - exact_rank(intertwiner),
        commutant_dimension=16 - exact_rank(commutant),
        free_entries=free_entries,
        determined_entries=determined,
        forced_residuals=forced,
        family_residuals=family_residuals,
        s_heavy=tuple(tuple(int(one_site_heavy[i, j]) for j in range(4))
                      for i in range(4)),
        s_heavy_residuals=(
            residual_count(one_site_heavy * one_site_heavy + sp.eye(4)),
            residual_count(one_site_heavy * heavy - heavy * one_site_heavy)),
        s_cut_rank=cut_rank,
        s_cut_dimension=len(unknowns) - cut_rank,
        family_alpha=alpha,
        family_beta=beta,
        family_r=radius,
        family_gamma=sp.expand(1 + radius ** 2),
        family_display_residual=residual_count(
            sp.expand(declared - cut_family)))
    return {"facts": facts, "display": display, "order": order,
            "cut_family": declared, "a": a_symbol, "b": b_symbol,
            "s_heavy": one_site_heavy}


def measure_completion(frame: dict, space: dict, point: tuple
                       ) -> CompletionFacts:
    """THE COMPLETION.  The minimal polynomial is the mechanism; the two
    exhibited points are witnesses, not the argument."""
    heavy = frame["heavy"]
    coefficients = HEAVY_FACTORS[point]
    a, b, c = (sp.Integer(v) for v in coefficients)
    tau = sp.Rational(-b, a)
    display = space["display"]
    product = sp.expand(display * heavy)
    diagonal = sp.diag(*THETA_DIAGONAL) if point == FIXTURE \
        else sp.diag(*SECOND_RAY)
    second = sp.Matrix(THETA_SECOND) if point == FIXTURE else diagonal
    diagonal_product = sp.expand(diagonal * heavy)
    second_product = sp.expand(second * heavy)
    return CompletionFacts(
        minimal_residual=residual_count(
            a * heavy * heavy + b * heavy + c * sp.eye(4)),
        tau_residual=residual_count(
            heavy * heavy - tau * heavy + sp.eye(4)),
        irreducible=len(sp.factor_list(a * Z ** 2 + b * Z + c)[1]) == 1
        and sp.factor_list(a * Z ** 2 + b * Z + c)[1][0][1] == 1,
        charpoly_square_residual=0 if sp.expand(
            a ** 2 * symbolic_determinant(heavy - Z * sp.eye(4))
            - (a * Z ** 2 + b * Z + c) ** 2) == 0 else 1,
        tau=tau,
        tau_minus_two=sp.Rational(tau - 2),
        discriminant=b ** 2 - 4 * a * c,
        root_product=sp.Rational(c, a),
        parameterization_residuals=(
            residual_count(display - display.T),
            residual_count(display * heavy - heavy.T * display),
            residual_count(product - product.T),
            residual_count(sp.expand(
                display * (heavy * heavy - tau * heavy + sp.eye(4))))),
        diagonal=tuple(int(diagonal[i, i]) for i in range(4)),
        diagonal_minors=tuple(leading_minors(diagonal)),
        diagonal_product_minors=tuple(leading_minors(diagonal_product)),
        diagonal_s_residual=residual_count(
            space["s_heavy"].T * diagonal * space["s_heavy"] - diagonal),
        second=tuple(tuple(int(second[i, j]) for j in range(4))
                     for i in range(4)),
        second_minors=tuple(leading_minors(second)),
        second_product_minors=tuple(leading_minors(second_product)),
        second_s_residual=residual_count(
            space["s_heavy"].T * second * space["s_heavy"] - second),
        pd_residuals=(
            residual_count(diagonal * heavy - heavy.T * diagonal)
            + residual_count(second * heavy - heavy.T * second),
            residual_count(diagonal_product - diagonal_product.T)
            + residual_count(second_product - second_product.T)))


def measure_cone(space: dict, point: tuple) -> ConeFacts:
    """The four Sylvester minors are formulas, and the displayed positive
    region contains a rational box."""
    family = space["cut_family"]
    a_symbol, b_symbol = space["a"], space["b"]
    alpha, beta = FAMILY_ALPHA[point], FAMILY_BETA[point]
    gamma = sp.expand(1 + FAMILY_R[point] ** 2)
    diagonal_entry = alpha * a_symbol + beta * b_symbol
    schur = diagonal_entry * b_symbol - gamma * a_symbol ** 2
    predicted = (diagonal_entry, diagonal_entry ** 2,
                 diagonal_entry * schur, schur ** 2)
    residuals = tuple(
        0 if sp.expand(symbolic_determinant(family[:k, :k]) - predicted[k - 1])
        == 0 else 1 for k in range(1, 5))
    ray = sp.expand(family.subs({a_symbol: 0, b_symbol: 1}))
    bad = sp.expand(family.subs({a_symbol: 1, b_symbol: 0}))
    primitive = primitive_matrix(ray)
    a_margin = beta * BOX_B_LOW - alpha * BOX_A
    product_margin = sp.expand(a_margin * BOX_B_LOW - gamma * BOX_A ** 2)
    corners = tuple(
        minor_signs(sp.expand(family.subs({a_symbol: pa, b_symbol: pb})))
        for pa, pb in BOX_CORNERS)
    coordinates = sp.Matrix([[pa, pb] for pa, pb in RAYLESS_POINTS])
    return ConeFacts(
        minor_residuals=residuals,
        ray_point=RAY_POINT,
        ray_minor_signs=minor_signs(ray),
        ray_primitive=tuple(tuple(int(primitive[i, j]) for j in range(4))
                            for i in range(4)),
        non_pd_point=NON_PD_POINT,
        non_pd_minor_signs=minor_signs(bad),
        box_a_margin=a_margin,
        box_product_margin=product_margin,
        corner_signs=corners,
        rayless_rank=exact_rank(coordinates),
        rayless_signs=tuple(
            minor_signs(sp.expand(family.subs({a_symbol: pa, b_symbol: pb})))
            for pa, pb in RAYLESS_POINTS))


def measure_cut(frame: dict) -> CutFacts:
    """THE BLOCK 197 CUT, TESTED RATHER THAN ASSUMED.  The vacuity is proved for
    a SYMBOLIC X, so no choice of the landed datum could have changed it; one
    concrete Y' is then rebuilt on this frame with all four landed identities."""
    reps, gram, operator = frame["reps"], frame["gram"], frame["operator"]
    heavy_basis, heavy_left = frame["heavy_basis"], frame["heavy_left"]
    shift = frame["one_site"]
    identity = sp.eye(QUOTIENT_DIM)
    square = sp.expand(shift * shift)
    p_zero = sp.expand((identity + shift + square + shift ** 3) / 4)
    p_two = sp.expand((identity - shift + square - shift ** 3) / 4)
    p_heavy = sp.expand((identity - square) / 2)
    basis_zero = sp.Matrix.hstack(*p_zero.columnspace())
    basis_two = sp.Matrix.hstack(*p_two.columnspace())
    pi_zero = coordinate_left_inverse(basis_zero)
    pi_two = coordinate_left_inverse(basis_two)

    symbolic_x = sp.Matrix(2, 2, sp.symbols("x0:4"))
    symbolic_y = sp.Matrix(2, 2, sp.symbols("y0:4"))
    generic = sp.expand(basis_two * symbolic_x * pi_zero
                        + basis_zero * symbolic_y * pi_two + p_heavy)

    monodromy_zero = sp.expand(pi_zero * operator * basis_zero)
    monodromy_two = sp.expand(pi_two * operator * basis_two)
    gram_zero = sp.expand(basis_zero.T * gram * basis_zero)
    gram_two = sp.expand(basis_two.T * gram * basis_two)
    x_star = sp.Matrix([[sp.Rational(X_STAR[0][0]), sp.Rational(X_STAR[0][1])],
                        [sp.Rational(X_STAR[1][0]), sp.Rational(X_STAR[1][1])]])
    completion_operator = sp.expand(
        basis_two * x_star * pi_zero
        + basis_zero * exact_inverse(x_star) * pi_two + p_heavy)
    return CutFacts(
        projector_ranks=(exact_rank(p_zero), exact_rank(p_two),
                         exact_rank(p_heavy)),
        partition_residual=residual_count(
            p_zero + p_two + p_heavy - identity),
        orthogonality=(residual_count(pi_zero * heavy_basis),
                       residual_count(pi_two * heavy_basis),
                       residual_count(p_heavy * heavy_basis - heavy_basis)),
        generic_residuals=(
            residual_count(sp.expand(generic * heavy_basis - heavy_basis)),
            residual_count(sp.expand(heavy_left * generic * heavy_basis
                                     - sp.eye(SECTOR_DIM)))),
        isospectrality=0 if sp.expand(
            monodromy_zero.charpoly(Z).as_expr()
            - monodromy_two.charpoly(Z).as_expr()) == 0 else 1,
        x_star_residuals=(
            residual_count(x_star * monodromy_zero - monodromy_two * x_star),
            residual_count(x_star.T * gram_two * x_star - gram_zero)),
        x_star_det=exact_determinant(x_star),
        gram_ratio=sp.Rational(exact_determinant(gram_zero)
                               / exact_determinant(gram_two)),
        yprime_residuals=(
            residual_count(completion_operator * operator
                           - operator * completion_operator),
            residual_count(completion_operator.T * gram * completion_operator
                           - gram),
            residual_count(completion_operator * completion_operator
                           - identity)),
        yprime_rank=exact_rank(completion_operator),
        yprime_heavy=residual_count(
            sp.expand(heavy_left * completion_operator * heavy_basis
                      - sp.eye(SECTOR_DIM))))


def measure_check_theta(frame: dict) -> CheckThetaFacts:
    """THE ADVERSARIAL RECORD'S OWN DISPLAYED MATRIX, MEASURED IN BOTH
    DIRECTIONS.  Every signed permutation of the four heavy basis vectors is
    swept, so 'a reordering exists' is a COUNT and not an anecdote."""
    import itertools
    heavy = frame["heavy"]
    theta = sp.Matrix(CHECK_THETA)
    admissible = 0
    for permutation in itertools.permutations(range(4)):
        placement = sp.zeros(4, 4)
        for index, image in enumerate(permutation):
            placement[image, index] = 1
        for signs in itertools.product((1, -1), repeat=4):
            change = sp.expand(placement * sp.diag(*signs))
            reordered = sp.expand(exact_inverse(change) * heavy * change)
            if residual_count(theta * reordered - reordered.T * theta) == 0:
                admissible += 1
    change = sp.Matrix(CHECK_THETA_REORDERING)
    reordered = sp.expand(exact_inverse(change) * heavy * change)
    product = sp.expand(theta * reordered)
    minors = tuple(leading_minors(product))
    return CheckThetaFacts(
        declared_defect=residual_count(theta * heavy - heavy.T * theta),
        reordered_defect=residual_count(
            theta * reordered - reordered.T * theta),
        admissible=admissible,
        own_minors=tuple(leading_minors(theta)),
        rebuilt_product_minors=minors,
        product_minor_signs=tuple(int(sp.sign(v)) for v in minors),
        claimed_reproducible=minors == tuple(
            sp.Integer(v) for v in CHECK_CLAIMED_PRODUCT_MINORS))


