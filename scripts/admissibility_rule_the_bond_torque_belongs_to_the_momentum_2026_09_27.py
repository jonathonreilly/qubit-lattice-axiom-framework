def sn(x):
    return (x - 1 / x) / (2 * I)


def cs(x):
    return (x + 1 / x) / 2


def hmat(zz):
    return sum((sn(zz[a]) * SIG[a] for a in range(3)), sp.zeros(2))


def symbols_of(zk, zkp, density="x"):
    """matrix symbols (pair <k'| . |k>) of: A_a, f_a, block 63's J, block 69's K, the symmetric K^s and the densities"""
    A = [R(1, 4) * (zk[a] + 1 / zkp[a]) * SIG[a] for a in range(3)]
    f = [R(1, 2) * (1 + zk[a] / zkp[a]) * sn(zk[a] * zkp[a]) for a in range(3)]
    h, hp = hmat(zk), hmat(zkp)
    J = [[A[a] * (sn(zk[j]) + sn(zkp[j])) for j in range(3)] for a in range(3)]
    g = [(sn(zk[j]) * cs(zk[j]) + sn(zkp[j]) * cs(zkp[j])) for j in range(3)]
    K69 = [[A[a] * g[j] for j in range(3)] for a in range(3)]
    Ks = [[R(1, 2) * (A[a] * f[j] + A[j] * f[a]) for j in range(3)] for a in range(3)]
    half = R(1, 2) if not (mut("density_forged") and density == "s") else 0
