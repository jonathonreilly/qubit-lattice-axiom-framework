    Bt[0, 0], Bt[0, 1], Bt[0, 2], Bt[1, 0], Bt[1, 1], Bt[1, 2] = xs
    fam = c1 * quadT(Bt, (0, 0, kap))[0] + c2 * quadT(Bt, (0, 0, kap))[1] + c3 * quadT(Bt, (0, 0, kap))[2]
    M6 = sp.hessian(fam, xs) / 2
