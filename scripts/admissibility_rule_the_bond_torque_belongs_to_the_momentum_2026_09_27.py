def band_expect(M, zk):
    s = [sn(t) for t in zk]
    E = sp.sqrt(sp.expand(sum(t ** 2 for t in s)))
    Pi = (sp.eye(2) + hmat(zk) / E) / 2
    return sp.simplify(sp.trace(Pi * M))  # trace over the band's rank-one projector = expectation in its normalised coin


