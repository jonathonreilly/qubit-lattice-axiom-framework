def perm_matrix(sigma: dict[int, int]) -> sp.Matrix:
    """Return the standard 3x3 permutation matrix P_sigma with
    P_sigma e_j = e_{sigma(j)}. Equivalently (P_sigma)_{i, j}
    = delta_{i, sigma(j)}."""
    M = sp.zeros(3, 3)
    for j in [1, 2, 3]:
        i = sigma[j]
        M[i - 1, j - 1] = 1
    return M


def matrix_unit(i: int, j: int) -> sp.Matrix:
    """3x3 standard matrix unit E_{ij} with 1 at row i, col j, else 0
    (using 1-based indices)."""
    M = sp.zeros(3, 3)
    M[i - 1, j - 1] = 1
    return M


def s3_elements() -> dict[str, dict[int, int]]:
    return {
        "id": {1: 1, 2: 2, 3: 3},
        "(1 2)": {1: 2, 2: 1, 3: 3},
        "(1 3)": {1: 3, 2: 2, 3: 1},
        "(2 3)": {1: 1, 2: 3, 3: 2},
        "(1 2 3)": {1: 2, 2: 3, 3: 1},
        "(1 3 2)": {1: 3, 2: 1, 3: 2},
    }


