def place_node(
    site: Coord,
    kind: str,
    lane: int | None,
    parents: frozenset[Coord],
) -> Coord:
    if site in NODE_KIND or site in CABLE_DYNAMIC or site in TERMINAL_BITS:
        raise ValueError(("dynamic-overlap", site, NODE_KIND.get(site), kind))
    if not parents or any(manhattan(site, parent) != 1 for parent in parents):
        raise ValueError(("nonlocal-parent", site, parents))
    NODE_KIND[site] = kind
    NODE_LANE[site] = lane
    CUSTOM_PARENTS[site] = parents
    return site


def add_path(
    parent: Coord,
    waypoints: tuple[Coord, ...],
    kind: str,
    lane: int | None,
) -> Coord:
    previous = parent
    for site in lattice_path(parent, waypoints):
        place_node(site, kind, lane, frozenset((previous,)))
        previous = site
    return previous


def add_join(left: Coord, right: Coord, target: Coord) -> Coord:
    return place_node(target, "status", None, frozenset((left, right)))


