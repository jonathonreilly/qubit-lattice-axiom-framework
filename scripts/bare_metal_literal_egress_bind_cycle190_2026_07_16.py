def extension_closure(
    records: RoleMap,
    wanted: RoleMap,
    *,
    order: str,
):
    records = dict(records)
    formed = set()
    wrong = []
    maximum = 0
    actual = enabled(records)
    while True:
        live = {
            site: roles
            for site, roles in actual.items()
            if site not in records and site in EXTENSION_DYNAMIC
        }
        bad = {
            site: roles
            for site, roles in live.items()
            if wanted.get(site) != next(iter(roles))
        }
        if bad:
            wrong.append((len(formed), bad))
            break
        futures = tuple(site for site in live if site in wanted)
        maximum = max(maximum, len(futures))
        if not futures:
            break
        target = min(futures) if order == "min" else max(futures)
        records[target] = wanted[target]
        formed.add(target)
        c171.refresh_after_append(records, actual, target)
    return {
        "formed": frozenset(formed),
        "wrong": tuple(wrong),
        "maximum": maximum,
    }


