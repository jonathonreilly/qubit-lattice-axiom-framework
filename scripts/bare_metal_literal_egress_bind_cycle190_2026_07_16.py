def manhattan(left: Coord, right: Coord) -> int:
    return sum(abs(a - b) for a, b in zip(left, right))


def lattice_path(
    start: Coord,
    waypoints: tuple[Coord, ...],
) -> tuple[Coord, ...]:
    """Nearest-neighbour path excluding start and including each waypoint."""

    current = list(start)
    path = []
    for waypoint in waypoints:
        axes = tuple(
            axis for axis in range(3)
            if current[axis] != waypoint[axis]
        )
        if len(axes) > 1:
            raise ValueError(("non-axis-waypoint", tuple(current), waypoint))
        if not axes:
            continue
        axis = axes[0]
        while current[axis] != waypoint[axis]:
            current[axis] += 1 if waypoint[axis] > current[axis] else -1
            path.append(tuple(current))
    if len(path) != len(set(path)):
        raise ValueError(("path-self-contact", start, waypoints))
    return tuple(path)


def merge_records(*parts: RoleMap) -> RoleMap:
    merged: RoleMap = {}
    for part in parts:
        for site, role in part.items():
            prior = merged.setdefault(site, role)
            if prior != role:
                raise ValueError(("record-conflict", site, prior, role))
    return merged


