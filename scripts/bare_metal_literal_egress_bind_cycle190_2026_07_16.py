    if observed_ports != wanted_ports:
        raise ValueError(("cable-port-mismatch", observed_ports ^ wanted_ports))
    remove = (
        set(REFERENCE_INITIAL)
        | set(REFERENCE_BASE_EXPECTED)
        | set(TERMINAL_BITS)
        | set(CABLE_DYNAMIC)
    )
    scaffold = {
        site: role
        for site, role in all_records.items()
        if site not in remove
    }
    return scaffold, frozenset(observed_ports)


