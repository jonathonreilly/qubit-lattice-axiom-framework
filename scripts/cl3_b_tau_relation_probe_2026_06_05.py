#   16 pi^2 dy_b/dt = y_b ( 9/2 y_b^2 + 3/2 y_t^2 + y_tau^2
#                           - (1/4 g1^2 + 9/4 g2^2 + 8 g3^2) )
#   16 pi^2 dy_tau/dt = y_tau ( 5/2 y_tau^2 + 3 y_t^2 + 3 y_b^2
#                           - (9/4 g1^2 + 9/4 g2^2) )       <-- NO 8 g3^2 term
#
# The asymmetry that splits y_b from y_tau is precisely the color coupling
# 8 g3^2 in dy_b/dt that is ABSENT in dy_tau/dt (leptons are color-singlets).

INV16PI2 = 1.0 / (16.0 * math.pi**2)
B_GAUGE = (41.0 / 10.0, -19.0 / 6.0, -7.0)  # SM 1-loop, GUT-normalized g1


def derivs(y):
    """y = [g1, g2, g3, yt, yb, ytau];  returns dy/dt (1-loop SM)."""
    g1, g2, g3, yt, yb, ytau = y
    g1sq, g2sq, g3sq = g1 * g1, g2 * g2, g3 * g3
    yt2, yb2, ytau2 = yt * yt, yb * yb, ytau * ytau

    dg1 = B_GAUGE[0] * g1 * g1sq * INV16PI2
    dg2 = B_GAUGE[1] * g2 * g2sq * INV16PI2
    dg3 = B_GAUGE[2] * g3 * g3sq * INV16PI2

    dyt = yt * (4.5 * yt2 + 1.5 * yb2 + ytau2
                - (17.0 / 20.0 * g1sq + 2.25 * g2sq + 8.0 * g3sq)) * INV16PI2
    dyb = yb * (4.5 * yb2 + 1.5 * yt2 + ytau2
                - (0.25 * g1sq + 2.25 * g2sq + 8.0 * g3sq)) * INV16PI2
    dytau = ytau * (2.5 * ytau2 + 3.0 * yt2 + 3.0 * yb2
                    - (2.25 * g1sq + 2.25 * g2sq)) * INV16PI2
    return [dg1, dg2, dg3, dyt, dyb, dytau]


def rk4_step(y, h):
    k1 = derivs(y)
    y2 = [yi + 0.5 * h * ki for yi, ki in zip(y, k1)]
    k2 = derivs(y2)
    y3 = [yi + 0.5 * h * ki for yi, ki in zip(y, k2)]
    k3 = derivs(y3)
    y4 = [yi + h * ki for yi, ki in zip(y, k3)]
    k4 = derivs(y4)
    return [yi + (h / 6.0) * (a + 2 * b + 2 * c + d)
            for yi, a, b, c, d in zip(y, k1, k2, k3, k4)]


def integrate(y0, t0, t1, nsteps):
    h = (t1 - t0) / nsteps
    y = list(y0)
    for _ in range(nsteps):
        y = rk4_step(y, h)
    return y


