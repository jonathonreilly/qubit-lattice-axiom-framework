# Conventions:
#   t = ln(mu/GeV);  d X / d t = beta_X / (16 pi^2).
#   g1 is GUT-normalized: g1^2 = (5/3) g_Y^2  (so g1 = g2 = g3 at SU(5)).
#   1-loop gauge: d g_i/dt = b_i g_i^3/(16 pi^2),  b = (41/10, -19/6, -7).
#   1-loop top/bottom/tau Yukawa (3rd-gen dominant; lighter Yukawas dropped):
