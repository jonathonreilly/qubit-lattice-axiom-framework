# ------------------------------------------------ 5. diagonal energies of qubit slots, on balanced surroundings
# A 6^3 torus holds the planar 20-slot move. Surroundings are sampled among zero-charge configurations (every row
# balanced) by a SAT solver with random phases; the move's slots start where the move can act.
Lq = 6


def qkey(x, i, j):
    return (tuple(int(c) % Lq for c in x), (min(i, j), max(i, j)))


qcells = list(itertools.product(range(Lq), repeat=3))
qslots = [qkey(x, j, j) for x in qcells for j in range(3)] + [qkey(x, i, j) for x in qcells for (i, j) in PAIRS]
qsid = {k: n for n, k in enumerate(qslots)}
qrows = [[(qkey(k[0], *k[1]), c) for k, c in row_terms(x, j)] for x in qcells for j in range(3)]
Gq = np.zeros((len(qrows), len(qslots)), dtype=int)
for r, terms in enumerate(qrows):
    for k, c in terms:
        Gq[r, qsid[k]] += c
clauses = []
for terms in qrows:
    lits = [(qsid[k] + 1, c) for k, c in terms]
    for assign in itertools.product((0, 1), repeat=6):
        if sum(c * a for (_, c), a in zip(lits, assign)):
            clauses.append([-v if a else v for (v, _), a in zip(lits, assign)])
qmove = {qkey(np.array(k[0]) + 3, *k[1]): c for k, c in M_PLANAR.items()}
dmove = np.array([qmove.get(k, 0) for k in qslots])
qsup = [qsid[k] for k in qmove]
qout = sorted({t for t in range(len(qslots)) for q in qsup if t not in qsup and np.any(Gq[:, q] * Gq[:, t])})
Eq = np.sum(Gq ** 2, axis=0).astype(float)
qpairs = [(q, t, float(Gq[:, q] @ Gq[:, t])) for q in qsup for t in qout if np.any(Gq[:, q] * Gq[:, t])]


def pair_e4(q, t, o, sq, st):
    Est = Eq[q] + Eq[t] + 2 * sq * st * o
    return -(1 / (Eq[q] * Est * Eq[t]) + 1 / (Eq[q] * Est * Eq[q]) + 1 / (Eq[t] * Est * Eq[q]) + 1 / (Eq[t] * Est * Eq[t]))


diag_pairs = [(qsid[terms[0][0]], qsid[terms[1][0]]) for terms in qrows]
solver = Glucose4(bootstrap_with=clauses)
rngq = np.random.default_rng(20260924)
formula_dev, dNA = 0.0, []
for trial in range(12):
    solver.set_phases([v if rngq.random() < 0.5 else -v for v in range(1, len(qslots) + 1)])
    assert solver.solve(assumptions=[-(qsid[k] + 1) if c == 1 else qsid[k] + 1 for k, c in qmove.items()])
    xq = np.array([1 if lit > 0 else 0 for lit in solver.get_model()[:len(qslots)]])
    sig = 1 - 2 * xq
    dE = sum(pair_e4(q, t, o, -sig[q], sig[t]) - pair_e4(q, t, o, sig[q], sig[t]) for q, t, o in qpairs)
    x2 = xq ^ (dmove != 0)
    NA = sum(xq[a] != xq[b] for a, b in diag_pairs)
    NA2 = sum(x2[a] != x2[b] for a, b in diag_pairs)
    formula_dev = max(formula_dev, abs(dE - 201 / 960 * (NA2 - NA)))
    dNA.append(int(NA2 - NA))
solver.delete()
check("qubit slots get fourth-order diagonal potentials across a move: exactly (201/960) dN_A h^4/U^3 on balanced surroundings",
      formula_dev < 1e-12 and len(set(dNA)) > 2 and not np.any(Gq @ dmove),
      f"{len(qpairs)} slot pairs across the planar move's edge; 12 SAT-sampled zero-charge surroundings: largest deviation from "
      f"(201/960) dN_A {formula_dev:.0e}, dN_A values {sorted(set(dNA))} (N_A counts rows whose two diagonal slots differ)")

# ------------------------------------------------ 6. with an electric energy: the Gaussian spectrum
# Add a one-site electric energy (J/2) sum_s E_s^2 (supplied) and expand the cosines: physical modes live on ker G(k),
# with omega^2 = J g * eig of sum_planes v_p(k) v_p(k)^dag restricted there (v_p the Fourier image of the planar piece).
FACE_IX = {(0, 1): 3, (1, 2): 4, (0, 2): 5}


def G_k(k):
    Gk = np.zeros((3, 6), dtype=complex)
    for j in range(3):
        Gk[j, j] = np.exp(1j * k[j]) - 1
        for i in range(3):
            if i != j:
                Gk[j, FACE_IX[tuple(sorted((i, j)))]] += 1 - np.exp(-1j * k[i])
    return Gk


def piece_k(k, n_):
    a, b = [c for c in range(3) if c != n_]
    v = np.zeros(6, dtype=complex)
    v[a] = 2 * np.cos(k[b]) - 2
    v[b] = 2 * np.cos(k[a]) - 2
    i, j = min(a, b), max(a, b)
    v[FACE_IX[(i, j)]] = -1 + np.exp(-1j * k[i]) + np.exp(-1j * k[j]) - np.exp(-1j * (k[i] + k[j]))
    return v


def branches(k, scalar=False):
    Gk = G_k(k)
    V = np.array([piece_k(k, n_) for n_ in range(3)])
    K = np.linalg.svd(Gk)[2][3:].conj().T
    if scalar:
        # the landed scalar constraint S q = 0 on the conjugate slots: the phase of the summed pieces vanishes
        w = V.sum(axis=0) @ K
        K = K @ np.linalg.svd(w[None, :])[2][1:].conj().T
    return np.linalg.eigvalsh(K.conj().T @ V.conj().T @ V @ K), np.linalg.norm(V @ Gk.conj().T)


