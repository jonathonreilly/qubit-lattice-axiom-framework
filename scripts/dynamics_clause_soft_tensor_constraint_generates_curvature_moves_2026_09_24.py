# ------------------------------------------------ 7. modulo 2 the tensor rows are a Z2 gauge structure
def rank_mod2(M):
    M = M.copy() % 2
    r = 0
    for c in range(M.shape[1]):
        piv = [i for i in range(r, M.shape[0]) if M[i, c]]
        if not piv:
            continue
        M[[r, piv[0]]] = M[[piv[0], r]]
        for i in range(M.shape[0]):
            if i != r and M[i, c]:
                M[i] ^= M[r]
        r += 1
        if r == M.shape[0]:
            break
    return r


Lt = 3
