def residual_support(state: tuple[int, ...]) -> Support:
    banks, links = K.M.unpack_state(state, FIXTURE_BANKS)
    rows: list[Coordinate] = []
    if state[K.R3.X.SOURCE_POINTER]:
        rows.append(("source", "SOURCE_POINTER", 0))
    for bank_index, bank in enumerate(banks):
        rows.extend(
            ("bank", name, bank_index)
            for name, wire in watched_registers()
            if bank[wire]
        )
    for link_index, link in enumerate(links):
        rows.extend(
            ("link", f"WIRE_{wire}", link_index)
            for wire, bit in enumerate(link)
            if bit
        )
    return tuple(sorted(rows))


