def render_output(
    checks: dict[str, bool],
    findings: dict[str, str],
    certificates: dict[str, object],
    report: dict[str, object],
) -> str:
    lines = [
        f"{'PASS' if passed else 'FAIL'} {label}"
        for label, passed in checks.items()
    ]
    lines.extend(
        f"FINDING {label} {finding}"
        for label, finding in findings.items()
    )
    lines.extend(
        f"CERTIFICATE {label} {compact(certificate)}"
        for label, certificate in certificates.items()
    )
    lines.append("SUMMARY_JSON " + compact(report))
    lines.append(str(report["terminal"]))
    return "\n".join(lines) + "\n"


def stable_output(
    checks: dict[str, bool],
    findings: dict[str, str],
    certificates: dict[str, object],
    report: dict[str, object],
) -> str:
    for _attempt in range(20):
        report["checks"] = dict(checks)
        report["pass"] = all(checks.values())
        report["terminal"] = (
            "CYCLE816_FORECAST_INDEPENDENT_CHECK_CONFIRMED"
            if report["pass"]
            else "CYCLE816_FORECAST_INDEPENDENT_CHECK_HONEST_FAIL"
        )
        output = render_output(checks, findings, certificates, report)
        size = len(output.encode("utf-8"))
        controls = certificates["CONTROLS"]
        if (
            report["stdout_bytes"] == size
            and controls["stdout_bytes"] == size
        ):
            return output
        report["stdout_bytes"] = size
        controls["stdout_bytes"] = size
    raise AssertionError("stdout byte fixed point did not converge")


