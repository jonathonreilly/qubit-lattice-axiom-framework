def separated_pairs() -> tuple[tuple[int, int], ...]:
    return tuple(
        (left, right)
        for left, right in combinations(range(RING_STATIONS), 2)
        if min(
            (right - left) % RING_STATIONS,
            (left - right) % RING_STATIONS,
        ) > 1
    )


def support_counts(support: Support) -> tuple[int, ...]:
    source = sum(row[0] == "source" for row in support)
    bank = sum(row[0] == "bank" for row in support)
    link = sum(row[0] == "link" for row in support)
    bank0 = sum(
        row[0] == "bank" and row[2] == 0 for row in support
    )
    bank1 = sum(
        row[0] == "bank" and row[2] == 1 for row in support
    )
    kind_mask = int(source > 0) + 2 * int(bank > 0) + 4 * int(link > 0)
    return (
        source,
        bank,
        link,
        bank0,
        bank1,
        kind_mask,
        sum(row[2] for row in support),
    )


def occupied_set_feature_vector(
    event: int,
    positions: tuple[int, ...],
    direction: tuple[int, int],
    support: Support,
    pair_support_ids: dict[Support, int],
) -> tuple[Any, ...]:
    """Compute the later Cycle-816 occupied-set extension independently."""

    left = min(positions)
    right = max(positions)
    clockwise = (right - left) % RING_STATIONS
    anticlockwise = (left - right) % RING_STATIONS
    separation = min(clockwise, anticlockwise)
    short_sign = 1 if clockwise < anticlockwise else -1
    direction_sign = 1 if direction == (1, 0) else -1
    position_sum = sum(positions)
    source, bank, link, bank0, bank1, kind_mask, index_sum = (
        support_counts(support)
    )
    support_id: int | str = pair_support_ids.get(
        support, "NEW_SUPPORT_" + digest(support)
    )

    values: list[Any] = [
        event,
        event & 1,
        direction_sign,
        left,
        right,
        clockwise,
        anticlockwise,
        separation,
        max(clockwise, anticlockwise),
        short_sign,
        direction_sign * short_sign,
        position_sum,
        prod(positions),
        sum(1 << position for position in positions),
        pow(len(positions), -1, RING_STATIONS)
        * position_sum % RING_STATIONS,
        left if short_sign == 1 else right,
        right if short_sign == 1 else left,
        left & 1,
        right & 1,
        2 * (left & 1) + (right & 1),
        int(len({position & 1 for position in positions}) == 1),
        (event + position_sum) & 1,
        len(support),
        len(support),
        support_id,
        kind_mask,
        source,
        bank,
        link,
        bank0,
        bank1,
        bank1 - bank0,
        index_sum,
    ]
    for modulus in LANDED_CONSTANTS:
        values.extend(
            (
                left % modulus,
                right % modulus,
                position_sum % modulus,
                clockwise % modulus,
                separation % modulus,
                event % modulus,
            )
        )
    values.extend(
        int(len({position % modulus for position in positions}) == 1)
        for modulus in LANDED_CONSTANTS
    )
    if len(values) != len(FEATURE_NAMES):
        raise AssertionError(("feature width", len(values)))
    return tuple(values)


def build_feature_data() -> dict[str, object]:
    program = K.interleaved_program(FIXTURE_BANKS)
    fixtures = allocator_fixtures()
    pair_supports: dict[PairKey, Support] = {}
    for event, _direction, before in fixtures:
        for positions in separated_pairs():
            after, rail_a, rail_b, _trace = K.run_orbit(
                before, program, token_positions=positions
            )
            expected_rail = tuple(
                int(station in positions)
                for station in range(RING_STATIONS)
            )
            if rail_a != expected_rail or any(rail_b):
                raise AssertionError(("pair rail", event, positions))
            pair_supports[(event, positions)] = residual_support(after)

    pair_support_ids = {
        support: index
        for index, support in enumerate(sorted(set(pair_supports.values())))
    }
    fixture_map = {
        event: (direction, before)
        for event, direction, before in fixtures
    }
    pair_vectors: dict[PairKey, tuple[Any, ...]] = {}
    pair_rows = []
    for key in sorted(pair_supports):
        event, positions = key
        vector = occupied_set_feature_vector(
            event,
            positions,
            fixture_map[event][0],
            pair_supports[key],
            pair_support_ids,
        )
        pair_vectors[key] = vector
        pair_rows.append((event, positions[0], positions[1], *vector))

    higher_vectors: dict[HigherKey, tuple[Any, ...]] = {}
    higher_initial_states: dict[HigherKey, tuple[int, ...]] = {}
    for key in RESOLVED_KEYS:
        k, positions, event = key
        direction, before = fixture_map[event]
        after, rail_a, rail_b, _trace = K.run_orbit(
            before, program, token_positions=positions
        )
        expected_rail = tuple(
            int(station in positions)
            for station in range(RING_STATIONS)
        )
        if len(positions) != k or rail_a != expected_rail or any(rail_b):
            raise AssertionError(("higher rail", key))
        higher_vectors[key] = occupied_set_feature_vector(
            event,
            positions,
            direction,
            residual_support(after),
            pair_support_ids,
        )
        higher_initial_states[key] = after

    return {
        "program": program,
        "fixtures": fixtures,
        "pair_vectors": pair_vectors,
        "pair_rows": tuple(pair_rows),
        "pair_support_ids": pair_support_ids,
        "higher_vectors": higher_vectors,
        "higher_initial_states": higher_initial_states,
    }


def select(vector: tuple[Any, ...], names: tuple[str, ...]) -> tuple[Any, ...]:
    return tuple(vector[FEATURE_INDEX[name]] for name in names)


def implication(
    value: tuple[Any, ...],
    transient_values: frozenset[tuple[Any, ...]],
    cycle_values: frozenset[tuple[Any, ...]],
) -> str:
    if value in transient_values and value not in cycle_values:
        return "TRANSIENT"
    if value in cycle_values and value not in transient_values:
        return "CYCLE"
    return "UNSEEN"


def independent_separator_analysis(
    feature_data: dict[str, object],
) -> dict[str, object]:
    pair_vectors = feature_data["pair_vectors"]
    higher_vectors = feature_data["higher_vectors"]
    transient_keys = tuple(sorted(EXPECTED_TRANSIENT_KEYS))
    cycle_keys = tuple(sorted(EXPECTED_CYCLE_KEYS))
    old_open_keys = tuple(
        sorted(
            set(pair_vectors)
            - set(transient_keys)
            - set(cycle_keys)
        )
    )
    candidates = (
        tuple((name,) for name in FEATURE_NAMES)
        + tuple(combinations(PAIR_FEATURES, 2))
    )
    hypotheses = []
    for names in candidates:
        transient_values = frozenset(
            select(pair_vectors[key], names) for key in transient_keys
        )
        cycle_values = frozenset(
            select(pair_vectors[key], names) for key in cycle_keys
        )
        if not transient_values.isdisjoint(cycle_values):
            continue
        old_forecast = tuple(
            implication(
                select(pair_vectors[key], names),
                transient_values,
                cycle_values,
            )
            for key in old_open_keys
        )
        margin = min(
            sum(abs(left - right) for left, right in zip(tvalue, cvalue))
            for tvalue in transient_values
            for cvalue in cycle_values
        )
        hypotheses.append(
            {
                "names": names,
                "transient_values": transient_values,
                "cycle_values": cycle_values,
                "old_forecast": old_forecast,
                "old_classified":
                    sum(label != "UNSEEN" for label in old_forecast),
                "margin": margin,
            }
        )
    hypotheses.sort(
        key=lambda row: (
            -row["old_classified"],
            len(row["names"]),
            -row["margin"],
            row["names"],
        )
    )

    rows = []
    census_lists = {
        "correct_on_both": [],
        "correct_on_one": [],
        "wrong_on_both": [],
    }
    for hypothesis_id, hypothesis in enumerate(hypotheses, start=1):
        key_tests = []
        correct = 0
        for key in RESOLVED_KEYS:
            value = select(higher_vectors[key], hypothesis["names"])
            side = implication(
                value,
                hypothesis["transient_values"],
                hypothesis["cycle_values"],
            )
            is_correct = side == "CYCLE"
            correct += int(is_correct)
            key_tests.append(
                {
                    "key": key,
                    "separator_value": value,
                    "forecast_side": side,
                    "resolved_side": "CYCLE",
                    "test_result": "CORRECT" if is_correct else "WRONG",
                }
            )
        census_name = {
            2: "correct_on_both",
            1: "correct_on_one",
            0: "wrong_on_both",
        }[correct]
        census_lists[census_name].append(hypothesis["names"])
        rows.append(
            {
                "hypothesis_id": hypothesis_id,
                "features": hypothesis["names"],
                "key_tests": tuple(key_tests),
                "census_bin": census_name,
                "killed_as_universal_separator": correct < 2,
            }
        )

    correct_one_rows = tuple(
        {
            "hypothesis_id": row["hypothesis_id"],
            "features": row["features"],
            "correct_key": next(
                test["key"]
                for test in row["key_tests"]
                if test["test_result"] == "CORRECT"
            ),
            "forecast_sides": tuple(
                test["forecast_side"] for test in row["key_tests"]
            ),
            "separator_values": tuple(
                test["separator_value"] for test in row["key_tests"]
            ),
        }
        for row in rows
        if row["census_bin"] == "correct_on_one"
    )
    counts = {
        name: len(values) for name, values in census_lists.items()
    }
    return {
        "candidate_count": len(candidates),
        "old_open_keys": old_open_keys,
        "hypotheses": tuple(hypotheses),
        "rows": tuple(rows),
        "rows_sha256": digest(rows),
        "clean_names_sha256":
            digest(tuple(row["names"] for row in hypotheses)),
        "old_forecast_vector_count":
            len({row["old_forecast"] for row in hypotheses}),
        "counts": counts,
        "lists": {
            name: tuple(values) for name, values in census_lists.items()
        },
        "correct_one_rows": correct_one_rows,
    }


def synchronous_configuration_word(
    program: tuple[object, ...],
    occupied: tuple[int, ...],
) -> tuple[object, ...]:
    """Direct scheduler composition, separate from Cycle 814's implementation."""

    current = frozenset(occupied)
    word = []
    for _tick in range(len(program)):
        for station, macro in enumerate(program):
            if station in current:
                word.extend(K.mapped_macro(macro))
        current = frozenset(
            (station + 1) % len(program) for station in current
        )
    return tuple(word)


def clean_postimage(state: tuple[int, ...]) -> bool:
    return not residual_support(state)


def verify_two_cycles(feature_data: dict[str, object]) -> tuple[
    dict[str, object], ...
]:
    program = feature_data["program"]
    initial_states = feature_data["higher_initial_states"]
    rows = []
    for key in RESOLVED_KEYS:
        _k, positions, _event = key
        word = synchronous_configuration_word(program, positions)
        initial = initial_states[key]
        state = initial
        clean_moments = []
        earlier_returns = []
        trajectory_hasher = sha256()
        for moment in range(RESOLVED_PERIOD):
            trajectory_hasher.update(
                str(sum(bit << index for index, bit in enumerate(state)))
                .encode("ascii")
            )
            trajectory_hasher.update(b"\n")
            if clean_postimage(state):
                clean_moments.append(moment)
            if moment and state == initial:
                earlier_returns.append(moment)
            state = K.A.apply_semantic(state, word)
        rows.append(
            {
                "key": key,
                "period": RESOLVED_PERIOD,
                "all_phases_nonclean": not clean_moments,
                "clean_moments": tuple(clean_moments),
                "no_earlier_return_to_T0": not earlier_returns,
                "earlier_return_moments": tuple(earlier_returns),
                "exact_full_state_return_to_T0": state == initial,
                "initial_state_sha256": sha256(
                    str(
                        sum(
                            bit << index
                            for index, bit in enumerate(initial)
                        )
                    ).encode("ascii")
                ).hexdigest(),
                "trajectory_sha256": trajectory_hasher.hexdigest(),
                "permanent_cycle_certified": (
                    not clean_moments
                    and not earlier_returns
                    and state == initial
                ),
            }
        )
    return tuple(rows)


def returned_dict_constant(
    function: ast.FunctionDef,
    key: str,
) -> object:
    returns = [
        node for node in function.body
        if isinstance(node, ast.Return) and isinstance(node.value, ast.Dict)
    ]
    if len(returns) != 1:
        raise AssertionError(("dict return", function.name, len(returns)))
    mapping = {
        ast.literal_eval(key_node): value_node
        for key_node, value_node in zip(
            returns[0].value.keys, returns[0].value.values
        )
        if key_node is not None
    }
    return ast.literal_eval(mapping[key])


def pair_key_annotation(tree: ast.Module) -> str | None:
    rows = [
        node.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "Key"
            for target in node.targets
        )
    ]
    return ast.unparse(rows[0]) if len(rows) == 1 else None


def pair_unpack_present(function: ast.FunctionDef) -> bool:
    for node in ast.walk(function):
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if (
            isinstance(target, ast.Tuple)
            and len(target.elts) == 2
            and isinstance(target.elts[0], ast.Name)
            and target.elts[0].id == "epoch"
            and isinstance(target.elts[1], ast.Tuple)
            and tuple(
                item.id if isinstance(item, ast.Name) else None
                for item in target.elts[1].elts
            ) == ("left", "right")
            and isinstance(node.value, ast.Name)
            and node.value.id == "key"
        ):
            return True
    return False


