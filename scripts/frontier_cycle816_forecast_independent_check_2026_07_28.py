def compact(value: object) -> str:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), default=str
    )


def digest(value: object) -> str:
    return sha256(compact(value).encode("utf-8")).hexdigest()


def git_blob_sha(payload: bytes) -> str:
    return sha1(f"blob {len(payload)}\0".encode("ascii") + payload).hexdigest()


def named_function(tree: ast.Module, name: str) -> ast.FunctionDef:
    rows = [
        node for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name == name
    ]
    if len(rows) != 1:
        raise AssertionError(("function", name, len(rows)))
    return rows[0]


def literal_assignment(tree: ast.Module, name: str) -> object:
    rows = [
        node.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == name
            for target in node.targets
        )
    ]
    if len(rows) != 1:
        raise AssertionError(("literal assignment", name, len(rows)))
    return ast.literal_eval(rows[0])


def literal_return(function: ast.FunctionDef) -> object:
    returns = [
        node.value for node in function.body
        if isinstance(node, ast.Return)
    ]
    if len(returns) != 1:
        raise AssertionError(("literal return", function.name, len(returns)))
    return ast.literal_eval(returns[0])


