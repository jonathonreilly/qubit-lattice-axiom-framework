def block_signed_perm_group(blocks):
    """Signed-permutation group with a BLOCK structure: within each block axes
    permute + sign-flip freely; NO permutation across blocks (axes in different
    blocks may still sign-flip independently).  `blocks` is a list of axis-index
    lists partitioning range(n).
      - spatial O_h on 3 axes:      blocks=[[0,1,2]]            -> order 48
      - O_h x time-parity (Z^3xZt): blocks=[[0],[1,2,3]]        -> order 2*48=96
      - 4D hypercubic B_4:          blocks=[[0,1,2,3]]          -> order 384
    """
    import itertools as it
    n = sum(len(b) for b in blocks)
    per_block = []
    for b in blocks:
        m = len(b)
        mats_b = []
        for perm in it.permutations(range(m)):
            for signs in it.product([1, -1], repeat=m):
                M = np.zeros((m, m))
                for i, pi in enumerate(perm):
                    M[i, pi] = signs[i]
                mats_b.append((b, M))
        per_block.append(mats_b)
    group = []
    for combo in it.product(*per_block):
        full = np.zeros((n, n))
        for axes, M in combo:
            for i, ai in enumerate(axes):
                for j, aj in enumerate(axes):
                    full[ai, aj] = M[i, j]
        group.append(full)
    return group


def invariant_diag_dim(group):
    """Dimension of the space of diagonal quadratic forms diag(c_0..c_{n-1})
    invariant under the group (each g maps diag-form to diag-form here since the
    group is signed-permutation).  The invariant diagonals = orbits of axes under
    the permutation part; dim = number of axis-orbits."""
    n = group[0].shape[0]
    # axis-permutation orbits: union-find on axes connected by any group element's
    # permutation action
    parent = list(range(n))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    def union(a, b):
        parent[find(a)] = find(b)

    for M in group:
        perm = [int(np.argmax(np.abs(M[i]))) for i in range(n)]
        for i in range(n):
            union(i, perm[i])
    return len({find(i) for i in range(n)})


