"""
Finite D,U joint-algebra rank-one-selector no-go (Koide delta support route).

Theorem attempt:
  Test whether the unital *-algebra A_DU generated by the finite L=3
  Wilson-Dirac operator D and the spin lift U of the body-diagonal 120-degree
  lattice rotation contains a rank-one selector on their common zeta
  zero-mode sector.

Result:
  Negative for A_DU only.  At frozen L=3 and r=1.0, the relevant zero-mode
  spin-lift eigenspace has rank two.  The generator restrictions are
  D|M_zeta = 0 and U|M_zeta = zeta I_2, so every element of A_DU restricts to
  a scalar and none is a rank-one projector on M_zeta.

  This is not a no-go for the full Wilson/Clifford construction.  The displayed
  Clifford volume element Gamma=-i gamma_1 gamma_2 gamma_3 commutes with D and
  U and splits M_zeta.  The runner also makes no ambient eta-proxy or
  endpoint-lift claim.

No mass data, fitted Koide value, or selected endpoint target is used.
"""

