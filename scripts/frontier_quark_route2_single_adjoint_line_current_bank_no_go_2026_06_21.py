def check(name: str, cond: bool, detail: str = "") -> bool:
    global PASS, FAIL
    print(f"[{'PASS' if cond else 'FAIL'}] {name}")
    if detail:
        print(f"       {detail}")
    PASS += int(bool(cond))
    FAIL += int(not cond)
    return bool(cond)


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def perm_sign(p: tuple[int, int, int]) -> int:
    inversions = 0
    for i in range(3):
        for j in range(i + 1, 3):
            if p[i] > p[j]:
                inversions += 1
    return -1 if inversions % 2 else 1


def su3_structure_constants() -> dict[tuple[int, int, int], sp.Expr]:
    sqrt3 = sp.sqrt(3)
    base = {
        (1, 2, 3): sp.Integer(1),
        (1, 4, 7): sp.Rational(1, 2),
        (1, 5, 6): -sp.Rational(1, 2),
        (2, 4, 6): sp.Rational(1, 2),
        (2, 5, 7): sp.Rational(1, 2),
        (3, 4, 5): sp.Rational(1, 2),
        (3, 6, 7): -sp.Rational(1, 2),
        (4, 5, 8): sqrt3 / 2,
        (6, 7, 8): sqrt3 / 2,
    }
    out: dict[tuple[int, int, int], sp.Expr] = {}
    for key, value in base.items():
        for p in permutations(key):
            out[p] = perm_sign(p) * value
    return out


def adjoint_matrices() -> list[sp.Matrix]:
    f = su3_structure_constants()
    mats: list[sp.Matrix] = []
    for a in range(1, 9):
        mat = sp.zeros(8, 8)
        for b in range(1, 9):
            for c in range(1, 9):
                mat[b - 1, c - 1] = f.get((a, c, b), sp.Integer(0))
        mats.append(mat)
    return mats


