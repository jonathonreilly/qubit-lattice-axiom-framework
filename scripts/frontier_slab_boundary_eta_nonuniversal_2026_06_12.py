def wilson_block(k: float, height: int, r_value: float, m0: float, periodic: bool) -> np.ndarray:
    """Return the 2 height x 2 height Wilson-mass block at one ring momentum."""
    mass = -float(m0)
    H = np.zeros((2 * height, 2 * height), dtype=complex)
    onsite = np.sin(k) * S1 + (mass + r_value * (1.0 - np.cos(k)) + r_value) * S3
    hop = (-0.5j) * S2 - (0.5 * r_value) * S3
    for y in range(height):
        sl = slice(2 * y, 2 * y + 2)
        H[sl, sl] += onsite
        if y + 1 < height:
            sr = slice(2 * (y + 1), 2 * (y + 1) + 2)
            H[sl, sr] += hop
            H[sr, sl] += hop.conj().T
    if periodic and height > 1:
        left = slice(2 * (height - 1), 2 * height)
        right = slice(0, 2)
        H[left, right] += hop
        H[right, left] += hop.conj().T
    return H


def smooth_sum(vals: np.ndarray, eps: float) -> float:
    return float(np.tanh(vals / eps).sum())


def boundary_total(k: float, height: int, r_value: float, m0: float, eps: float, bc_label: str) -> float:
    if bc_label not in BC_LABELS:
        raise ValueError(f"unknown boundary label {bc_label!r}")
    open_vals = np.linalg.eigvalsh(wilson_block(k, height, r_value, m0, periodic=False))
    per_vals = np.linalg.eigvalsh(wilson_block(k, height, r_value, m0, periodic=True))
    return smooth_sum(open_vals, eps) - smooth_sum(per_vals, eps)


def total_quantities(height: int, r_value: float, m0: float, eps: float, bc_label: str) -> dict[str, float]:
    e0 = boundary_total(MOMENTA["0"], height, r_value, m0, eps, bc_label)
    ew = boundary_total(MOMENTA["omega"], height, r_value, m0, eps, bc_label)
    ew2 = boundary_total(MOMENTA["omega2"], height, r_value, m0, eps, bc_label)
    return {
        "eta_0": e0,
        "eta_omega": ew,
        "eta_omega2": ew2,
        "A2": 0.5 * (ew + ew2) - e0,
        "S": e0 + ew + ew2,
        "D": ew - ew2,
    }


def edge_eta(k: float, height: int, r_value: float, m0: float, eps: float) -> tuple[float, float]:
    H_open = wilson_block(k, height, r_value, m0, periodic=False)
    vals, vecs = np.linalg.eigh(H_open)
    H_per = wilson_block(k, height, r_value, m0, periodic=True)
    per_vals = np.linalg.eigvalsh(H_per)
    signs = np.tanh(vals / eps)
    bottom_weights = (np.abs(vecs[:height, :]) ** 2).sum(axis=0)
    bottom = float(np.dot(signs, bottom_weights) - 0.5 * smooth_sum(per_vals, eps))
    total = smooth_sum(vals, eps) - smooth_sum(per_vals, eps)
    top = float(total - bottom)
    return bottom, top


def signed_edge_count(k: float, height: int, r_value: float, m0: float) -> tuple[int, int]:
    H = wilson_block(k, height, r_value, m0, periodic=False)
    vals, vecs = np.linalg.eigh(H)
    span = max(4, height // 8)
    bottom_weights = (np.abs(vecs[: 2 * span, :]) ** 2).sum(axis=0)
    top_weights = (np.abs(vecs[-2 * span :, :]) ** 2).sum(axis=0)
    bottom = 0
    top = 0
    for val, wb, wt in zip(vals, bottom_weights, top_weights):
        if abs(val) < GAP_WINDOW and wb > 0.5:
            bottom += 1 if val > 0.0 else -1
        if abs(val) < GAP_WINDOW and wt > 0.5:
            top += 1 if val > 0.0 else -1
    return bottom, top


def max_total_abs(height: int, eps: float) -> float:
    max_abs = 0.0
    for r_value, m0 in PARAM_GRID:
        for bc_label in BC_LABELS:
            q = total_quantities(height, r_value, m0, eps, bc_label)
            max_abs = max(max_abs, max(abs(v) for v in q.values()))
    return max_abs


def max_eps_tail(height: int) -> float:
    max_abs = 0.0
    for r_value, m0 in PARAM_GRID:
        for bc_label in BC_LABELS:
            q_hi = total_quantities(height, r_value, m0, 0.05, bc_label)
            q_lo = total_quantities(height, r_value, m0, 0.02, bc_label)
            for key in q_hi:
                max_abs = max(max_abs, abs(q_lo[key] - q_hi[key]))
    return max_abs


def max_height_tail(eps: float) -> float:
    max_abs = 0.0
    for r_value, m0 in PARAM_GRID:
        for bc_label in BC_LABELS:
            q64 = total_quantities(64, r_value, m0, eps, bc_label)
            q128 = total_quantities(128, r_value, m0, eps, bc_label)
            for key in q64:
                max_abs = max(max_abs, abs(q128[key] - q64[key]))
    return max_abs


def run_s1_anchor() -> None:
    section("S1 anchor: in-gap signed mode count")
    bw, tw = signed_edge_count(MOMENTA["omega"], 64, 0.5, 1.5)
    bw2, tw2 = signed_edge_count(MOMENTA["omega2"], 64, 0.5, 1.5)
    d_bottom = bw - bw2
    d_top = tw - tw2
    print(f"  recovered bottom counts: omega={bw:+d}, omega2={bw2:+d}, D={d_bottom:+d}")
    print(f"  recovered top counts:    omega={tw:+d}, omega2={tw2:+d}, D={d_top:+d}")
    check("S1", "bottom edge D = +2", d_bottom == 2)
    check("S1", "top edge D = -2", d_top == -2)


def run_s2_global() -> None:
    section("S2 global zero, eps stability, and L convergence")
    raw_max = max_total_abs(128, 0.05)
    check("S2", "all total quantities vanish at L_h=128, eps=0.05", raw_max < TOL_ZERO, f"max abs = {raw_max:.3e}")
    eps_tail = max_eps_tail(128)
    check("S2", "eps tail |eps0.02 - eps0.05| is zero for totals", eps_tail < TOL_ZERO, f"max tail = {eps_tail:.3e}")
    height_tail = max_height_tail(0.05)
    check("S2", "L tail |L128 - L64| is zero for totals", height_tail < TOL_ZERO, f"max tail = {height_tail:.3e}")
    grid_max = 0.0
    for height in HEIGHT_GRID:
        for eps in EPS_GRID:
            grid_max = max(grid_max, max_total_abs(height, eps))
    check("S2", "full eps/L/parameter grid is globally zero on the open-uniform slab", grid_max < TOL_ZERO, f"grid max = {grid_max:.3e}")
    # Scope narrowing (2026-06-20): the runner only computes the open-uniform
    # slab. The 'sharp domain wall' label is computationally inert -- it builds
    # no distinct mass profile and reproduces the open-uniform totals exactly.
    # This check verifies that inertness, so the note's "sharp-domain-wall not
    # computed" claim is runner-verified rather than asserted.
    label_diff = 0.0
    for height in HEIGHT_GRID:
        for eps in EPS_GRID:
            for r_value, m0 in PARAM_GRID:
                q_open = total_quantities(height, r_value, m0, eps, "open uniform")
                q_wall = total_quantities(height, r_value, m0, eps, "sharp domain wall")
                for key in q_open:
                    label_diff = max(label_diff, abs(q_open[key] - q_wall[key]))
    check(
        "S2",
        "the 'sharp domain wall' label is computationally inert (reproduces the open-uniform slab); the sharp-domain-wall boundary condition is NOT computed",
        label_diff == 0.0,
        f"max label diff = {label_diff:.3e}",
    )


def run_s3_per_edge() -> None:
    section("S3 per-edge nonzero, parameter-dependent, and non-2/9")
    references = {
        (0.5, 0.5): 0.1223,
        (0.5, 1.5): 0.2007,
        (1.0, 0.5): 0.0499,
    }
    observed: dict[tuple[float, float], float] = {}
    for point, expected in references.items():
        r_value, m0 = point
        bottom, top = edge_eta(MOMENTA["omega"], EDGE_HEIGHT, r_value, m0, EDGE_EPS)
        observed[point] = bottom
        check(
            "S3",
            f"per-edge eta_omega(bottom) at (r,m0)={point} matches verified value",
            abs(bottom - expected) < 1.0e-3,
            f"got {bottom:.4f}, expected {expected:.4f}, top {top:.4f}",
        )
    min_abs = min(abs(v) for v in observed.values())
    check("S3", "all three per-edge values are genuinely nonzero", min_abs > 1.0e-2, f"min |value| = {min_abs:.4f}")
    pair_gap = min(abs(a - b) for i, a in enumerate(observed.values()) for b in list(observed.values())[i + 1 :])
    check("S3", "the three per-edge values are pairwise distinct", pair_gap > 1.0e-2, f"minimum gap = {pair_gap:.4f}")
    two_ninths = 2.0 / 9.0
    distances = {point: abs(value - two_ninths) for point, value in observed.items()}
    best_point = min(distances, key=distances.get)
    best_dist = distances[best_point]
    dist_text = ", ".join(f"{point}:{dist:.4f}" for point, dist in distances.items())
    check("S3", "no per-edge value is within 0.01 of 2/9", min(distances.values()) > 0.01, dist_text)
    check(
        "S3",
        "closest tested point is the 0.2007 value, distance about 0.0215",
        best_point == (0.5, 1.5) and abs(best_dist - abs(0.2007 - two_ninths)) < 1.0e-3,
        f"best point = {best_point}, distance = {best_dist:.4f}",
    )


