def run_s5_control() -> None:
    section("S5 trivial control and structural source hygiene")
    vals = []
    for height in (32, 64, 128):
        bottom, top = edge_eta(MOMENTA["omega"], height, 0.0, 4.0, EDGE_EPS)
        totals = total_quantities(height, 0.0, 4.0, EDGE_EPS, "open uniform")
        vals.append((height, abs(bottom), abs(top), max(abs(v) for v in totals.values())))
    detail = "; ".join(f"L={height}: edge=({b:.2e},{t:.2e}), total={q:.2e}" for height, b, t, q in vals)
    check("S5", "r=0, m0=4 trivial control has no per-edge or total remainder", max(max(row[1:]) for row in vals) < TOL_ZERO, detail)
    source = Path(__file__).read_text(encoding="utf-8")
    tree = ast.parse(source)
    token = "de" + "lta"
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            names.add(node.id)
        elif isinstance(node, ast.arg):
            names.add(node.arg)
        elif isinstance(node, ast.Attribute):
            names.add(node.attr)
        elif isinstance(node, ast.FunctionDef):
            names.add(node.name)
    offenders = sorted(name for name in names if token in name.lower())
    check("S5", "no-" + token + " structural check: no such Python variable or symbol", not offenders, f"offenders = {offenders}")


