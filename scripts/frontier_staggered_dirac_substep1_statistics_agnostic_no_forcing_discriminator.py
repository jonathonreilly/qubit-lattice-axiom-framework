            "  (B) A Jordan-Wigner string turns them into cross-site CAR (fermions),\n"
            "  (C) but the qubit-ladder algebra and the JW-fermion algebra are the\n"
            "      SAME full matrix algebra M_{2^N}; JW is an invertible change of\n"
            "      generators, so the checked ungraded algebra/dimension data leave\n"
            "      'fermion' vs 'qubit' as a FRAME choice, not forced.\n"
            "  (D) Per-site dim 2 holds for fermion AND hard-core boson alike; the\n"
            "      retained dim-2 readout only excludes the FREE boson (dim inf).\n"
