#!/usr/bin/env python3
"""Bounded forcing test: does nearest-neighbor Admissibility force dn = 0?

This runner deliberately tests one finite modeling premise, not the physical
4D gauge surface: the parent T^4_2 cubical complex, branch datum n as an
integer 2-cochain on plaquettes, and defect dn as the integer 3-cochain on
cubes. The candidate Admissibility reading encoded here is:

  plaquette branch values are singleton local possibilities, determined by
  nearest-neighbor supplied-cell conditions through one fixed local rule.

The concrete exhaustive test uses binary vertex conditions c(x) on T^4_2 and
the translation-covariant anchored rule n(x; mu, nu) = c(x). All 2^16
condition fields, hence all branch assignments generated by this finite rule,
are enumerated exactly.
"""
from __future__ import annotations

from itertools import combinations, product
from pathlib import Path
import sys


D = 4
L = 2

AXIOM_PATH = Path("docs/MINIMAL_AXIOMS_2026-06-29.md")
PARENT_NOTE_PATH = Path(
    "docs/THETA_4D_CARRIER_FLUX_COHOMOLOGY_INTERSECTION_PAIRING_CLOSED_BRANCH_"
    "AND_DEFECT_CLOSURE_RESIDUAL_BOUNDED_THEOREM_NOTE_2026-07-02.md"
)
PARENT_RUNNER_PATH = Path(
    "scripts/theta_4d_carrier_flux_cohomology_intersection_pairing_2026_07_02.py"
)

ADMISSIBILITY_QUOTE = (
    "For each site, the available possibilities are determined by, and vary with,\n"
    "the nearest-neighbor conditions."
)
THEOREM_4_1_NO_DECOMP_QUOTE = (
    "no class function exists and\n"
    "   no sector decomposition survives on the unrestricted branch sum"
)
N6_OPEN_QUESTION_QUOTE = (
    "whether the framework's Admissibility rule bears on it is an\n"
    "open forward question, not asserted here"
)
PARENT_BRANCH_GRADING_QUOTE = "n_open = np.zeros(len(CI[2][0]), dtype=np.int64)"
PARENT_DEFECT_GRADING_QUOTE = "DM[2] @ n_open"


PASS = 0
FAIL = 0
CHECK_INDEX = 0


def check(label: str, condition: bool, detail: str = "") -> None:
    global PASS, FAIL, CHECK_INDEX
    CHECK_INDEX += 1
    if condition:
        PASS += 1
        status = "PASS"
    else:
        FAIL += 1
        status = "FAIL"
    print(f"CHECK {CHECK_INDEX:02d}: {status} - {label}")
    if detail:
        print(f"  {detail}")


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def sites() -> list[tuple[int, int, int, int]]:
    return [tuple(x) for x in product(range(L), repeat=D)]


SITES = sites()
SITE_INDEX = {x: i for i, x in enumerate(SITES)}


def cells(k: int) -> list[tuple[tuple[int, int, int, int], tuple[int, ...]]]:
    return [(x, S) for S in combinations(range(D), k) for x in SITES]


C1 = cells(1)
C2 = cells(2)
C3 = cells(3)
I1 = {c: i for i, c in enumerate(C1)}
I2 = {c: i for i, c in enumerate(C2)}
I3 = {c: i for i, c in enumerate(C3)}


def shift(x: tuple[int, int, int, int], mu: int) -> tuple[int, int, int, int]:
    y = list(x)
    y[mu] = (y[mu] + 1) % L
    return tuple(y)


def d1(lam: list[int]) -> list[int]:
    """Coboundary of a link 1-cochain, returned on plaquettes."""
    out = [0 for _ in C2]
    for (x, S), row in I2.items():
        total = 0
        for j, mu in enumerate(S):
            srem = tuple(m for m in S if m != mu)
            sign = 1 if j % 2 == 0 else -1
            total += sign * (lam[I1[(shift(x, mu), srem)]] - lam[I1[(x, srem)]])
        out[row] = total
    return out


def d2(n: list[int]) -> list[int]:
    """Coboundary of a plaquette 2-cochain, returned on cubes."""
    out = [0 for _ in C3]
    for (x, S), row in I3.items():
        total = 0
        for j, mu in enumerate(S):
            srem = tuple(m for m in S if m != mu)
            sign = 1 if j % 2 == 0 else -1
            total += sign * (n[I2[(shift(x, mu), srem)]] - n[I2[(x, srem)]])
        out[row] = total
    return out


def branch_from_vertex_conditions(mask: int) -> list[int]:
    """Encoding E1: n(x; mu, nu) is the condition bit at the anchor vertex x."""
    out = [0 for _ in C2]
    for (x, _S), row in I2.items():
        out[row] = (mask >> SITE_INDEX[x]) & 1
    return out


def nonzero_entries(values: list[int], domain: list[tuple], limit: int = 8) -> list[str]:
    found = []
    for value, cell in zip(values, domain):
        if value:
            found.append(f"{cell}:{value}")
            if len(found) == limit:
                break
    return found


def qraw(n: list[int]) -> int:
    """Minimal cup-square sum for 2-cochains, matching the parent cup rule."""
    total = 0
    for x, S in cells(4):
        cell_total = 0
        for S1 in combinations(S, 2):
            S2 = tuple(m for m in S if m not in S1)
            perm = list(S1) + list(S2)
            inv = sum(
                1
                for i in range(len(perm))
                for j in range(i + 1, len(perm))
                if perm[i] > perm[j]
            )
            y = x
            for mu in S1:
                y = shift(y, mu)
            cell_total += (1 if inv % 2 == 0 else -1) * n[I2[(x, S1)]] * n[I2[(y, S2)]]
        total += cell_total
    return total


def main() -> int:
    axiom_text = read_text(AXIOM_PATH)
    parent_note_text = read_text(PARENT_NOTE_PATH)
    parent_runner_text = read_text(PARENT_RUNNER_PATH)

    check("Admissibility quote guard", ADMISSIBILITY_QUOTE in axiom_text)
    check(
        "parent Theorem 4.1 no-decomposition quote guard",
        THEOREM_4_1_NO_DECOMP_QUOTE in parent_note_text,
    )
    check("parent N6 open-question quote guard", N6_OPEN_QUESTION_QUOTE in parent_note_text)
    check(
        "parent runner branch grading guard: branch n is a plaquette 2-cochain",
        PARENT_BRANCH_GRADING_QUOTE in parent_runner_text,
    )
    check(
        "parent runner defect grading guard: defect is dn on cubes",
        PARENT_DEFECT_GRADING_QUOTE in parent_runner_text,
    )

    check("T^4_2 cell counts match parent grading", len(SITES) == 16 and len(C2) == 96 and len(C3) == 64)

    dd_zero = True
    for link_index in range(len(C1)):
        lam = [0 for _ in C1]
        lam[link_index] = 1
        if any(d2(d1(lam))):
            dd_zero = False
            break
    check("cubical coboundary sanity: d2 d1 = 0 on every link basis cochain", dd_zero)

    total_masks = 1 << len(SITES)
    closed_count = 0
    open_count = 0
    first_open_mask = None
    first_open_dn: list[int] | None = None

    for mask in range(total_masks):
        n = branch_from_vertex_conditions(mask)
        dn = d2(n)
        if any(dn):
            open_count += 1
            if first_open_mask is None:
                first_open_mask = mask
                first_open_dn = dn
        else:
            closed_count += 1

    check(
        "Encoding E1 exhaustive enumeration completed",
        closed_count + open_count == total_masks,
        f"closed={closed_count} open={open_count} total={total_masks}",
    )
    check(
        "FORCING FAILS in E1: a neighbor-determined branch assignment has dn != 0",
        first_open_mask is not None and first_open_dn is not None,
        (
            f"witness_mask=0x{first_open_mask:04x}; "
            f"nonzero dn entries={nonzero_entries(first_open_dn or [], C3)}"
        ),
    )

    single_site_mask = 1 << SITE_INDEX[(0, 0, 0, 0)]
    single_site_n = branch_from_vertex_conditions(single_site_mask)
    single_site_dn = d2(single_site_n)
    check(
        "explicit witness: c(0,0,0,0)=1 and all other vertex conditions 0 gives dn != 0",
        any(single_site_dn),
        f"nonzero dn entries={nonzero_entries(single_site_dn, C3)}",
    )

    unrestricted = [0 for _ in C2]
    unrestricted[I2[((0, 0, 0, 0), (0, 1))]] = 1
    unrestricted_dn = d2(unrestricted)
    check(
        "negative control: without neighbor-determination, a single plaquette branch has dn != 0",
        any(unrestricted_dn),
        f"nonzero dn entries={nonzero_entries(unrestricted_dn, C3)}",
    )

    witness_qraw = qraw(single_site_n)
    check(
        "counterexample is still on the parent branch object; no theta value is inferred",
        isinstance(witness_qraw, int),
        f"witness Q_raw={witness_qraw}; used only as object sanity, not as theta charge",
    )

    print(f"TOTAL: PASS={PASS} FAIL={FAIL}")
    print(
        "FILES: docs/THETA_DEFECT_CLOSURE_FROM_ADMISSIBILITY_TEST_BOUNDED_NOTE_2026-07-03.md; "
        "scripts/frontier_theta_defect_closure_admissibility_2026_07_03.py"
    )
    print(f"CHECK COUNT: {PASS + FAIL}")
    if first_open_mask is None or first_open_dn is None:
        print("RESULT: FORCING HOLDS in Encoding E1")
    else:
        print(
            "RESULT: FORCING FAILS; witness="
            f"mask 0x{first_open_mask:04x}, dn {nonzero_entries(first_open_dn, C3, limit=3)}"
        )
    print(
        "ENCODING PREMISE: branch n is a plaquette singleton possibility, "
        "n(x;mu,nu)=c(x), determined by supplied nearest-neighbor vertex conditions"
    )
    print(
        "UNCERTAINTIES: this does not test the physical SU(3) surface, other admissibility "
        "encodings, F-pairing insertion, or relative-frame correlation"
    )

    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
