"""KCPT L = 6 ind8-separator reach census (surface comparison with the landed L = 4 census).

Self-contained (stdlib + numpy only). Ports the KCPT structure map to L = 6
(N = 216, 6^3 torus, staggered lattice) and measures, over every H-conjugation
orbit of the D2-commuting signed-permutation group G_amb, the reach observable

    omega(g) = || Pi_{C_g}(sep6) ||_F^2 / || sep6 ||_F^2 ,

where C_g = <D2, J_full, S_eps, U_g> is the complex-linear matrix *-algebra
generated by those real matrices and one census element U_g, Pi is Frobenius orthogonal
projection, and sep6 = P8a - P8b is the ind-8 separator (difference of the two
multiplicity-1 rank-8 isotypic projectors on the top staggered shell). The reach
into the full 9-dimensional separator complement of C[M] inside A' is recorded as
d(g); the shell-projector character difference Dchi(g) = Re(tr(P8a U_g) - tr(P8b U_g))
is recorded alongside.

The construction section (build_lattice, signed-permutation helpers, build_group,
A_nat, per-shell H-averaged commutant, isotypic blocks, A', sep6, the 9-direction
complement) mirrors the landed L = 6 surface-change lane. Everything is built from
scratch; no external data files are loaded. Runs single-threaded.

Gate contract: prints per-gate PASS lines and a final `TOTAL: PASS=N FAIL=0`,
exits 0 on success.
"""

