def q_le_candidates(maxq):
    vals = set()
    for q in range(1, maxq + 1):
        for p in range(0, q + 1):
            vals.add(Fraction(p, q))
    return sorted(vals)


def nearest_two(x, cands):
    ds = sorted(((abs(float(c) - x), c) for c in cands), key=lambda t: t[0])
    return ds[0], ds[1]


