def gate(name, cond, msg=""):
    ok = bool(cond)
    tag = "PASS" if ok else "FAIL"
    line = f"[GATE {name}] {tag}"
    if msg:
        line += f" -- {msg}"
    print(line, flush=True)
    if ok:
        _P[0] += 1
    else:
        _F[0] += 1
    return ok


