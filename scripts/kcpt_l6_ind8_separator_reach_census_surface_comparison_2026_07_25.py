def vec(A):
    return np.asarray(A, dtype=complex).reshape(-1)


def orth_add(B, A, tol=1e-9):
    v = vec(A)
    nv = np.linalg.norm(v)
    if nv < tol:
        return B, False
    v = v / nv
    for _ in range(2):
        if B.shape[0]:
            v = v - B.T @ (B.conj() @ v)
    r = np.linalg.norm(v)
    if r < tol:
        return B, False
    return np.vstack([B, v / r]), True


def word_algebra(gens, N, cap=400, tol=1e-9):
    gens = [np.asarray(g, dtype=complex) for g in gens]
    B = np.zeros((0, N * N), dtype=complex)
    B, _ = orth_add(B, np.eye(N))
    frontier = [np.eye(N, dtype=complex)]
    while frontier and B.shape[0] < cap:
        newf = []
        for w in frontier:
            for g in gens:
                p = g @ w
                B2, added = orth_add(B, p, tol)
                if added:
                    B = B2
                    newf.append(p)
        frontier = newf
    return B, len(frontier) == 0


def word_algebra_real(gens, N, cap, tol=1e-9):
    """Real-valued word basis for the complex-linear matrix *-algebra <I, gens>.

    All generators and words are real, so a real Frobenius-orthonormal basis of
    their real span is also a complex basis of the complex-linear span. Returns
    (B, dim, closed): B is (dim, N*N) float64 rows, dim is the complex
    dimension, and closed is True iff the frontier emptied below cap. Stored as
    one growing (cap, N*N) array; one such array is live at a time.
    """
    gens = [np.asarray(g, dtype=np.float64) for g in gens]
    NN = N * N
    B = np.empty((cap, NN), dtype=np.float64)
    v = np.eye(N).reshape(-1).astype(np.float64)
    v /= np.linalg.norm(v)
    B[0] = v
    cnt = 1
    frontier = [np.eye(N, dtype=np.float64)]
    while frontier and cnt < cap:
        newf = []
        for w in frontier:
            for g in gens:
                p = g @ w
                v = p.reshape(-1).copy()
                nv = np.linalg.norm(v)
                if nv < tol:
                    continue
                v /= nv
                for _ in range(2):
                    if cnt:
                        v = v - B[:cnt].T @ (B[:cnt] @ v)
                r = np.linalg.norm(v)
                if r < tol:
                    continue
                B[cnt] = v / r
                cnt += 1
                newf.append(p)
                if cnt >= cap:
                    break
            if cnt >= cap:
                break
        frontier = newf
    closed = (len(frontier) == 0)
    return B[:cnt], cnt, closed


def overlap2(B, X):
    if B.shape[0] == 0:
        return 0.0
    v = vec(X)
    v = v / np.linalg.norm(v)
    return float(np.linalg.norm(B.conj() @ v) ** 2)


def center_of(Blist, gens, tol=1e-10):
    d = len(Blist)
    Gm = np.zeros((d, d), dtype=complex)
    for gg in gens:
        gg = np.asarray(gg, dtype=complex)
        Cg = np.stack([(gg @ Xk - Xk @ gg).ravel() for Xk in Blist], axis=1)
        Gm += Cg.conj().T @ Cg
    w, V = np.linalg.eigh(Gm)
    thr = tol * max(w[-1].real, 1e-30)
    nidx = np.where(w < thr)[0]
    Z = [sum(V[k, j] * Blist[k] for k in range(d)) for j in nidx]
    return Z, len(nidx)


