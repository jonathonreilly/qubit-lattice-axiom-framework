PASS = 0
FAIL = 0


def check(label, cond):
    """Record and print one exact check."""
    global PASS, FAIL
    ok = bool(cond)
    if ok:
        PASS += 1
    else:
        FAIL += 1
    print(("PASS " if ok else "FAIL ") + label)


