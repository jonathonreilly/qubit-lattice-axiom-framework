#!/usr/bin/env python3
"""Matter graded composition: the axiom-update boundary, checked exactly.

Class-A finite-dimensional runner for the composition gap: the same one-site
datum M_2(C) admits two inequivalent cross-site compositions, and nothing in
the one-site data selects between them.

Declared objects (all exact; sympy only, no floats, no sampling):

  * Pauli matrices s1, s2, s3, the unit one = eye(2), and the matrix units
    E00, E01 = |0><1|, E10, E11 of M_2(C);
  * three sites 0, 1, 2 on a line, nearest-neighbour pairs (0,1) and (1,2),
    with (0,2) non-adjacent; kron = iterated Kronecker product on C^8;
  * iota(x, M): the ungraded site embedding (identity on the other factors);
  * a Jordan-Wigner family c_x for a chosen total order, with Z = s3, plus
    cd_x = c_x^dagger, n_x = cd_x c_x and total parity P = s3 (x) s3 (x) s3;
  * kappa(x, M): the graded site embedding, the unital *-homomorphism with
    E01 -> c_x, E10 -> cd_x, E11 -> cd_x c_x, E00 -> c_x cd_x;
  * the proper cubic rotation group generated by Rz and Rx with SU(2) lifts
    Uz = (1 - i s3)/sqrt(2), Ux = (1 - i s1)/sqrt(2);
  * the real 8-dimensional basis {1, i, s_k, i s_k} of M_2(C);
  * six Majoranas g_1..g_6 on C^8 built from three Jordan-Wigner modes, with
    g_1,g_2,g_3 assigned to one site and g_4,g_5,g_6 to the other.

Check groups:

  A  two compositions of the same one-site data: both iota and kappa are
     injective unital *-homomorphisms generating all of M_8(C), they agree on
     the even one-site content, and they differ in their cross-site relations;
  B  the ungraded product forbids a site-local graded family;
  C  every complex Z_2-grading of the site algebra is an axis, different
     axes give different odd parts, and the *-compatible axes are real;
  D  proper cubic rotations: no invariant axis, the vector representation is
     irreducible, and the only rotation-equivariant unital real automorphisms
     of M_2(C) are the identity and the antilinear Clifford involution alpha;
  E  the graded composition with the mode's own parity: exact CAR, order
     independence up to an even intertwiner, the ladder's own parity axis,
     parity superselection, and readable one-site content;
  F  the rotation-covariant real alternative: six Majoranas on two sites give
     a real algebra of real dimension 64 against 32 for M_2(C) (x) M_2(C), the
     site generators anticommute across sites, and the smallest even Hermitian
     non-scalar elements are cross-site bond bilinears;
  G  the graded clause selects no dynamics and no state;
  H  coexistence: the two local structures share the parity-even and
     parity-odd subspaces exactly, at most 7 of the 12 nearest-neighbour
     bonds of a 2x2x2 cube are string-free under any total order, and the
     three-Majorana bilinears form a commuting spin-1/2 lattice inside the
     even sector of the real graded product.

Output: one PASS/FAIL line per check and a final `TOTAL: PASS=N FAIL=M`.
Exit code 0 iff FAIL = 0.
"""

