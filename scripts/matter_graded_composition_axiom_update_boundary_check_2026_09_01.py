def kron(*ms):
    out = ms[0]
    for m in ms[1:]:
        out = sp.kronecker_product(out, m)
    return Matrix(out)


def zero(M):
    return all(sp.expand(e) == 0 for e in M)


def eq(A, B):
    return zero(A - B)


def rows_of(mats):
    return Matrix([[e for e in M] for M in mats])


def iota(x, M):
    fac = [one, one, one]
    fac[x] = M
    return kron(*fac)


def jw_family(order):
    """c_x for the total order given by rank list `order` (order[y] = rank of y)."""
    out = []
    for x in range(NSITE):
        fac = []
        for y in range(NSITE):
            if y == x:
                fac.append(E01)
            elif order[y] < order[x]:
                fac.append(s3)
            else:
                fac.append(one)
        out.append(kron(*fac))
    return out


c = jw_family([0, 1, 2])
cd = [m.H for m in c]
n = [cd[x] * c[x] for x in range(NSITE)]
P = kron(s3, s3, s3)


def kappa(x, M):
    return sp.expand(
        M[0, 0] * (c[x] * cd[x])
        + M[0, 1] * c[x]
        + M[1, 0] * cd[x]
        + M[1, 1] * (cd[x] * c[x])
    )


