def embedding_report(emb):
    ok = True
    for x in range(NSITE):
        for i in range(2):
            for j in range(2):
                for k in range(2):
                    for l in range(2):
                        lhs = emb(x, UNITS[2 * i + j]) * emb(x, UNITS[2 * k + l])
                        rhs = emb(x, UNITS[2 * i + l]) if j == k else Z8
                        ok = ok and eq(lhs, rhs)
        for U in UNITS:
            ok = ok and eq(emb(x, U.H), emb(x, U).H)
        ok = ok and eq(emb(x, E00) + emb(x, E11), I8)
        ok = ok and rows_of([emb(x, U) for U in UNITS]).rank() == 4
    return ok


