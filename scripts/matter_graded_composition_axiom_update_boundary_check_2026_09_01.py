def ad_matrix(Vm):
    cols = []
    for Bm in UNITS:
        W = Vm * Bm * Vm
        cols.append([W[0, 0], W[0, 1], W[1, 0], W[1, 1]])
    return Matrix(cols).T


def flat2(M):
    return [M[0, 0], M[0, 1], M[1, 0], M[1, 1]]


