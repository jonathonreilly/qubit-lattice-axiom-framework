def coords(M):
    a = sp.re(M.trace() / 2)
    b = sp.im(M.trace() / 2)
    cs = [(M * s).trace() / 2 for s in SIG]
    return [a, b] + [sp.re(x) for x in cs] + [sp.im(x) for x in cs]


