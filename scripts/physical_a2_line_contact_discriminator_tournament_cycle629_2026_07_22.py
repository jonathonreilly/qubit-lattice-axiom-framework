def ball_mask(length: int, keep_radius: int) -> np.ndarray:
    return (C622.chebyshev_radii(length) <= keep_radius)[..., None]


def masked_step(engine, state, keep, contact):
    return engine.step(state, contact) * keep


def interior_line(engine, keep_radius: int, contact: float, iters: int = 600,
                  block: int = 8) -> dict[str, object]:
    """Dominant interior A2-sector line of the ball-absorber operator via
    block subspace iteration with Rayleigh-Ritz."""
    keep = ball_mask(engine.length, keep_radius)
    rng_free = [engine.source()]
    base = engine.source()
    vecs = [base]
    for i in range(1, block):
        nxt = masked_step(engine, vecs[-1], keep, contact)
        vecs.append(nxt / np.linalg.norm(nxt))
    block_v = np.stack([v.reshape(-1) for v in vecs], axis=1)

    def apply(mat):
        cols = []
        for j in range(mat.shape[1]):
            s = mat[:, j].reshape(engine.shape)
            s = masked_step(engine, s, keep, contact)
            cols.append(s.reshape(-1))
        return np.stack(cols, axis=1)

    for _ in range(iters):
        block_v = apply(block_v)
        q, _ = np.linalg.qr(block_v)
        block_v = q
    image = apply(block_v)
    small = block_v.conj().T @ image
    values, small_vecs = np.linalg.eig(small)
    ritz_vecs = block_v @ small_vecs
    rows = []
    radii = C622.chebyshev_radii(engine.length)
    for idx in range(len(values)):
        vec = ritz_vecs[:, idx]
        vec = vec / np.linalg.norm(vec)
        state = vec.reshape(engine.shape)
        residual = float(np.linalg.norm(
            masked_step(engine, state, keep, contact).reshape(-1)
            - values[idx] * vec))
        interior = float(np.sum(np.abs(state[radii <= 2]) ** 2))
        rows.append({"abs": float(abs(values[idx])),
                     "arg": float(np.angle(values[idx])),
                     "residual": residual,
                     "interior_weight": interior,
                     "antisym": engine.antisym_defect(state)})
    rows.sort(key=lambda r: -r["abs"])
    interior_rows = [r for r in rows if r["interior_weight"] > 0.9
                     and r["residual"] < 1e-8]
    return {"all": rows[:4], "interior": interior_rows[:2],
            "top_interior": interior_rows[0] if interior_rows else None}


