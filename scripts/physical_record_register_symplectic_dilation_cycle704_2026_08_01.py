#!/usr/bin/env python3
"""Cycle 704: record-register symplectic dilation of the executed Cycle-700
readout channel.

The Cycle-700 harness executes an open readout: an affine-linear symplectic
leapfrog on (phi, pi) over a Z^3 box, driven by a supplied frozen source, whose
kept output is the hold-window time average at four detector sites. Everything
not kept is discarded, and that discard is the open-system step.

This harness adjoins a record register pair (A, B) of size k = 4 and one exact
symplectic shear per hold step, generated by the coupling Hamiltonian
H_c = B . (P phi) with (phi, A) as positions and (pi, B) as momenta. It then
gates, against the landed Cycle-700 anchors: bit-for-bit non-disturbance on the
physical slice B = 0; that A carries the executed readout; per-factor exact
symplecticity with an explicit factor-wise inverse; exact conservation of B
under active coupling; the measured rank and kernel of the readout map; and the
Cycle-700 mutation family carried through the dilation.

The harness is import-safe: it imports the landed sibling runners and executes
their machinery, and emits a bounded transcript only when invoked.
"""

