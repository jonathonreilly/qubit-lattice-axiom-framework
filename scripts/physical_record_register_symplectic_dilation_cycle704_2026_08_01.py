def emit(line: str) -> None:
    _OUT.append(line)


def sig6(x) -> float:
    """Display rounding for machine-round-off diagnostics.

    Applied uniformly to every dimensionless defect, residual, and round-trip
    error reported below, and never to a physical magnitude, a landed anchor,
    or a singular value. Six significant digits far exceeds the meaningful
    content of a quantity whose size is set by double-precision round-off. The
    gates themselves always compare the unrounded value; only the transcript
    and the summary carry the rounded one.
    """
    return float(format(float(x), ".6e"))


def check(label: str, ok: bool, detail: object = "") -> bool:
    global _PASS, _FAIL
    if len(label) > 34 or not all(c.islower() or c.isdigit() or c == "_" for c in label):
        raise ValueError("invalid check label: " + label)
    if ok:
        _PASS += 1
        emit("PASS " + label)
    else:
        _FAIL += 1
        emit("FAIL " + label + " :: " + str(detail))
    return ok


def load_module(root: Path, alias: str, relative: str):
    spec = importlib.util.spec_from_file_location(alias, root / relative)
    if spec is None or spec.loader is None:
        raise ImportError(relative)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


