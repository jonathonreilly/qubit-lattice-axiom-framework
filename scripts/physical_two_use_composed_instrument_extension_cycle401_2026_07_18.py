def contact_and_two_use_controls(
    base: c385.EffectSystem,
    banks: tuple[c398.CompiledBank, ...],
    programs: tuple[ComposedProgram, ...],
) -> dict[str, object]:
    by_bank_program = {
        (program.bank_index, program.program_index): program
        for program in programs
    }
    two_use_update_residuals = []
    maximum_effect_change = 0.0
    maximum_process_change = 0.0
    minimum_bank_effect_change = []
    minimum_bank_process_change = []
    two_use_isometry = []
    for bank in banks:
        deleted_compilation = c390.compile_menus(base, bank.rows, I2)
        deleted_carrier = c398.FixedMenuBank(deleted_compilation.programs)
        actual_update = c323.two_use_from_fixed(bank.carrier.update)
        deleted_update = c323.two_use_from_fixed(deleted_carrier.update)
        two_use_update_residuals.append(float(np.linalg.norm(
            actual_update - deleted_update
        )))
        two_use_isometry.append(float(np.linalg.norm(
            actual_update.conj().T @ actual_update - np.eye(16)
        )))
        bank_effect = bank_process = 0.0
        for program_index, deleted_program in enumerate(
            deleted_compilation.programs
        ):
            actual = by_bank_program[(bank.index, program_index)]
            deleted_ops = tuple(
                right @ left
                for left in deleted_program.kraus
                for right in deleted_program.kraus
            )
            for branch, deleted_operator in zip(actual.branches, deleted_ops):
                effect_change = float(np.linalg.norm(
                    branch.effect - deleted_operator.conj().T @ deleted_operator
                ))
                process_change = float(np.linalg.norm(
                    branch.process - c321.choi((deleted_operator,))
                ))
                bank_effect = max(bank_effect, effect_change)
                bank_process = max(bank_process, process_change)
                maximum_effect_change = max(maximum_effect_change, effect_change)
                maximum_process_change = max(maximum_process_change, process_change)
        minimum_bank_effect_change.append(bank_effect)
        minimum_bank_process_change.append(bank_process)
    detail = {
        "carrier_banks": len(banks),
        "two_use_update_contact_deletion_residuals": tuple(two_use_update_residuals),
        "minimum_two_use_update_contact_deletion_residual": min(two_use_update_residuals),
        "maximum_two_use_isometry_residual": max(two_use_isometry),
        "maximum_ordered_effect_contact_deletion_change": maximum_effect_change,
        "maximum_ordered_process_contact_deletion_change": maximum_process_change,
        "per_bank_maximum_effect_change": tuple(minimum_bank_effect_change),
        "per_bank_maximum_process_change": tuple(minimum_bank_process_change),
        "actual_contact_is_load_bearing_in_every_bank": all(
            effect > 0.01 and process > 0.01
            for effect, process in zip(
                minimum_bank_effect_change, minimum_bank_process_change
            )
        ),
    }
    check(
        "actual contact is load-bearing in every fixed two-use update, ordered effect, and process family",
        len(banks) == 7
        and min(two_use_update_residuals) > 0.5
        and max(two_use_isometry) < TOL
        and maximum_effect_change > 0.05
        and maximum_process_change > 0.1
        and detail["actual_contact_is_load_bearing_in_every_bank"],
        detail,
    )
    return detail


