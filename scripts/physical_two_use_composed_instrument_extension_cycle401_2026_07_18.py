def process_quotient_controls(
    programs: tuple[ComposedProgram, ...],
) -> dict[str, object]:
    by_effect: dict[c383.MatrixKey, dict[c383.MatrixKey, np.ndarray]] = {}
    occurrences = 0
    for program in programs:
        for presentation in program.presentations:
            for effect, process in zip(
                presentation.effects, presentation.processes
            ):
                effect_key = c383.matrix_key(effect)
                process_key = c383.matrix_key(process)
                by_effect.setdefault(effect_key, {})[process_key] = process
                occurrences += 1
    maximum_separator = 0.0
    for processes in by_effect.values():
        matrices = tuple(processes.values())
        for left in range(len(matrices)):
            for right in range(left + 1, len(matrices)):
                maximum_separator = max(
                    maximum_separator,
                    float(np.linalg.norm(matrices[left] - matrices[right])),
                )
    process_keys = {
        key for processes in by_effect.values() for key in processes
    }
    detail = {
        "composed_effect_occurrences": occurrences,
        "composed_equal_effect_keys": len(by_effect),
        "effect_process_pairs": sum(len(processes) for processes in by_effect.values()),
        "unique_process_tags": len(process_keys),
        "effect_keys_with_multiple_process_tags": sum(
            len(processes) > 1 for processes in by_effect.values()
        ),
        "maximum_process_tags_for_one_effect": max(
            map(len, by_effect.values())
        ),
        "maximum_same_effect_distinct_process_Choi_separator": maximum_separator,
        "effect_functionality_premise_supplied": True,
        "process_functionality_premise_supplied": False,
        "same_effect_means_same_process": False,
        "distinct_process_tags_retained": True,
    }
    check(
        "equal effects share incidence classes while 785 distinct effect/process pairs retain process separators",
        occurrences == 3277
        and len(by_effect) == 616
        and detail["effect_process_pairs"] == 785
        and detail["unique_process_tags"] == 785
        and detail["effect_keys_with_multiple_process_tags"] == 50
        and detail["maximum_process_tags_for_one_effect"] == 15
        and maximum_separator > 0.86
        and detail["effect_functionality_premise_supplied"]
        and not detail["process_functionality_premise_supplied"]
        and not detail["same_effect_means_same_process"]
        and detail["distinct_process_tags_retained"],
        detail,
    )
    return detail


