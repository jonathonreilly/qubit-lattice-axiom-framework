    incidence_failures = 0
    representatives = 0
    for length in (3, 4, 5, 6):
        code = c252.join_code(length)
        for space in cache[length]:
            endpoints = set(code.graph.edges[space.seed][:2])
            for candidate in quotient_candidates(code, space):
                representatives += 1
                code_failures += sum(
                    not candidate.commutes(stabilizer)
                    for stabilizer in c256.local_constraints(code)
                )
                matter_x = {
                    vertex
                    for vertex in range(code.vertices)
                    if (candidate.x >> (code.m_offset + vertex)) & 1
                }
