def gf2_rank(rows: list[int]) -> int:
    pivots: dict[int, int] = {}
    for source in rows:
        row = int(source)
        while row:
            pivot = row.bit_length() - 1
            if pivot in pivots:
                row ^= pivots[pivot]
            else:
                pivots[pivot] = row
                break
    return len(pivots)


def add_to_span(vector: int, pivots: dict[int, int]) -> bool:
    value = int(vector)
    while value:
        pivot = value.bit_length() - 1
        if pivot in pivots:
            value ^= pivots[pivot]
        else:
            pivots[pivot] = value
            return True
    return False


def coefficient_equations(
    code: c252.JoinCode, seed: int, columns: list[c235.Pauli]
) -> list[int]:
    equations = []
    for stabilizer in c256.local_constraints(code):
        row = sum(
            1 << index
            for index, column in enumerate(columns)
            if not column.commutes(stabilizer)
        )
        if row:
            equations.append(row)
    for vertex_map, edge_map in c256.edge_stabilizer_maps(code, seed):
        coordinate_rows: dict[tuple[str, int], int] = {}
        for index, column in enumerate(columns):
            moved = c256.permute_pauli(code, column, vertex_map, edge_map)
            for part, difference in (("x", column.x ^ moved.x), ("z", column.z ^ moved.z)):
                while difference:
                    bit = (difference & -difference).bit_length() - 1
                    key = (part, bit)
                    coordinate_rows[key] = coordinate_rows.get(key, 0) ^ (1 << index)
                    difference &= difference - 1
        equations.extend(row for row in coordinate_rows.values() if row)
    return equations


def physical_vector(
    code: c252.JoinCode, columns: list[c235.Pauli], coefficients: int
) -> int:
    x = 0
    z = 0
    for index, column in enumerate(columns):
        if (coefficients >> index) & 1:
            x ^= column.x
            z ^= column.z
    return x | (z << code.total_qubits)


def vertex_ball(code: c252.JoinCode, seed: int, radius: int) -> set[int]:
    vertices = set(code.graph.edges[seed][:2])
    for _ in range(radius):
        vertices |= {
            neighbor
            for vertex in tuple(vertices)
            for edge in code.graph.incident[vertex]
            for neighbor in code.graph.edges[edge][:2]
        }
    return vertices


def bounded_check_product_generators(
    code: c252.JoinCode, seed: int, radius: int
) -> list[c235.Pauli]:
    """Local checks centered wholly in a finite graph ball around the seed."""
    vertices = vertex_ball(code, seed, radius)
    result = [code.combined_gauss[vertex] for vertex in sorted(vertices)]
    result += [code.frame_moves[vertex] for vertex in sorted(vertices)]
    result += [
        code.charge_moves[edge]
        for edge, (left, right, _, _) in enumerate(code.graph.edges)
        if left in vertices and right in vertices
    ]
    cycles = c235.primal_edge_cycles(code.graph)
    result += [
        code.frame_flat[index]
        for index, (_, cycle_vertices, _) in enumerate(cycles)
        if set(cycle_vertices) <= vertices
    ]
    return result


@dataclass
class QuotientSeedSpace:
    seed: int
    kind: str
    columns: int
    affine_basis: list[int]
    affine_rank: int
    stabilizer_intersection_dimension: int
    quotient_basis: list[int]
    full_stabilizer_rank: int
    bounded_intersections: tuple[int, int, int]
    bounded_check_counts: tuple[int, int, int]
    bounded_subset_failures: int
    witness_radius: int


def quotient_seed_space(code: c252.JoinCode, seed: int) -> QuotientSeedSpace:
    columns = c256.radius_two_columns(code, seed)
    equations = coefficient_equations(code, seed, columns)
    _, coefficient_basis = c256.rref_nullspace(equations, len(columns))
    affine_basis = [
        physical_vector(code, columns, coefficients)
        for coefficients in coefficient_basis
    ]
    stabilizers = [
        c256.pauli_vector(stabilizer, code.total_qubits)
        for stabilizer in c256.local_constraints(code)
    ]
    stabilizer_rank = gf2_rank(stabilizers)
    affine_rank = gf2_rank(affine_basis)
    intersection = (
        affine_rank
        + stabilizer_rank
        - gf2_rank(stabilizers + affine_basis)
    )
    pivots: dict[int, int] = {}
    for stabilizer in stabilizers:
        add_to_span(stabilizer, pivots)
    quotient_basis = []
    for vector in affine_basis:
        trial = dict(pivots)
        if add_to_span(vector, trial):
            quotient_basis.append(vector)
            pivots = trial

    bounded_intersections = []
    bounded_counts = []
    bounded_subset_failures = 0
    full_span: dict[int, int] = {}
    for stabilizer in stabilizers:
        add_to_span(stabilizer, full_span)
    for radius in (0, 1, 2):
        bounded_checks = bounded_check_product_generators(code, seed, radius)
        bounded_vectors = [
            c256.pauli_vector(check_pauli, code.total_qubits)
            for check_pauli in bounded_checks
        ]
        bounded_rank = gf2_rank(bounded_vectors)
        for vector in bounded_vectors:
            trial = dict(full_span)
            bounded_subset_failures += add_to_span(vector, trial)
        bounded_intersections.append(
            affine_rank
            + bounded_rank
            - gf2_rank(affine_basis + bounded_vectors)
        )
        bounded_counts.append(len(bounded_checks))
    witness_radius = next(
        radius
        for radius, dimension in enumerate(bounded_intersections)
        if dimension == intersection
    )
    return QuotientSeedSpace(
        seed=seed,
        kind=code.graph.edges[seed][2],
        columns=len(columns),
        affine_basis=affine_basis,
        affine_rank=affine_rank,
        stabilizer_intersection_dimension=intersection,
        quotient_basis=quotient_basis,
        full_stabilizer_rank=stabilizer_rank,
        bounded_intersections=tuple(bounded_intersections),
        bounded_check_counts=tuple(bounded_counts),
        bounded_subset_failures=bounded_subset_failures,
        witness_radius=witness_radius,
    )


def quotient_candidates(
    code: c252.JoinCode, space: QuotientSeedSpace
) -> list[c235.Pauli]:
    natural = c256.pauli_vector(
        c256.natural_hopping(code, space.seed), code.total_qubits
    )
    result = []
    for assignment in range(1 << len(space.quotient_basis)):
        vector = natural
        for index, basis in enumerate(space.quotient_basis):
            if (assignment >> index) & 1:
                vector ^= basis
        result.append(c256.vector_pauli(vector, code.total_qubits))
    return result


def quotient_basis_descriptor(
    code: c252.JoinCode, space: QuotientSeedSpace
) -> dict[str, object]:
    supports = []
    pauli_form_failures = 0
    matter_mask = (1 << code.vertices) - 1
    for vector in space.quotient_basis:
        pauli = c256.vector_pauli(vector, code.total_qubits)
        matter_z = (pauli.z >> code.m_offset) & matter_mask
        pauli_form_failures += pauli.x != 0 or pauli.z != matter_z
        supports.append(
            frozenset(
                vertex
                for vertex in range(code.vertices)
                if (matter_z >> vertex) & 1
            )
        )

    left, right = code.graph.edges[space.seed][:2]
    if space.kind == "internal_triangle":
        cell = code.graph.vertices[left][0]
        left_role = code.graph.vertices[left][1]
        right_role = code.graph.vertices[right][1]
        reverse_pair = frozenset(
            (
                code.graph.vertex_index[(cell, c235.REVERSE[left_role])],
                code.graph.vertex_index[(cell, c235.REVERSE[right_role])],
            )
        )
        used_roles = {
            left_role,
            right_role,
            c235.REVERSE[left_role],
            c235.REVERSE[right_role],
        }
        remaining_pair = frozenset(
            code.graph.vertex_index[(cell, role)]
            for role in range(6)
            if role not in used_roles
        )
        outer_neighbors = []
        for endpoint in (left, right):
            outer_edge = next(
                edge
                for edge in code.graph.incident[endpoint]
                if code.graph.edges[edge][2] == "outer_square"
            )
            endpoints = code.graph.edges[outer_edge][:2]
            outer_neighbors.append(endpoints[1] if endpoints[0] == endpoint else endpoints[0])
        expected = {
            frozenset((left, right)),
            reverse_pair,
            remaining_pair,
            frozenset(outer_neighbors),
        }
        names = (
            "endpoint pair",
            "reverse-role onsite pair",
            "remaining onsite pair",
            "two outer-continuation neighbors",
        )
    else:
        left_cell, left_role = code.graph.vertices[left]
        right_cell, right_role = code.graph.vertices[right]
        axis_roles = {left_role, right_role}
        transverse = frozenset(
            code.graph.vertex_index[(cell, role)]
            for cell in (left_cell, right_cell)
            for role in range(6)
            if role not in axis_roles
        )
        expected = {frozenset((left, right)), transverse}
        names = ("endpoint pair", "eight transverse vertices")
    return {
        "kind": space.kind,
        "pauli_form_failures": pauli_form_failures,
        "support_match": set(supports) == expected,
        "support_sizes": sorted(len(support) for support in supports),
        "descriptors": names,
        "supports": [
            tuple(code.graph.vertices[vertex] for vertex in sorted(support))
            for support in supports
        ],
    }


def sparse_permute(
    code: c252.JoinCode,
    pauli: c235.Pauli,
    vertex_map: list[int],
    edge_map: list[int],
) -> c235.Pauli:
    def moved_position(position: int) -> int:
        if position < code.g_offset:
            return code.m_offset + vertex_map[position - code.m_offset]
        if position < code.f_offset:
            return code.g_offset + edge_map[position - code.g_offset]
        if position < code.r_offset:
            return code.f_offset + edge_map[position - code.f_offset]
        return code.r_offset + vertex_map[position - code.r_offset]

    x = 0
    source = pauli.x
    while source:
        bit = (source & -source).bit_length() - 1
        x |= 1 << moved_position(bit)
        source &= source - 1
    z = 0
    source = pauli.z
    while source:
        bit = (source & -source).bit_length() - 1
        z |= 1 << moved_position(bit)
        source &= source - 1
    return c235.Pauli(x=x, z=z)


@dataclass
class SymmetryMaps:
    frames: list[tuple[list[int], list[int]]]
    translations: dict[tuple[int, int, int], tuple[list[int], list[int]]]


def symmetry_maps(code: c252.JoinCode) -> SymmetryMaps:
    frames = [c235.graph_frame_maps(code.graph, frame) for frame in c235.proper_cubic_frames()]
    translations = {
        displacement: c256.translation_maps(code, displacement)
        for displacement in product(range(code.graph.length), repeat=3)
    }
    return SymmetryMaps(frames=frames, translations=translations)


def candidate_family(
    code: c252.JoinCode,
    maps: SymmetryMaps,
    seed: int,
    candidate: c235.Pauli,
) -> tuple[list[c235.Pauli | None], int]:
    family: list[c235.Pauli | None] = [None] * code.edges
    ambiguities = 0
    for frame_vertices, frame_edges in maps.frames:
        framed = sparse_permute(code, candidate, frame_vertices, frame_edges)
        mapped_seed = frame_edges[seed]
        owner = code.graph.edges[mapped_seed][3]
        for target_cell in product(range(code.graph.length), repeat=3):
            displacement = tuple(
                (target_cell[axis] - owner[axis]) % code.graph.length
                for axis in range(3)
            )
            translation_vertices, translation_edges = maps.translations[displacement]
            target = translation_edges[mapped_seed]
            moved = sparse_permute(
                code, framed, translation_vertices, translation_edges
            )
            previous = family[target]
            if previous is not None and (
                previous.x != moved.x or previous.z != moved.z
            ):
                ambiguities += 1
            family[target] = moved
    return family, ambiguities


@dataclass
class TruthTableResult:
    assignments: int
    models: list[tuple[int, int]]
    satisfaction_mask: int
    best: tuple[int, int, int, int, int]
    histogram: dict[tuple[int, int], int]
    incident_relations: int
    disjoint_relations: int
    local_pairs_replayed: int
    support_discharged_pairs: int
    covariance_ambiguities: int
    first_witnesses: list[dict[str, object]]
    maximum_support: int


def exact_truth_table(
    code: c252.JoinCode,
    internal: QuotientSeedSpace,
    outer: QuotientSeedSpace,
) -> TruthTableResult:
    maps = symmetry_maps(code)
    internal_candidates = quotient_candidates(code, internal)
    outer_candidates = quotient_candidates(code, outer)
    internal_families = []
    outer_families = []
    ambiguities = 0
    for candidate in internal_candidates:
        family, failures = candidate_family(code, maps, internal.seed, candidate)
        internal_families.append(family)
        ambiguities += failures
    for candidate in outer_candidates:
        family, failures = candidate_family(code, maps, outer.seed, candidate)
        outer_families.append(family)
        ambiguities += failures

    union_support = []
    for edge in range(code.edges):
        families = (
            internal_families
            if code.graph.edges[edge][2] == "internal_triangle"
            else outer_families
        )
        support = 0
        for family in families:
            support |= family[edge].x | family[edge].z
        union_support.append(support)

    local_pairs = []
    total_pairs = code.edges * (code.edges - 1) // 2
    incident_relations = 0
    for left, right in combinations(range(code.edges), 2):
        left_endpoints = code.graph.edges[left][:2]
        right_endpoints = code.graph.edges[right][:2]
        incident = (
            left_endpoints[0] == right_endpoints[0]
            or left_endpoints[0] == right_endpoints[1]
            or left_endpoints[1] == right_endpoints[0]
            or left_endpoints[1] == right_endpoints[1]
        )
        incident_relations += incident
        if incident or (union_support[left] & union_support[right]):
            local_pairs.append((left, right, incident))
    disjoint_relations = total_pairs - incident_relations

    models = []
    best = (10**18, 10**18, 10**18, 0, 0)
    histogram: dict[tuple[int, int], int] = {}
    witnesses = []
    maximum_support = 0
    for internal_assignment, internal_family in enumerate(internal_families):
        for outer_assignment, outer_family in enumerate(outer_families):
            family = [
                internal_family[edge]
                if code.graph.edges[edge][2] == "internal_triangle"
                else outer_family[edge]
                for edge in range(code.edges)
            ]
            maximum_support = max(
                maximum_support,
                max((pauli.x | pauli.z).bit_count() for pauli in family),
            )
            incident_failures = 0
            disjoint_failures = 0
            first = None
            for left, right, wanted in local_pairs:
                actual = not family[left].commutes(family[right])
                if actual != wanted:
                    if wanted:
                        incident_failures += 1
                    else:
                        disjoint_failures += 1
                    if first is None:
                        first = {
                            "assignment": (internal_assignment, outer_assignment),
                            "edges": (left, right),
                            "shared_endpoint_required": wanted,
                            "actual_anticommutator_bit": int(actual),
                        }
            total = incident_failures + disjoint_failures
            histogram[(incident_failures, disjoint_failures)] = (
                histogram.get((incident_failures, disjoint_failures), 0) + 1
            )
            if total < best[0]:
                best = (
                    total,
                    incident_failures,
                    disjoint_failures,
                    internal_assignment,
                    outer_assignment,
                )
            if total == 0:
                models.append((internal_assignment, outer_assignment))
            else:
                witnesses.append(first)
    return TruthTableResult(
        assignments=len(internal_families) * len(outer_families),
        models=models,
        satisfaction_mask=sum(
            1 << (internal_assignment * len(outer_families) + outer_assignment)
            for internal_assignment, outer_assignment in models
        ),
        best=best,
        histogram=histogram,
        incident_relations=incident_relations,
        disjoint_relations=disjoint_relations,
        local_pairs_replayed=len(local_pairs),
        support_discharged_pairs=total_pairs - len(local_pairs),
        covariance_ambiguities=ambiguities,
        first_witnesses=witnesses,
        maximum_support=maximum_support,
    )


