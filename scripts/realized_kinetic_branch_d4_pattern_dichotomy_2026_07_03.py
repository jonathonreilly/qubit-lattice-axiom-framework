def _expm_2x2(M):
    """Matrix exponential for a 2x2 complex matrix via eigendecomposition."""
    w, V = np.linalg.eig(M)
    return V @ np.diag(np.exp(w)) @ np.linalg.inv(V)


def _proportional_sign(A, B, tol=1e-9):
    """Return s in {+1,-1} if A ~= s*B, else None (B must be nonzero)."""
    nb = np.linalg.norm(B)
    if nb < tol:
        return None
    for s in (1.0, -1.0):
        if np.linalg.norm(A - s * B) < 1e-9:
            return s
    return None


def fourier_extract(C_true, A_true, B_true):
    """Extract C, A_mu, B_mu from the Hermitian NN symbol by discrete Fourier
    orthogonality on an 8^3 momentum grid.

    K(p) = C + sum_mu (A_mu cos p_mu + B_mu sin p_mu).  On the uniform grid,
    <1,1>=1, <1,cos p_mu>=<1,sin p_mu>=0, <cos p_mu,cos p_nu>=(1/2)delta,
    <sin p_mu,sin p_nu>=(1/2)delta, <cos,sin>=0, so the coefficients are the
    grid averages of K weighted by 1, 2 cos p_mu, 2 sin p_mu respectively.
    """
    N = 8
    vals = np.linspace(-math.pi, math.pi, N, endpoint=False)
    pts = list(itertools.product(vals, repeat=3))
    npts = len(pts)
    C_acc = np.zeros((2, 2), dtype=complex)
    A_acc = [np.zeros((2, 2), dtype=complex) for _ in range(3)]
    B_acc = [np.zeros((2, 2), dtype=complex) for _ in range(3)]
    for p in pts:
        p = np.array(p, dtype=float)
        K = nn_symbol(p, C_true, A_true, B_true)
        C_acc += K
        for mu in range(3):
            A_acc[mu] += 2.0 * math.cos(float(p[mu])) * K
            B_acc[mu] += 2.0 * math.sin(float(p[mu])) * K
    C_ext = C_acc / npts
    A_ext = [A_acc[mu] / npts for mu in range(3)]
    B_ext = [B_acc[mu] / npts for mu in range(3)]
    return C_ext, A_ext, B_ext


