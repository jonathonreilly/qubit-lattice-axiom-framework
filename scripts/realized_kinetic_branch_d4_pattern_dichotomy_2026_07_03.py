def eta0(x, mu):
    """Kawamoto-Smit signs, matching the parent kinetic-class runner."""
    if mu == 0:
        return 1.0
    if mu == 1:
        return (-1.0) ** (x[0] % 2)
    return (-1.0) ** ((x[0] + x[1]) % 2)


def Tmat(x):
    out = I2.copy()
    for mu, power in enumerate(x):
        if power % 2:
            out = out @ SIG[mu]
    return out


def absorbed_k1_edge_coefficients(tfun=eta0):
    """Direction matrices from eta and the parent absorbing frame.

    The identity T(x)^dag sigma_mu T(x+mu) = eta_mu(x) I implies
    sigma_mu = eta_mu(x) T(x) T(x+mu)^dag.  Average only after computing
    these edge matrices from the phase system.
    """
    coeffs = []
    spreads = []
    for mu in range(3):
        mats = []
        for x in CELL:
            y = tuple(np.array(x) + E_UNIT[mu])
            mats.append(complex(tfun(x, mu)) * Tmat(x) @ Tmat(y).conj().T)
        avg = sum(mats) / len(mats)
        coeffs.append(avg)
        spreads.append(max(np.linalg.norm(M - avg) for M in mats))
    return coeffs, spreads


def k1_raw_extraction_symbol(p, edge_coeffs):
    M = np.zeros((2, 2), dtype=complex)
    for mu in range(3):
        M += 1j * edge_coeffs[mu] * math.sin(float(p[mu]))
    return M


def extract_k1_gammas(edge_coeffs):
    gammas = []
    q = math.pi / 2.0
    for mu in range(3):
        p_plus = np.zeros(3)
        p_minus = np.zeros(3)
        p_plus[mu] = q
        p_minus[mu] = -q
        raw_plus = k1_raw_extraction_symbol(p_plus, edge_coeffs)
        raw_minus = k1_raw_extraction_symbol(p_minus, edge_coeffs)
        gammas.append((raw_plus - raw_minus) / (2j))
    return gammas


def blocked_symbol_8(p, phases):
    """Translation-cell (2^3) blocked nearest-neighbor symbol from per-link
    phases, mirroring the discriminator runner's T8 pipeline."""
    M = np.zeros((8, 8), dtype=complex)
    for r in CELL:
        for mu in range(3):
            y = list(r)
            y[mu] += 1
            block_shift = np.zeros(3)
            if y[mu] >= 2:
                y[mu] -= 2
                block_shift[mu] = 1.0
            y = tuple(y)
            phase = complex(phases[(r, mu)])
            z = np.exp(1j * float(np.dot(p, block_shift)))
            i = CELL_INDEX[y]
            j = CELL_INDEX[r]
            M[i, j] += phase * z
            M[j, i] += np.conj(phase) * np.conj(z)
    return M


def blocked_derivative_gammas_8(phases):
    """First-order (sin) coefficient family of the blocked symbol, extracted by
    a momentum derivative at p0 = pi*(1,1,1), as the discriminator runner does."""
    p0 = math.pi * np.ones(3)
    dq = 1e-5
    out = []
    for mu in range(3):
        e = np.zeros(3)
        e[mu] = dq
        out.append(
            (blocked_symbol_8(p0 + e, phases) - blocked_symbol_8(p0 - e, phases))
            / (2.0 * dq)
        )
    return out


def eta0_cell_phases():
    return {(r, mu): eta0(r, mu) for r in CELL for mu in range(3)}


def perturbed_cell_phases():
    """Flip one eta0 link sign (as the discriminator runner's T8 does)."""
    phases = eta0_cell_phases()
    phases[((1, 0, 0), 0)] *= -1.0
    return phases


# --------------------------------------------------------------------------
# Hermitian nearest-neighbor symbol machinery for the covariance legs.
# K(p) = C + sum_mu (A_mu cos p_mu + B_mu sin p_mu).
# --------------------------------------------------------------------------

def nn_symbol(p, C, As, Bs):
    M = np.array(C, dtype=complex)
    for mu in range(3):
        M = M + As[mu] * math.cos(float(p[mu])) + Bs[mu] * math.sin(float(p[mu]))
    return M


def rot_z12(p):
    """Proper C4z rotation of momentum: (p0,p1,p2) -> (p1,-p0,p2)."""
    return np.array([p[1], -p[0], p[2]], dtype=float)


def grid_points(N):
    vals = np.linspace(-math.pi, math.pi, N, endpoint=False)
    return list(itertools.product(vals, repeat=3))


