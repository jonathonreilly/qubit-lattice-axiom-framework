def vectorize(M):
    return np.asarray(M, dtype=complex).reshape(-1, order="F")


def rank_complex(A, tol=1e-10):
    if A.size == 0:
        return 0
    s = np.linalg.svd(A, compute_uv=False)
    return int(np.sum(s > tol))


def alg_dim(gens, tol=1e-10):
    """Dimension of the unital *-subalgebra of M_n(C) generated by gens.

    Start from [I] + gens + adjoints, close under pairwise products to a
    fixed point (dimension can only grow, capped at n*n), take numerical
    rank of the flattened span via SVD at tol.  Real machinery: the rank is
    computed from actual singular values, never from an if/else on whether a
    generator is scalar.
    """
    n = gens[0].shape[0]
    basis = [np.eye(n, dtype=complex)]
    candidates = list(gens) + [G.conj().T for G in gens]

    def current_rank(items):
        return rank_complex(np.column_stack([vectorize(B) for B in items]), tol)

    changed = True
    while changed:
        changed = False
        for C in list(candidates):
            trial = basis + [C]
            if current_rank(trial) > current_rank(basis):
                basis.append(C)
                changed = True
        products = []
        for A in basis:
            for B in basis:
                products.append(A @ B)
        candidates = products + [P.conj().T for P in products]
    return current_rank(basis)


def rand_hermitian(rng):
    A = rng.standard_normal((2, 2)) + 1j * rng.standard_normal((2, 2))
    return (A + A.conj().T) / 2.0


def rand_unitary(rng):
    A = rng.standard_normal((2, 2)) + 1j * rng.standard_normal((2, 2))
    Q, R = np.linalg.qr(A)
    ph = np.diag(R) / np.abs(np.diag(R))
    return Q * ph.conj()


