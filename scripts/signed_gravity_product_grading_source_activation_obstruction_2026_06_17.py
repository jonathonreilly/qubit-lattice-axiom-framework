#!/usr/bin/env python3
"""Product-grading source-activation obstruction for signed gravity.

This runner isolates the source-action step left open after the product-grading
eta-sector bridge.  The product grading supplies an odd involution Gamma with
sector labels (+,-).  The question here is narrower:

    Does the presence of Gamma itself force the scalar source action to use it?

In the finite two-sector linear scalar-source class generated by I and Gamma,
the answer is exact:

  * orientation-even scalar coefficients are multiples of I and give only
    [+, +] or [0, 0] source vectors;
  * the desired [+, -] active source is the unique Gamma coefficient;
  * therefore the product grading derives the label carrier, but the active
    odd source coefficient is still a source-line/section activation premise.

This is a source-side obstruction packet, not a physical signed-gravity claim.
"""

from __future__ import annotations

import os
import sys
from dataclasses import dataclass

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
COMPANION_NOTE = "SIGNED_GRAVITY_PRODUCT_GRADING_SOURCE_ACTIVATION_OBSTRUCTION_NOTE_2026-06-17.md"

TOL = 1.0e-10
PASS = 0
FAIL = 0


def check(name: str, ok: bool, detail: str = "") -> None:
    global PASS, FAIL
    if ok:
        PASS += 1
        status = "PASS"
    else:
        FAIL += 1
        status = "FAIL"
    suffix = f"  ({detail})" if detail else ""
    print(f"[{status}] {name}{suffix}")


def read_note(name: str) -> str:
    path = os.path.join(DOCS, name)
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def normalize(vec: np.ndarray) -> np.ndarray:
    total = float(np.sum(vec))
    if abs(total) <= TOL:
        raise ValueError("zero density")
    return vec / total


def packet_density(n: int = 17, center: float = 8.0, sigma: float = 2.2) -> np.ndarray:
    xs = np.arange(n, dtype=float)
    return normalize(np.exp(-0.5 * ((xs - center) / sigma) ** 2))


@dataclass(frozen=True)
class LinearSourceCoefficient:
    name: str
    a_identity: float
    b_gamma: float
    description: str

    def matrix(self) -> np.ndarray:
        ident = np.eye(2)
        gamma = np.diag([1.0, -1.0])
        return self.a_identity * ident + self.b_gamma * gamma

    def source_vector(self) -> np.ndarray:
        mat = self.matrix()
        return np.diag(mat)


def source_from_variation(coeff: LinearSourceCoefficient, mass: float, rho: np.ndarray) -> np.ndarray:
    """Return the sector-integrated active source from S = -M <rho,Phi> C."""

    phi = np.linspace(-0.03, 0.04, len(rho))
    step = 1.0e-6
    active = []
    for sector in range(2):
        c = coeff.source_vector()[sector]
        numeric = np.zeros_like(rho)
        for idx in range(len(rho)):
            dphi = np.zeros_like(rho)
            dphi[idx] = step

            def action(local_phi: np.ndarray) -> float:
                return -float(mass * c * np.dot(rho, local_phi))

            dsdphi = (action(phi + dphi) - action(phi - dphi)) / (2.0 * step)
            numeric[idx] = -dsdphi
        active.append(float(np.sum(numeric)))
    return np.array(active)


def orientation_exchange() -> np.ndarray:
    return np.array([[0.0, 1.0], [1.0, 0.0]])


def invariant_under_exchange(coeff: LinearSourceCoefficient) -> bool:
    r = orientation_exchange()
    mat = coeff.matrix()
    return bool(np.allclose(r @ mat @ r.T, mat, atol=TOL))


def odd_under_exchange(coeff: LinearSourceCoefficient) -> bool:
    r = orientation_exchange()
    mat = coeff.matrix()
    return bool(np.allclose(r @ mat @ r.T, -mat, atol=TOL))


def least_squares_residual(coeffs: list[LinearSourceCoefficient], target: np.ndarray) -> tuple[float, np.ndarray]:
    basis = np.column_stack([c.source_vector() for c in coeffs])
    weights, *_ = np.linalg.lstsq(basis, target, rcond=None)
    residual = float(np.linalg.norm(basis @ weights - target))
    return residual, weights


def force_read(force_a: int, force_b: int) -> str:
    if abs(force_a) < TOL and abs(force_b) < TOL:
        return "ZERO"
    residual = abs(force_a + force_b) / max(abs(force_a), abs(force_b), 1.0)
    if residual > 1.0e-12:
        return "UNBALANCED"
    return "ATTRACT" if force_a > 0 else "REPEL"


def locked_table(source_coeff: LinearSourceCoefficient, response_coeff: LinearSourceCoefficient) -> tuple[bool, str]:
    source = np.sign(source_coeff.source_vector()).astype(int)
    response = np.sign(response_coeff.source_vector()).astype(int)
    pairs = ((0, 0), (0, 1), (1, 0), (1, 1))
    reads = []
    for a, b in pairs:
        force_a = response[a] * source[b]
        force_b = -response[b] * source[a]
        reads.append(force_read(force_a, force_b))
    desired = ["ATTRACT", "REPEL", "REPEL", "ATTRACT"]
    return reads == desired, ",".join(reads)


def main() -> int:
    print("=" * 88)
    print("SIGNED GRAVITY PRODUCT-GRADING SOURCE-ACTIVATION OBSTRUCTION")
    print("  exact two-sector source-action split; not a physical signed-gravity claim")
    print("=" * 88)
    print()

    product_note = read_note("SIGNED_GRAVITY_PRODUCT_GRADING_ETA_SECTOR_SELECTION_BRIDGE_NARROW_THEOREM_NOTE_2026-06-11.md")
    companion_note = read_note(COMPANION_NOTE)
    lower_product = product_note.lower()
    lower_companion = companion_note.lower()
    check(
        "upstream product-grading note derives the opposite eta label pair",
        "derived label pair" in lower_product
        and "derivation of `s_int`" in lower_product
        and "action `s_int` itself" in lower_product,
    )
    check(
        "companion note records source activation as the remaining boundary",
        "active use of gamma in s_int" in lower_companion
        and "gate result: pass for this narrow obstruction boundary" in lower_companion
        and "this note does **not** derive `s_int`" in lower_companion,
    )

    ident = LinearSourceCoefficient(
        "identity_even_source",
        1.0,
        0.0,
        "orientation-even scalar source coefficient",
    )
    spectator = LinearSourceCoefficient(
        "eta_spectator_no_source",
        0.0,
        0.0,
        "eta label is present but not activated in the source action",
    )
    gamma = LinearSourceCoefficient(
        "gamma_odd_source_line",
        0.0,
        1.0,
        "orientation-line/source-section coefficient",
    )
    mixed = LinearSourceCoefficient(
        "generic_linear_coefficient",
        0.25,
        0.75,
        "generic I + Gamma coefficient",
    )

    R = orientation_exchange()
    Gamma = np.diag([1.0, -1.0])
    check("product grading Gamma is an odd involution", np.allclose(Gamma @ Gamma, np.eye(2)) and np.allclose(R @ Gamma @ R.T, -Gamma))
    check("identity source is orientation-even", invariant_under_exchange(ident))
    check("Gamma source is orientation-odd", odd_under_exchange(gamma) and not invariant_under_exchange(gamma))
    check("generic I+Gamma coefficient is neither invariant nor pure odd", not invariant_under_exchange(mixed) and not odd_under_exchange(mixed))

    rho = packet_density()
    mass = 2.75
    active_ident = source_from_variation(ident, mass, rho)
    active_spectator = source_from_variation(spectator, mass, rho)
    active_gamma = source_from_variation(gamma, mass, rho)
    target = mass * np.array([1.0, -1.0])
    check(
        "orientation-even scalar source gives only [+,+]",
        np.allclose(active_ident, mass * np.array([1.0, 1.0]), atol=1.0e-9),
        f"active={np.round(active_ident, 6)}",
    )
    check(
        "spectator eta label gives no active source",
        np.allclose(active_spectator, np.array([0.0, 0.0]), atol=1.0e-9),
        f"active={np.round(active_spectator, 6)}",
    )
    check(
        "Gamma source-line coefficient gives exactly [+,-]",
        np.allclose(active_gamma, target, atol=1.0e-9),
        f"active={np.round(active_gamma, 6)}",
    )

    residual_even, weights_even = least_squares_residual([ident, spectator], target)
    check(
        "even/spectator source basis cannot span signed source",
        residual_even > mass,
        f"residual={residual_even:.3e}, weights={np.round(weights_even, 3)}",
    )
    residual_with_gamma, weights_with_gamma = least_squares_residual([ident, spectator, gamma], target)
    check(
        "adding the odd Gamma coefficient spans the signed source uniquely",
        residual_with_gamma < TOL
        and abs(weights_with_gamma[0]) < TOL
        and abs(weights_with_gamma[2] - mass) < TOL,
        f"weights={np.round(weights_with_gamma, 3)}",
    )

    table_even_even, reads_even_even = locked_table(ident, ident)
    table_gamma_even, reads_gamma_even = locked_table(gamma, ident)
    table_even_gamma, reads_even_gamma = locked_table(ident, gamma)
    table_gamma_gamma, reads_gamma_gamma = locked_table(gamma, gamma)
    check("identity source/identity response fails locked table", not table_even_even, reads_even_even)
    check("Gamma source only fails action-reaction locked table", not table_gamma_even and "UNBALANCED" in reads_gamma_even, reads_gamma_even)
    check("Gamma response only fails action-reaction locked table", not table_even_gamma and "UNBALANCED" in reads_even_gamma, reads_even_gamma)
    check("Gamma source plus Gamma response gives locked table", table_gamma_gamma, reads_gamma_gamma)

    print()
    print("INTERPRETATION")
    print("  The product grading supplies the odd label carrier Gamma.")
    print("  It does not by itself authorize the scalar action to use the odd")
    print("  coefficient. In the finite linear source class, the desired signed")
    print("  source is exactly the Gamma coefficient, so the remaining premise is")
    print("  the active source-line/section rule, not a missing sign label.")
    print()
    print(f"SUMMARY: PASS={PASS} FAIL={FAIL}")
    print("FINAL_TAG: PRODUCT_GRADING_SOURCE_ACTIVATION_OBSTRUCTION")
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
