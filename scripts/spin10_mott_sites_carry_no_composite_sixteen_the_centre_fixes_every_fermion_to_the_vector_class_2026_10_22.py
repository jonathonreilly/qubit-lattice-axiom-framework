def dense_majoranas(nm):
    """Majoranas g_{2p}=c+c^dag, g_{2p+1}=i(c^dag-c); mode 0 is the most significant bit."""
    c1 = sp.csr_matrix(np.array([[0.0, 1.0], [0.0, 0.0]]))  # |1> -> |0>
    Z = sp.csr_matrix(np.diag([1.0, -1.0]))
    I2 = sp.identity(2, format="csr")
    gs = []
    for p in range(nm):
        op = sp.identity(1, format="csr")
        for q in range(nm):
            op = sp.kron(op, Z if q < p else (c1 if q == p else I2), format="csr")
        c = op.astype(complex)
        cd = c.conj().T
        gs.append((c + cd).tocsr())
        gs.append((1j * (cd - c)).tocsr())
    return gs


def gens(gs_site_list):
    """Total Spin(10) generators summed over sites; gs_site_list[s] = 10 Majoranas of site s."""
    out = []
    for a in range(10):
        for b in range(a + 1, 10):
            out.append(sum(0.5j * (g[a] @ g[b]) for g in gs_site_list))
    return out


def nrm(A):
    A = A.tocoo() if sp.issparse(A) else sp.coo_matrix(A)
    return float(np.sqrt(np.sum(np.abs(A.data) ** 2))) if A.nnz else 0.0


