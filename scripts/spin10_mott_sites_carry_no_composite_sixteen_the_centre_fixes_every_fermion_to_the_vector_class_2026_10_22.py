def trans(basis, n):
    """site translation s -> s+1 on a ring, with the fermion sign of moving site n-1 to 0."""
    x = basis
    last = (x >> (5 * (n - 1))) & 31
    rest = x & ((1 << (5 * (n - 1))) - 1)
    y = (rest << 5) | last
    nl = pc(last)
    sg = (-1.0) ** (nl * (pc(x) - nl))
    rows = np.searchsorted(basis, y)
    d = len(basis)
    return sp.csr_matrix((sg, (rows, np.arange(d))), shape=(d, d))


def kband(H, T, d, kk):
    """lowest eigenpair of H restricted to translation eigenvalue exp(i kk)."""
    ph = np.exp(-1j * kk)
    T2 = T @ T
    T3 = T2 @ T

    def Pk(x):
        return (x + ph * (T @ x) + ph ** 2 * (T2 @ x) + ph ** 3 * (T3 @ x)) / 4

    def mv(x):
        y = Pk(x)
        return Pk(H @ y) + 10.0 * (x - y)

    L = sla.LinearOperator((d, d), matvec=mv, dtype=complex)
    v0 = Pk(np.random.rand(d) + 1j * np.random.rand(d))
    w, v = sla.eigsh(L, k=1, which="SA", v0=v0, tol=1e-10)
    return w[0], v[:, 0]


