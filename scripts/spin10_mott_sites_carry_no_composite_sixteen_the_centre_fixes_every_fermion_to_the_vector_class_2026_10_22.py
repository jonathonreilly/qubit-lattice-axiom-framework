def residues(rg, tt):
    """spectral weight sum_s |<odd_i| c^dag_{s,1} |vac>|^2 for the six lowest odd states."""
    be_, Ke_, He_ = model(4, (2, 2, 2, 2, 2), rg, U, tt)
    bo_, Ko_, Ho_ = model(4, (3, 2, 2, 2, 2), rg, U, tt)
    g0_ = lowest(He_, 1)[1][:, 0]
    wo_, vo_ = lowest(Ho_, 6)
    Co_ = casimir(bo_, 4, Ko_)
    zs = []
    for s_ in range(4):
        p = 5 * s_
        m = ((be_ >> p) & 1) == 0
        xs = be_[m]
        vec = np.zeros(len(bo_), complex)
        vec[np.searchsorted(bo_, xs | (1 << p))] = (-1.0) ** pc(xs & ((1 << p) - 1)) * g0_[m]
        zs.append(vec)
    out = []
    for i in range(6):
        out.append((wo_[i] - U, name(cas_of(Co_, vo_[:, i])[0]),
                    sum(abs(np.vdot(vo_[:, i], z)) ** 2 for z in zs)))
    return out


