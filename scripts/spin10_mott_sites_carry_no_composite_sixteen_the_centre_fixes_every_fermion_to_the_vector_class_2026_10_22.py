# ---------------------------------------------------------------- sector engine
def pc(x):
    return np.bitwise_count(x).astype(np.int64)


def sector_basis(n, Ns):
    per = []
    for a, Na in enumerate(Ns):
        per.append([sum(1 << (5 * s + a) for s in S) for S in itertools.combinations(range(n), Na)])
    b = np.array(sorted(sum(t) for t in itertools.product(*per)), dtype=np.int64)
    return b


def hop(basis, p, q):
    """matrix of c_p^dag c_q (p != q) in a sector basis (sector preserved)."""
    x = basis
    m = ((x >> q) & 1 == 1) & ((x >> p) & 1 == 0)
    xs = x[m]
    s1 = pc(xs & ((1 << q) - 1))
    x1 = xs ^ (1 << q)
    s2 = pc(x1 & ((1 << p) - 1))
    y = x1 | (1 << p)
    rows = np.searchsorted(basis, y)
    cols = np.nonzero(m)[0]
    vals = (-1.0) ** (s1 + s2)
    d = len(basis)
    return sp.csr_matrix((vals, (rows, cols)), shape=(d, d))


def Kst(basis, s, t):
    d = len(basis)
    A = sp.csr_matrix((d, d), dtype=complex)
    for a in range(5):
        h = hop(basis, 5 * s + a, 5 * t + a)
        A = A + 2j * (h - h.T)
    return A


def podd(basis, s):
    return sp.diags((pc((basis >> (5 * s)) & 31) % 2).astype(float))


def casimir(basis, n, Ks):
    d = len(basis)
    C = (45.0 * n / 4) * sp.identity(d, dtype=complex, format="csr")
    for (s, t), A in Ks.items():
        C = C + (10 * sp.identity(d, format="csr") - A @ A) / 4
    return C


def model(n, Ns, bonds, U, t):
    b = sector_basis(n, Ns)
    Ks = {(s, u): Kst(b, s, u) for s in range(n) for u in range(s + 1, n)}
    H = U * sum(podd(b, s) for s in range(n)) + (t / 2) * sum(Ks[e] if e[0] < e[1] else -Ks[(e[1], e[0])]
                                                           for e in bonds)
    return b, Ks, H.tocsr()


def lowest(H, k=4):
    d = H.shape[0]
    if d <= 1200:
        w, v = np.linalg.eigh(H.toarray())
        return w[:k], v[:, :k]
    w, v = sla.eigsh(H, k=k, which="SA", tol=1e-11)
    o = np.argsort(w)
    return w[o], v[:, o]


def cas_of(C, v):
    Cv = C @ v
    m = float(np.real(np.vdot(v, Cv)))
    return m, float(np.linalg.norm(Cv - m * v))


