def _orth(rows, tol=1e-9):
    """Orthonormal row basis of the row span (SVD)."""
    u_, s_, vt_ = np.linalg.svd(rows)
    return vt_[: int(np.sum(s_ > tol))]


def algebra_span_dim(gens, d, max_iter=40):
    """(dim, basis) of the unital *-algebra generated by gens in M_d(C).

    Closes the linear span of words in {g, g^dagger} (starting from I)
    under right multiplication by the generator set until stable.
    """
    gset = []
    for g in gens:
        gc = np.asarray(g, dtype=complex)
        gset.append(gc)
        gset.append(gc.conj().T)
    basis = _orth(np.eye(d, dtype=complex).flatten()[None, :])
    for _ in range(max_iter):
        cur = [basis[i].reshape(d, d) for i in range(basis.shape[0])]
        new = [(m @ g).flatten() for m in cur for g in gset]
        nb = _orth(np.vstack([basis] + [n[None, :] for n in new]))
        if nb.shape[0] == basis.shape[0]:
            return basis.shape[0], basis
        basis = nb
    raise RuntimeError("algebra closure did not stabilize")


def commutant_dim(gens, d):
    """Dim of {K in M_d(C) : [K, g] = [K, g^dagger] = 0 for all g}."""
    rows = []
    for g in gens:
        gc = np.asarray(g, dtype=complex)
        for m in (gc, gc.conj().T):
            rows.append(np.kron(m, np.eye(d)) - np.kron(np.eye(d), m.T))
    A = np.vstack(rows)
    s_ = np.linalg.svd(A, compute_uv=False)
    return d * d - int(np.sum(s_ > 1e-9))


def jw_modes(n):
    """Jordan-Wigner fermion modes c_1..c_n as 2^n x 2^n matrices."""
