def Tspin(x):
    """T(x) = sigma_1^{x1} sigma_2^{x2} sigma_3^{x3}."""
    m = I2.copy()
    for p, s in zip(x, SIG):
        for _ in range(p % 2):
            m = m @ s
    return m


