def algebra_dim(gens):
    """Dimension of the unital algebra generated by 3x3 matrices.

    Iteratively closes the linear span under multiplication until the
    span dimension is stable, then returns it.
    """
    basis = [np.eye(3, dtype=complex)] + [g.astype(complex) for g in gens]
    dim = np.linalg.matrix_rank(
        np.array([m.flatten() for m in basis]), tol=1e-9)
    while True:
        prods = [x @ y for x in basis for y in basis]
        stack = np.array([m.flatten() for m in basis + prods])
        u_, s_, vt_ = np.linalg.svd(stack)
        new_dim = int(np.sum(s_ > 1e-9))
        if new_dim == dim:
            return dim
        basis = [vt_[i].reshape(3, 3) for i in range(new_dim)]
        dim = new_dim


