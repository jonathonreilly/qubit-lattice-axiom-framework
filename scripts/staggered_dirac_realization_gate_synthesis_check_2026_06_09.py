def commutant_dim(gens):
    """Dim of {K : [K, g] = 0 for all g} inside M_3(C)."""
    rows = []
    for g in gens:
        gc = g.astype(complex)
        Lop = np.kron(gc, np.eye(3)) - np.kron(np.eye(3), gc.T)
        rows.append(Lop)
    A = np.vstack(rows)
    s_ = np.linalg.svd(A, compute_uv=False)
    return 9 - int(np.sum(s_ > 1e-9))


