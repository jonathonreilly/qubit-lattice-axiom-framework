def build_staggered(eta_fun, apbc=False):
    D = np.zeros((N, N))
    for x in sites():
        for mu, e in enumerate(EMU):
            xp = tuple(x[k] + e[k] for k in range(3))
            xm = tuple(x[k] - e[k] for k in range(3))
            sp = -1.0 if (apbc and x[mu] == L - 1) else 1.0   # wrap x -> x+mu
            sm = -1.0 if (apbc and x[mu] == 0) else 1.0       # wrap x -> x-mu
            D[idx(*x), idx(*xp)] += 0.5 * eta_fun(x, mu) * sp
            D[idx(*x), idx(*xm)] -= 0.5 * eta_fun(x, mu) * sm
    return D


