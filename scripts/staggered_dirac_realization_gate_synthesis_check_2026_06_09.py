def cocycle_holds(eta_fun):
    """Clifford -1 plaquette cocycle for a phase field."""
    n_checked = 0
    for x in sites():
        for mu in range(3):
            for nu in range(mu + 1, 3):
                xp_mu = tuple(x[k] + EMU[mu][k] for k in range(3))
                xp_nu = tuple(x[k] + EMU[nu][k] for k in range(3))
                lhs = eta_fun(xp_mu, nu) * eta_fun(x, mu)
                rhs = -eta_fun(xp_nu, mu) * eta_fun(x, nu)
                n_checked += 1
                if lhs != rhs:
                    return False, n_checked
    return True, n_checked


