def test_b1_z3_body_diagonal_subgroup():
    """Z₃ generated by C₃ rotation about (1,1,1) is closed, order 3, det = +1."""
    # Body-diagonal C₃: (x,y,z) → (y,z,x), so R[i,j] = δ_{i, σ(j)} where σ = (1 2 3)
    R = np.array([[0, 1, 0],
                  [0, 0, 1],
                  [1, 0, 0]], dtype=int)
    R2 = R @ R
    R3 = R @ R @ R
    # det(R) = +1
    report("B1: det(R) = +1 (proper rotation, C₃ body-diagonal)",
           int(round(np.linalg.det(R))) == 1)
    # R³ = I
    report("B1: R³ = I (order 3)",
           np.array_equal(R3, np.eye(3, dtype=int)))
    # {I, R, R²} closed under composition
    elements = [np.eye(3, dtype=int), R, R2]
    closure = []
    for A in elements:
        for B in elements:
            AB = A @ B
            in_set = any(np.array_equal(AB, X) for X in elements)
            closure.append(in_set)
    report("B1: {I, R, R²} closed under composition (subgroup)",
           all(closure))
    # R cyclically permutes axes
    e_x = np.array([1, 0, 0])
    e_y = np.array([0, 1, 0])
    e_z = np.array([0, 0, 1])
    report("B1: R acts as (x → z, y → x, z → y)",
           np.array_equal(R @ e_x, e_z) and
           np.array_equal(R @ e_y, e_x) and
           np.array_equal(R @ e_z, e_y))


