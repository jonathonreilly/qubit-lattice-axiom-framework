def test_composite_closure():
    """Composite verification: on a sample RP-positive Z_Q distribution,
    the unique minimum of F(θ) = -log|Z(θ)| over the reduced BZ [0, π/3]
    is at θ = 0."""

    def Z_of_theta(Z_Q, Q_values, theta):
        return np.sum(Z_Q * np.exp(1j * theta * Q_values))

    Q_values = np.arange(-10, 11)
    # Mix of Gaussian + noise for realism
