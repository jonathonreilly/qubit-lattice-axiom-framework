# B4: RP-positivity + triangle inequality → strict minimum at θ = 0
# ----------------------------------------------------------------------


def test_b4_unique_min_at_zero():
    """For random Z_Q ≥ 0 distributions on topological sectors, |Z(θ)|
    achieves its strict global maximum at θ = 0 (hence F(θ) = -log|Z(θ)|
    achieves its strict minimum at θ = 0).

    Test multiple distribution shapes: Gaussian-peaked, uniform, sparse.
    """

    def Z_of_theta(Z_Q, Q_values, theta):
        return np.sum(Z_Q * np.exp(1j * theta * Q_values))

    Q_values = np.arange(-10, 11)  # topological charges Q ∈ {-10, ..., 10}
    theta_grid = np.linspace(0, 2 * np.pi, 1001)[:-1]

    all_ok = True
    for shape_name, Z_Q_func in [
        ("Gaussian-peaked", lambda: np.exp(-(Q_values**2) / 4.0)),
        ("uniform", lambda: np.ones_like(Q_values, dtype=float)),
        ("sparse-positive", lambda: np.array([np.exp(-abs(q) / 2.0) * RNG.uniform(0.5, 1.5)
                                              for q in Q_values])),
    ]:
        Z_Q = Z_Q_func()
        # Sanity: Z_Q ≥ 0 (RP-positivity)
        if not np.all(Z_Q >= 0):
            all_ok = False
            report(f"B4 ({shape_name}): Z_Q ≥ 0 sanity", False)
            continue
        # |Z(θ)| over the BZ
        Z_vals = np.array([abs(Z_of_theta(Z_Q, Q_values, t)) for t in theta_grid])
        # Global max at θ = 0?
        argmax_idx = np.argmax(Z_vals)
        argmax_theta = theta_grid[argmax_idx]
        Z_at_zero = abs(Z_of_theta(Z_Q, Q_values, 0.0))
        ok = abs(argmax_theta) < 1e-3 and Z_vals[argmax_idx] <= Z_at_zero + 1e-9
        report(f"B4 ({shape_name}): |Z(θ)| max at θ = 0", ok,
               detail=f"argmax θ = {argmax_theta:.4f}, |Z(0)| = {Z_at_zero:.4f}")
        if not ok:
            all_ok = False
    return all_ok


