    # Reduced BZ
    theta_reduced = np.linspace(0, np.pi / 3, 501)
    Z_vals = np.array([abs(Z_of_theta(Z_Q, Q_values, t)) for t in theta_reduced])
    F_vals = -np.log(Z_vals)  # free energy
    argmin_idx = np.argmin(F_vals)
    argmin_theta = theta_reduced[argmin_idx]
    report("Composite: F(θ) min at θ = 0 on reduced BZ [0, π/3]",
           argmin_theta < 0.01,
           detail=f"argmin θ = {argmin_theta:.6f}, F(0) = {F_vals[0]:.4f}")

    # Show F(π/3) > F(0) (i.e., the boundary is NOT a minimum)
    F_at_boundary = -np.log(abs(Z_of_theta(Z_Q, Q_values, np.pi / 3)))
    F_at_zero = -np.log(abs(Z_of_theta(Z_Q, Q_values, 0.0)))
    report("Composite: F(π/3) > F(0) (boundary not preferred)",
           F_at_boundary > F_at_zero,
           detail=f"F(0) = {F_at_zero:.4f}, F(π/3) = {F_at_boundary:.4f}")


