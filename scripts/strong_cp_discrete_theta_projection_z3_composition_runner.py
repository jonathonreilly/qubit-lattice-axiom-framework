def test_b6_reduced_brillouin():
    """After Z₃ gauging: θ ∈ [-π/3, π/3]. After Z₂ orbifold (θ ∼ -θ):
    θ ∈ [0, π/3]. This range contains θ = 0 but NOT θ = π."""
    reduced_zone = (0, np.pi / 3)
    contains_zero = reduced_zone[0] <= 0 <= reduced_zone[1]
    contains_pi = reduced_zone[0] <= np.pi <= reduced_zone[1]
    report("B6: reduced BZ [0, π/3] contains θ = 0",
           contains_zero, detail=f"range = [{reduced_zone[0]:.4f}, {reduced_zone[1]:.4f}]")
    report("B6: reduced BZ [0, π/3] excludes θ = π (Z₂-CP point ELIMINATED)",
           not contains_pi, detail=f"π = {np.pi:.4f} > π/3 = {np.pi/3:.4f}")


def test_b6_uniqueness_on_reduced_zone():
    """On the reduced BZ [0, π/3], the only CP-symmetric point (fixed
    under θ ∼ -θ mod 2π/3) is θ = 0."""
    # CP-fixed points satisfy θ ≡ -θ (mod 2π/3)
    # ⟹ 2θ ≡ 0 (mod 2π/3) ⟹ θ ∈ {0, π/3, 2π/3, ...}
    # In [0, π/3]: only θ = 0 (the boundary π/3 is excluded by half-open convention)
    cp_fixed = []
    grid = np.linspace(0, np.pi / 3, 1001)
    for t in grid:
        if abs((2 * t) % (2 * np.pi / 3)) < 1e-6 or \
           abs((2 * t) % (2 * np.pi / 3) - 2 * np.pi / 3) < 1e-6:
            cp_fixed.append(t)
    # Filter for unique modulo small tolerance
    cp_fixed_unique = []
    for t in cp_fixed:
        if not any(abs(t - u) < 1e-3 for u in cp_fixed_unique):
            cp_fixed_unique.append(t)
    report("B6: on reduced BZ [0, π/3], CP-fixed points = {0, ε(boundary)}",
           0.0 in cp_fixed_unique and len(cp_fixed_unique) <= 2,
           detail=f"found {len(cp_fixed_unique)} cp-fixed points: {[round(t, 4) for t in cp_fixed_unique]}")


