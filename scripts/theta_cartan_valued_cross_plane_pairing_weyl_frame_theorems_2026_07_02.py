print("Section B: Cartan-valued cup pairing on T^4")

D = 4
L = 2


def cells(k):
    out = []
    sites = [tuple(s) for s in np.ndindex(*(L,) * D)]
    for S in combinations(range(D), k):
        for x in sites:
            out.append((x, S))
    return out


CI = {k: (cells(k), {c: i for i, c in enumerate(cells(k))})
      for k in range(0, D + 1)}


def shift(x, mu):
    y = list(x)
    y[mu] = (y[mu] + 1) % L
    return tuple(y)


def d_matrix(k):
    _, ik = CI[k]
    _, ik1 = CI[k + 1]
    M = np.zeros((len(ik1), len(ik)), dtype=np.int64)
    for (x, S), r in ik1.items():
        for j, mu in enumerate(S):
            Srem = tuple(m for m in S if m != mu)
            sgn = (-1) ** j
            M[r, ik[(shift(x, mu), Srem)]] += sgn
            M[r, ik[(x, Srem)]] -= sgn
    return M


DM = {k: d_matrix(k) for k in range(0, D)}


def cup22(a, b):
    _, ik4 = CI[4]
    _, ik2 = CI[2]
    out = np.zeros(len(ik4), dtype=np.int64)
    for (x, S), r in ik4.items():
        tot = 0
        for S1 in combinations(S, 2):
            S2 = tuple(m for m in S if m not in S1)
            perm = list(S1) + list(S2)
            inv = sum(1 for i in range(4) for j in range(i + 1, 4)
                      if perm[i] > perm[j])
            y = x
            for mu in S1:
                y = shift(y, mu)
            tot += ((-1) ** inv) * int(a[ik2[(x, S1)]]) * int(b[ik2[(y, S2)]])
        out[r] = tot
    return out


PLANES = list(combinations(range(D), 2))


def flux_rep(mu, nu):
    v = np.zeros(len(CI[2][0]), dtype=np.int64)
    for (x, S), i in CI[2][1].items():
        if S == (mu, nu) and x[mu] == 0 and x[nu] == 0:
            v[i] = 1
    return v


REPS = {pl: flux_rep(*pl) for pl in PLANES}


def qg(n1, n2):
    """Q_G for the rank-2 cochain with weight-coordinate components n1, n2:
    (1/2) sum_ab G_ab n^a u n^b, exact rational."""
    c11 = int(np.sum(cup22(n1, n1)))
    c12 = int(np.sum(cup22(n1, n2)))
    c21 = int(np.sum(cup22(n2, n1)))
    c22 = int(np.sum(cup22(n2, n2)))
    return (G[0][0] * c11 + G[0][1] * (c12 + c21) + G[1][1] * c22) / 2


def flux_cochain(assign):
    """assign: plane -> weight-coordinate pair (a, b). Returns (n1, n2)."""
    n1 = np.zeros(len(CI[2][0]), dtype=np.int64)
    n2 = np.zeros(len(CI[2][0]), dtype=np.int64)
    for pl, (a, b) in assign.items():
        n1 = n1 + a * REPS[pl]
        n2 = n2 + b * REPS[pl]
    return n1, n2


def q_flux(assign):
    """Gram-intersection of the flux classes directly:
    Q = sum over complementary pairs, with block-3 signs."""
    comp = {(0, 1): (2, 3), (0, 2): (1, 3), (0, 3): (1, 2)}
    sgn = {(0, 1): 1, (0, 2): -1, (0, 3): 1}
    tot = Fraction(0)
    zero = (0, 0)
    for p, pc in comp.items():
        tot += sgn[p] * pair(assign.get(p, zero), assign.get(pc, zero))
    return tot


