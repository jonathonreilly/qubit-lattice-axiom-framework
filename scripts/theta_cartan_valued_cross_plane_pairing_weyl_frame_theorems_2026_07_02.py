def reflect2(v, axis=0):
    out = np.zeros_like(v)
    for (x, S), i in CI[2][1].items():
        y = list(x)
        y[axis] = (-y[axis]) % L
        sgn = 1
        if axis in S:
            y[axis] = (y[axis] - 1) % L
            sgn = -1
        out[i] = sgn * v[CI[2][1][(tuple(y), S)]]
    return out


